-- =============================================================================
-- ORB-07 — diagnóstico somente leitura das classificações do universo elegível
--
-- Não alimenta o envio. Serve para a simulação pré-ativação demonstrar, por
-- classificação, quantas OBs seriam aceitas ou rejeitadas pela regra final.
-- COUNT(DISTINCT) neutraliza eventual fan-out dos vínculos comerciais.
-- =============================================================================
WITH CLASSIFICACAO_OB AS (
    SELECT OBF.NUMERO_OB AS NR_OB,
           MAX(REC.CODIGO_CLASSIFICACAO)
               KEEP (DENSE_RANK LAST ORDER BY REC.CODIGO_CLASSIFICACAO)
               AS CD_CLASSIFICACAO_COR,
           MAX(TRIM(CCC.DESCRICAO))
               KEEP (DENSE_RANK LAST ORDER BY REC.CODIGO_CLASSIFICACAO)
               AS DS_CLASSIFICACAO_COR,
           COUNT(DISTINCT REC.CODIGO_CLASSIFICACAO) AS QTD_CLASSIFICACOES_COR
      -- Tabelas da antiga VW_EXC_OB_PROD_CLASS_COR, com os mesmos filtros e junções
      -- internas (status da OB pelo enumerado TOBSTATUS, como VW_ENU_STATUS_OB).
      FROM SGTPRD.OB_FASES OBF
     INNER JOIN SGTPRD.CADASTRO_RECEITAS REC
        ON REC.PROCESSOINDUSTRIAL = OBF.CODIGO_FASE || OBF.TIPO_PROCESSO
       AND TRIM(REC.CODCOR) = TRIM(OBF.CODIGO_COR_DESENHO)
       AND REC.ESPECIFICACAO_PRODUT = OBF.ESPECIFICACAO_PRODUT
       AND REC.PROCESSO_ESPECIFICO = OBF.PROCESSO_ESPECIFICO
     INNER JOIN SGTPRD.CLASSIFICACAO_COR CCC
        ON CCC.CODIGO_CLASSIFICACAO = REC.CODIGO_CLASSIFICACAO
     INNER JOIN SGTPRD.OB_PRODUTO OBP
        ON OBP.NUMERO_OB = OBF.NUMERO_OB
     INNER JOIN SGTPRD.OB OBE
        ON OBE.NUMERO_OB = OBF.NUMERO_OB
     INNER JOIN SGTPRD.ITENS_ESTOQUE ITE
        ON ITE.CODIGO_REDUZIDO = OBE.CODIGO_REDUZIDO
     INNER JOIN SGTPRD.XX2_ENUMERATES ENU
        ON ENU.NAME LIKE 'TOBSTATUS%'
     INNER JOIN SGTPRD.XX2_ENUMITEM ENI
        ON ENI.IDENUMERATE = ENU.ID
       AND ENI.SEQUENCE = OBE.STATUS
     WHERE OBF.CODIGO_FASE = 40
       AND OBE.STATUS <> 0
       AND NOT EXISTS (
           SELECT 1
             FROM SGTPRD.OB_FASES OBF2
            WHERE OBF2.NUMERO_OB = OBF.NUMERO_OB
              AND OBF2.CODIGO_FASE = 10
              AND OBF2.STATUS IN (3, 4)
       )
     GROUP BY OBF.NUMERO_OB
)
SELECT CLS.CD_CLASSIFICACAO_COR,
       NVL(CLS.DS_CLASSIFICACAO_COR, 'SEM CLASSIFICACAO')
           AS DS_CLASSIFICACAO_COR,
       NVL(CLS.QTD_CLASSIFICACOES_COR, 0) AS QTD_CLASSIFICACOES_COR,
       CASE
           WHEN CLS.CD_CLASSIFICACAO_COR IN (6, 9)
            AND CLS.QTD_CLASSIFICACOES_COR = 1
           THEN 'ACEITA'
           ELSE 'REJEITA'
       END AS DECISAO,
       COUNT(DISTINCT OB.NUMERO_OB) AS TOTAL_OBS
  FROM SGTPRD.OB OB
 INNER JOIN SGTPRD.PEDPRODUCAOOB PPOB
    ON PPOB.NUMEROOB = OB.NUMERO_OB
  LEFT JOIN CLASSIFICACAO_OB CLS
    ON CLS.NR_OB = OB.NUMERO_OB
  LEFT JOIN SGTPRD.OFORDENS OFO
    ON OFO.NUMEROPEDPRODUCAO = PPOB.NUMERO
   AND OFO.REDUZIDO = PPOB.REDUZIDO
  LEFT JOIN SGTPRD.OFPEDIDO OFP
    ON OFP.NUMEROOF = OFO.NUMEROOF
   AND OFP.NIVEL = OFO.NIVEL
   AND OFP.REDUZIDO = OFO.REDUZIDO
   AND OFP.QUANTIDADE_ATUAL <> 0
  LEFT JOIN SGTPRD.ITENSPEDIDOQTDES IPQ
    ON IPQ.IDITENSPEDIDOQTDES = OFP.IDITENSPEDIDOQTDES
  LEFT JOIN SGTPRD.ITENSPEDIDOGRADE IPG
    ON IPG.IDITENSPEDIDOGRADE = IPQ.IDITEMPEDGRADE
  LEFT JOIN SGTPRD.ITENSPEDIDOCOMERCIAL IPC
    ON IPC.PEDIDO = IPG.PEDIDO
   AND IPC.ITEMPEDIDO = IPG.ITEMPEDIDO
  LEFT JOIN SGTPRD.PEDIDOCOMERCIAL PED
    ON PED.PEDIDO = IPC.PEDIDO
 WHERE OB.STATUS = 1
   AND PPOB.OBMONTADA = '0'
   AND (
        PED.PEDIDOCLIENTE IS NULL
     OR (PED.PEDIDOCLIENTE NOT LIKE '%R' AND PED.PEDIDOCLIENTE NOT LIKE '%S')
   )
 GROUP BY CLS.CD_CLASSIFICACAO_COR,
          NVL(CLS.DS_CLASSIFICACAO_COR, 'SEM CLASSIFICACAO'),
          NVL(CLS.QTD_CLASSIFICACOES_COR, 0),
          CASE
              WHEN CLS.CD_CLASSIFICACAO_COR IN (6, 9)
               AND CLS.QTD_CLASSIFICACOES_COR = 1
              THEN 'ACEITA'
              ELSE 'REJEITA'
          END
 ORDER BY DECISAO, CLS.CD_CLASSIFICACAO_COR NULLS LAST
