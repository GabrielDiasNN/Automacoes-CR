WITH
    TINGIMENTO_TEMPOS AS (
        SELECT
            UPO.NUMEROORDEMREAL AS NUMERO_OB,
            MAX(UNP.DTTEMPOINICIAL) AS INICIO_TING,
            MAX(UNP.DTTEMPOFINAL) AS FINAL_TING
        FROM SGTPRD.UP_ORDEM_MVTO UPO
        JOIN SGTPRD.UNIDADE_PROGRAMACAO UNP ON UPO.NUMEROUP = UNP.NUMEROUP
        WHERE UNP.TIPO_MAQUINA = 19 
        AND UNP.EXCLUIDA = 0 
        GROUP BY UPO.NUMEROORDEMREAL
    ),
    MAQUINAS_TINGIMENTO AS (
        SELECT 
            NUMERO_OB,
            MAX(LTRIM(NUMERO_MAQUINA, '0')) AS MQ_TING
        FROM SGTPRD.OB_FASES 
        WHERE CODIGO_FASE = 40
        GROUP BY NUMERO_OB
    ),
    -- Fase atual só com tabelas (antes: VW_BNF_FASEATUALOB, que chama
    -- PKGBENF0001.FNC_RETORNA_SEQUENCIA_OB). Regra da função conferida em 17/10/2026
    -- contra a view: menor sequência com status 0, 1, 2 ou 3, senão a última (759 de 759
    -- OBs abertas iguais); OB com status 0 fica na sequência 0; só ordens tipo 0 e 6.
    FASE_ATUAL AS (
        SELECT OB.NUMERO_OB, FAS.STATUS, TRIM(FAS.DESCRICAO_FASE) AS DESCR_FASE
        FROM SGTPRD.OB OB
        LEFT JOIN (
            SELECT NUMERO_OB,
                NVL(MIN(CASE WHEN STATUS IN (0, 1, 2, 3) THEN SEQUENCIA END), MAX(SEQUENCIA)) AS SEQ
            FROM SGTPRD.OB_FASES
            GROUP BY NUMERO_OB
        ) SEQ ON SEQ.NUMERO_OB = OB.NUMERO_OB
        LEFT JOIN (
            SELECT OBX.NUMERO_OB, OBX.SEQUENCIA, OBX.STATUS, FFL.DESCRICAO_FASE
            FROM SGTPRD.OB_FASES OBX
            JOIN SGTPRD.FASES_FLUXO FFL ON FFL.CODIGO_FASE = OBX.CODIGO_FASE
        ) FAS ON FAS.NUMERO_OB = OB.NUMERO_OB
             AND FAS.SEQUENCIA = DECODE(OB.STATUS, 0, 0, SEQ.SEQ)
        WHERE OB.TIPO_ORDEM IN (0, 6)
    ),
    -- Receita pesada só com tabelas (antes: SGTPRD.FNC_ESP_REC_PES, que lê uma view sem
    -- acesso para a conta de leitura): existe item de MOVTO_RECEITA da fase de tingimento
    -- com quantidade pesada. Conferido em 17/10/2026 contra as views que chamam a função
    -- (VW_EXC_QUI_RESER_REC 27 de 27 e VW_ESP_OB_PED_ROM 49 de 49 OBs iguais).
    RECEITA_PESADA AS (
        SELECT OBF.NUMERO_OB,
            MAX(CASE WHEN NVL(M.QUANTIDADEPESADA, 0) > 0 THEN 1 ELSE 0 END) AS PESADA
        FROM SGTPRD.OB_FASES OBF
        JOIN SGTPRD.MOVTO_RECEITA M ON M.NUMEROORDEM = OBF.NUMEROORDEMMOVIMENTO
            AND M.SEQUENCIAFASEOB = OBF.SEQUENCIAORDEMMOVIME
        WHERE OBF.CODIGO_FASE = 40
        GROUP BY OBF.NUMERO_OB
    ),
    DADOS_AGREGADOS AS (
        SELECT
            OBF.NUMERO_OB, M.NUMEROORDEM, OBF.CODIGO_GRUPO, OBP.CODPRO_REDUZIDO,
            MAX(TRIM(OPE.NOME)) AS USUARIO,
            MAX(M.DT_PESAGEM) AS HORARIO_PESADO,
            SUM(M.QUANTIDADEPESADA) AS QUANT_PESADA
        FROM SGTPRD.OB_FASES OBF
        JOIN FASE_ATUAL OB ON OB.NUMERO_OB = OBF.NUMERO_OB
        JOIN SGTPRD.OB_PRODUTO OBP ON OBP.NUMERO_OB = OBF.NUMERO_OB
        JOIN SGTPRD.MOVTO_RECEITA M ON M.NUMEROORDEM = OBF.NUMEROORDEMMOVIMENTO 
            AND M.SEQUENCIAFASEOB = OBF.SEQUENCIAORDEMMOVIME
        LEFT JOIN SGTPRD.OPERADOR OPE ON OPE.IDOPERADOR = M.IDOPE_PESAGEM
        WHERE OBF.CODIGO_FASE = 40 AND OBF.STATUS IN (1, 2, 3)
        GROUP BY OBF.NUMERO_OB, M.NUMEROORDEM, OBF.CODIGO_GRUPO, OBP.CODPRO_REDUZIDO
    )

SELECT /*+ FIRST_ROWS(1000) */
    GRUPO,
    NUMERO_OB,
    PESADA,
    MQ_TING,
    INICIO_TING,
    FINAL_TING,
    ARTIGO,
    REDUZIDO,
    DESCRICAO,
    FASE_ATUAL,
    STATUS_FASE,
    USUARIO,
    HORARIO_PESADO,
    QUANT_PESADA
FROM (
    SELECT
        BASE.CODIGO_GRUPO AS GRUPO, BASE.NUMERO_OB,
        CASE WHEN NVL(PES.PESADA, 0) = 0 THEN 'NAO' ELSE 'SIM' END AS PESADA,
        MT.MQ_TING, TT.INICIO_TING, TT.FINAL_TING,
        ART.CDARTIGOCRU AS ARTIGO, BASE.CODPRO_REDUZIDO AS REDUZIDO,
        TRIM(ITE.DESCRICAO) AS DESCRICAO, FAS.DESCR_FASE AS FASE_ATUAL,
        CASE FAS.STATUS
            WHEN 0 THEN 'PROGRAMADA' WHEN 1 THEN 'EMITIDA'
            WHEN 2 THEN 'PESADA' WHEN 3 THEN 'EM EXECUCAO'
        END AS STATUS_FASE,
        BASE.USUARIO, BASE.HORARIO_PESADO,
        BASE.QUANT_PESADA
    FROM DADOS_AGREGADOS BASE
    LEFT JOIN TINGIMENTO_TEMPOS TT ON TT.NUMERO_OB = BASE.NUMERO_OB
    LEFT JOIN MAQUINAS_TINGIMENTO MT ON MT.NUMERO_OB = BASE.NUMERO_OB
    LEFT JOIN SGTPRD.ENGEITEMESTOARTCRU ART ON ART.CDREDUZIDO = BASE.CODPRO_REDUZIDO
    LEFT JOIN SGTPRD.ITENS_ESTOQUE ITE ON ITE.CODIGO_REDUZIDO = BASE.CODPRO_REDUZIDO
    LEFT JOIN FASE_ATUAL FAS ON FAS.NUMERO_OB = BASE.NUMERO_OB
    LEFT JOIN RECEITA_PESADA PES ON PES.NUMERO_OB = BASE.NUMERO_OB
)
WHERE PESADA = 'NAO'
ORDER BY INICIO_TING NULLS LAST, NUMERO_OB ASC
