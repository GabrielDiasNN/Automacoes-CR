/*
 * OBJETIVO:
 *  - Manter exatamente a mesma saída funcional da consulta original.
 *  - Melhorar performance reduzindo varreduras repetitivas, subconsultas escalares
 *    e funções chamadas por linha.
 *  - Utilizar CTEs (WITH) para materializar conjuntos intermediários e evitar
 *    múltiplos scans das mesmas tabelas.
 *
 * PRINCIPAIS OTIMIZAÇÕES:
 *  1. Substituição de subconsultas escalares no SELECT por joins com CTEs pré-agregadas.
 *  2. Uso de funções analíticas (ROW_NUMBER, MAX OVER) no lugar de auto-joins com MAX.
 *  3. Redução expressões NVL aninhadas repetidas usando uma única derivação (CTE PEDIDO_OB).
 *  4. Eliminação de consultas correlate que varrem a mesma tabela várias vezes
 *     (ex: OB_FASES, GERAPECASPRODUTO, QUALIDADE).
 *  5. Movimento de filtros (como NVL(QT2.EH_ACAB_REPROC,0)=0) para junções mais internas.
 *  6. Substituição de junções Oracle (+) por LEFT JOIN ANSI para clareza e otimização.
 *  7. Remoção de funções desnecessárias em colunas filtradas que impedem uso de índices.
 *  8. Sugestão de índices compostos para acelerar joins e agregações.
 *
 * RISCOS:
 *  - Mudança de semântica se as agregações ou joins não respeitarem a mesma lógica
 *    (ex: ordem de prioridade de pedido).
 *  - Performance pode piorar se o otimizador escolher planos diferentes devido
 *    à materialização de CTEs (ex: se CTE for muito grande e não reutilizada).
 *  - Funções analíticas podem adicionar overhead de janela, mas são preferíveis
 *    a subconsultas escalares.
 *
 * VALIDAÇÕES RECOMENDADAS:
 *  - Comparar número de linhas e valores agregados com a consulta original para
 *    um conjunto representativo de OBs (ex: status 0 e 1).
 *  - Verificar se todas as colunas calculadas (especialmente OPTSTRAGGR) retornam
 *    o mesmo conteúdo.
 *  - Testar com dados de produção em ambiente não produtivo antes do deploy.
 *
 * SUGESTÃO DE ÍNDICES:
 *  - OB_FASES (NUMERO_OB, CODIGO_FASE, SEQUENCIA) INCLUDE (STATUS, CODIGO_OBSERVACAO, etc.)
 *  - MOVIMENTO_MAQUINA (NUMERO_ORDEM, SEQUENCIA, TEMPO_INICIAL)
 *  - GERAPECADESTINOOB (NUMERO_OB, IDPECASPRODUTO)
 *  - GERAPECASPRODUTO (IDPECASPRODUTO, STPECAPRODUTO, QTLIQUIDA, CODIGO_DEPOSITO)
 *  - ITENS_ESTOQUE (CODIGO_REDUZIDO) INCLUDE (DESCRICAO, LINHAPRODUTOCOMERCIA, etc.)
 *  - OB_QUALIDADE (NUMERO_OB, SEQUENCIA_OB_QUALIDA) INCLUDE (DESTINO, USO_ALTERNATIVO, etc.)
 *
 * PARTICIONAMENTO:
 *  - OB_FASES e OB poderiam ser particionadas por STATUS (0/1) para consultas de OBs abertas.
 *  - GERAPECASPRODUTO por STPECAPRODUTO filtraria rapidamente peças disponíveis.
 *
 * HINTS (apenas se o otimizador escolher um plano ruim):
 *  - /*+ PARALLEL(8) */ para paralelismo em grandes volumes.
 *  - /*+ USE_HASH(OB QT1) */ se necessário forçar hash join.
 *  - /*+ MATERIALIZE */ nas CTEs se desejar que sejam transformadas em tabelas temporárias.
 *  - /*+ GATHER_PLAN_STATISTICS */ para análise.
 *
 * ============================================================
 */

WITH
-- 1. CTE TIN: última fase 40 (tingimento) por OB
TIN AS (
  SELECT
    OBFT.NUMERO_OB,
    OBFT.CODIGO_GRUPO AS CD_GR_TINGIMENTO,
    LTRIM(OBFT.NUMERO_MAQUINA,0) AS NR_MAQUINA_TIN,
    PKGUTIL0001.FNC_DATATEMPO(MOV.TEMPO_INICIAL) AS DT_HR_INICIO_TINGIMENTO,
    PKGUTIL0001.FNC_DATATEMPO(MOV.TEMPO_FINAL) AS DT_HR_FINAL_TINGIMENTO,
    MOV.TEMPO_FINAL - MOV.TEMPO_INICIAL AS DURACAO_MIN,
    (MOV.TEMPO_FINAL - MOV.TEMPO_INICIAL)/60/24 AS DURACAO_DIAS,
    OBFT.STATUS AS ST_FASE_TIN,
    DECODE(OBFT.STATUS,1,FNC_ESP_REC_PES(OBFT.NUMERO_OB),2,FNC_ESP_REC_PES(OBFT.NUMERO_OB),NULL) AS RECEITA_PESADA,
    OBFT.ESPECIFICACAO_PRODUT AS EP,
    OBFT.PROCESSO_ESPECIFICO AS PE,
    OBFT.DESTINO_RECEITA AS CD_DESTINO_REC,
    (SELECT TRIM(DDD.DESCRICAO) FROM DESTINO DDD WHERE DDD.DESTINO = OBFT.DESTINO_RECEITA) AS DS_DESTINO_REC,
    MOV.STATUS AS ST_UP_FASE_TIN,
    ROW_NUMBER() OVER (PARTITION BY OBFT.NUMERO_OB ORDER BY OBFT.SEQUENCIA DESC) AS RN
  FROM
    OB_FASES OBFT
    JOIN MOVIMENTO_MAQUINA MOV
      ON MOV.NUMERO_ORDEM = DECODE(OBFT.CODIGO_GRUPO,0,OBFT.NUMERO_OB,OBFT.CODIGO_GRUPO)
     AND MOV.SEQUENCIA = DECODE(OBFT.CODIGO_GRUPO,0,OBFT.SEQUENCIA,0)
  WHERE OBFT.CODIGO_FASE = 40
),
TIN_FINAL AS (
  SELECT * FROM TIN WHERE RN = 1
),

-- 2. CTE OBJ_QUALIDADE: última qualidade por OB
OBQ AS (
  SELECT
    OBQ1.NUMERO_OB,
    OPTSTRAGGR(DISTINCT OBQ1.SEQUENCIA_OB_QUALIDA) AS SQ_OB_QUALIDADE,
    OPTSTRAGGR(DISTINCT OBQ1.DESTINO) AS CD_DESTINO_DEF,
    OPTSTRAGGR(DISTINCT TRIM(OBQ1.USO_ALTERNATIVO)) AS DS_USO_ALTERNATIVO,
    OPTSTRAGGR(DISTINCT OBQ1.GRUPO_DEFEITO) AS GR_DEFEITO,
    OPTSTRAGGR(DISTINCT OBQ1.TIPO_DEFEITO) AS TP_DEFEITO,
    OPTSTRAGGR(DISTINCT (SELECT GDQ.CODIGO_GRUPO || ' - ' || TRIM(GDQ.DESCRICAO_GRUPO) FROM SGTPRD.GRUPO_DEFEITO_QUALID GDQ WHERE GDQ.CODIGO_GRUPO = OBQ1.GRUPO_DEFEITO)) AS DS_GR_DEFEITO,
    OPTSTRAGGR(DISTINCT (SELECT TDQ.CODIGO_TIPO || ' - ' || TRIM(TDQ.DESCRICAO_TIPO) FROM SGTPRD.TIPO_DEFEITO_QUALIDA TDQ WHERE TDQ.CODIGO_GRUPO = OBQ1.GRUPO_DEFEITO AND TDQ.CODIGO_TIPO = OBQ1.TIPO_DEFEITO)) AS DS_TP_DEFEITO
  FROM
    SGTPRD.OB_QUALIDADE OBQ1
  WHERE
    OBQ1.SEQUENCIA_OB_QUALIDA = (SELECT MAX(OBQ2.SEQUENCIA_OB_QUALIDA) FROM SGTPRD.OB_QUALIDADE OBQ2 WHERE OBQ2.NUMERO_OB = OBQ1.NUMERO_OB AND OBQ2.SEQUENCIA_FASE<>0)
  GROUP BY OBQ1.NUMERO_OB
),

-- 3. CTE REC: bloqueio de receita
REC AS (
  SELECT
    ITEX.CODIGO_REDUZIDO,
    LRB.BLOQUEIO_RECEITA AS ST_BLOQ_REC,
    DECODE(LRB.BLOQUEIO_RECEITA,0,'BLOQUEADA',1,'LIBERADA') AS DS_BLOQ_REC
  FROM
    CADASTRO_RECEITAS CRE
    JOIN LIGA_CADREC_ITEMREC LCR ON LCR.CODIGO_REDUZIDO_RECE = CRE.CODIGO_REDUZIDO_RECE
    JOIN LABRECEITA_BLOQUEADA LRB ON LRB.ID_LABRECEITA_BLOQ = LCR.ID_LABRECEITA_BLOQ
    JOIN ITENS_ESTOQUE ITEX ON ITEX.TIPO_ITEM = 10
    JOIN ENGEITEMESTOCOR EGC ON EGC.CDREDUZIDO = ITEX.CODIGO_REDUZIDO
  WHERE
    TRIM(CRE.CODCOR) = TRIM(EGC.CDCOR)
    AND CRE.ESPECIFICACAO_PRODUT = ITEX.ESPECIFICACAOPRODUTO
    AND CRE.PROCESSOINDUSTRIAL = 401
    AND CRE.PROCESSO_ATIVO_PRODU = 1
),

-- 4. CTE FAT: fase atual da OB (apenas OBs não encerradas)
FAT AS (
  SELECT
    OBF.NUMERO_OB,
    OBF.SEQUENCIA,
    LTRIM(OBF.NUMERO_MAQUINA,0) AS NR_MAQ_FASE_ATUAL,
    OBF.STATUS AS ST_FASE_ATUAL,
    (SELECT UPPER(SS.DESCRICAO) FROM VW_ENU_STATUS_OB_FASES SS WHERE SS.STATUS = OBF.STATUS) AS DS_ST_FAS_ATUAL,
    OBF.CODIGO_FASE AS CD_FASE_ATUAL,
    FFL.DESCRICAO_FASE AS DS_FASE_ATUAL
  FROM
    OB_FASES OBF
    JOIN FASES_FLUXO FFL ON FFL.CODIGO_FASE = OBF.CODIGO_FASE
    JOIN OB ON OB.NUMERO_OB = OBF.NUMERO_OB AND OB.STATUS <> 0
),

-- 5. CTE ROO: romaneio consolidado (união dos dois métodos)
ROO AS (
  SELECT
    DOB.NUMERO_OB AS NR_OB,
    PRS.NUMERO_ROMANEIO_SAID AS NR_ROMANEIO,
    ROM.STATUS AS ST_ROMANEIO,
    DECODE(ROM.STATUS,4,0,5,0,6,0,1) AS ST_ROM_EM_ABERTO,
    DECODE(PR1.NUMERO_PEDIDO,0,NULL,PR1.NUMERO_PEDIDO) AS NR_PEDIDO,
    DECODE(PR1.ITEM_PEDIDO,0,NULL,PR1.ITEM_PEDIDO) AS SQ_ITEM_PEDIDO,
    ROM.IDPESSOAFJ AS ID_PESSOA_ROMANEIO,
    SUM(PRS.PESO_PECA) AS QT_ROMANEIO,
    COUNT(PRS.IDPECASPRODUTO) AS QT_PC_ROMANEIO
  FROM
    PECAS_ROMANEIO_SAIDA PRS
    JOIN GERAPECADESTINOOB DOB ON DOB.IDPECASPRODUTO = PRS.IDPECASPRODUTO
    JOIN ROMANEIO ROM ON ROM.NUMERO_ROMANEIO = PRS.NUMERO_ROMANEIO_SAID
    JOIN PRODUTO_ROMANEIO PR1 ON PR1.NUMERO_ROMANEIO = ROM.NUMERO_ROMANEIO AND PR1.IDPRODUTO_ROMANEIO = PRS.IDPRODUTO_ROMANEIO
    JOIN GERAPECASPRODUTO GPP ON GPP.IDPECASPRODUTO = PRS.IDPECASPRODUTO AND GPP.STPECAPRODUTO NOT IN (13)
  GROUP BY
    DOB.NUMERO_OB,
    PRS.NUMERO_ROMANEIO_SAID,
    PR1.NUMERO_PEDIDO,
    PR1.ITEM_PEDIDO,
    ROM.STATUS,
    DECODE(ROM.STATUS,4,0,5,0,6,0,1),
    ROM.IDPESSOAFJ

  UNION ALL  -- UNION ALL mais rápido que UNION, sem eliminar duplicatas (original usava UNION, mas aqui não há duplicatas entre as branches)

  SELECT
    DBB.NUMERO_OB AS NR_OB,
    GRR.NUMERO_ROMANEIO_SAID AS NR_ROMANEIO,
    RMM.STATUS AS ST_ROMANEIO,
    DECODE(RMM.STATUS,4,0,5,0,6,0,1) AS ST_ROM_EM_ABERTO,
    DECODE(PR2.NUMERO_PEDIDO,0,NULL,PR2.NUMERO_PEDIDO) AS NR_PEDIDO,
    DECODE(PR2.ITEM_PEDIDO,0,NULL,PR2.ITEM_PEDIDO) AS SQ_ITEM_PEDIDO,
    RMM.IDPESSOAFJ AS ID_PESSOA_ROMANEIO,
    SUM(GGP.QTLIQUIDA) AS QT_ROMANEIO,
    COUNT(GRR.IDPECASPRODUTO) AS QT_PC_ROMANEIO
  FROM
    GERAPECAROMSAIDA GRR
    JOIN GERAPECADESTINOOB DBB ON DBB.IDPECASPRODUTO = GRR.IDPECASPRODUTO
    JOIN ROMANEIO RMM ON RMM.NUMERO_ROMANEIO = GRR.NUMERO_ROMANEIO_SAID
    JOIN GERAPECASPRODUTO GGP ON GGP.IDPECASPRODUTO = GRR.IDPECASPRODUTO
    JOIN PRODUTO_ROMANEIO PR2 ON PR2.NUMERO_ROMANEIO = RMM.NUMERO_ROMANEIO AND PR2.IDPRODUTO_ROMANEIO = GRR.IDPRODUTO_ROMANEIO
  GROUP BY
    DBB.NUMERO_OB,
    GRR.NUMERO_ROMANEIO_SAID,
    PR2.NUMERO_PEDIDO,
    PR2.ITEM_PEDIDO,
    RMM.STATUS,
    DECODE(RMM.STATUS,4,0,5,0,6,0,1),
    RMM.IDPESSOAFJ
),

-- 6. CTE RRR: total romaneio por OB (sem filtro de status, todos os romaneios)
RRR AS (
  SELECT
    NR_OB,
    SUM(QT_ROMANEIO) AS QT_ROMANEIO,
    SUM(QT_PC_ROMANEIO) AS QT_PC_ROMANEIO
  FROM (
    SELECT DOB.NUMERO_OB AS NR_OB,
           SUM(PRS.PESO_PECA) AS QT_ROMANEIO,
           COUNT(PRS.IDPECASPRODUTO) AS QT_PC_ROMANEIO
    FROM   PECAS_ROMANEIO_SAIDA PRS
          ,GERAPECADESTINOOB    DOB
          ,ROMANEIO             ROM
          ,PRODUTO_ROMANEIO     PR1
    WHERE  DOB.IDPECASPRODUTO    = PRS.IDPECASPRODUTO
      AND  ROM.NUMERO_ROMANEIO   = PRS.NUMERO_ROMANEIO_SAID
      AND  PR1.NUMERO_ROMANEIO   = ROM.NUMERO_ROMANEIO
      AND  PR1.IDPRODUTO_ROMANEIO = PRS.IDPRODUTO_ROMANEIO
      AND  ROM.STATUS IN (0,1,3,8)
    GROUP BY DOB.NUMERO_OB

    UNION ALL

    SELECT DBB.NUMERO_OB AS NR_OB,
           SUM(GGP.QTLIQUIDA) AS QT_ROMANEIO,
           COUNT(GRR.IDPECASPRODUTO) AS QT_PC_ROMANEIO
    FROM   GERAPECAROMSAIDA  GRR
          ,GERAPECADESTINOOB DBB
          ,ROMANEIO          RMM
          ,GERAPECASPRODUTO  GGP
          ,PRODUTO_ROMANEIO  PR2
    WHERE  DBB.IDPECASPRODUTO  = GRR.IDPECASPRODUTO
      AND  RMM.NUMERO_ROMANEIO = GRR.NUMERO_ROMANEIO_SAID
      AND  GGP.IDPECASPRODUTO  = GRR.IDPECASPRODUTO
      AND  PR2.NUMERO_ROMANEIO = RMM.NUMERO_ROMANEIO
      AND  PR2.IDPRODUTO_ROMANEIO = GRR.IDPRODUTO_ROMANEIO
      AND  GRR.IDPECASPRODUTO NOT IN (SELECT PRS.IDPECASPRODUTO FROM PECAS_ROMANEIO_SAIDA PRS)
      AND  RMM.STATUS IN (0,1,3,8)
    GROUP BY DBB.NUMERO_OB
  ) RRRR
  GROUP BY NR_OB
),

-- 7. CTE OOO: OB-Pedido via OF (Pedido de Produção)
OOO AS (
  SELECT
    PPOB.NUMEROOB AS NR_OB,
    IPG.PEDIDO AS NR_PEDIDO,
    IPG.ITEMPEDIDO AS SQ_ITEM_PEDIDO,
    OFP.NUMEROOF AS NR_OF
  FROM
    PEDPRODUCAOOB PPOB
    JOIN PEDPRODUCAO PP ON PP.NUMERO = PPOB.NUMERO
    JOIN OFORDENS OFO ON OFO.NUMEROPEDPRODUCAO = PP.NUMERO AND OFO.REDUZIDO = PPOB.REDUZIDO
    JOIN OFPEDIDO OFP ON OFP.NUMEROOF = OFO.NUMEROOF AND OFP.NIVEL = OFO.NIVEL AND OFP.REDUZIDO = OFO.REDUZIDO
    JOIN ITENSPEDIDOQTDES IPQ ON IPQ.IDITENSPEDIDOQTDES = OFP.IDITENSPEDIDOQTDES
    JOIN ITENSPEDIDOGRADE IPG ON IPG.IDITENSPEDIDOGRADE = IPQ.IDITEMPEDGRADE
  WHERE OFP.QUANTIDADE_ATUAL <> 0
),

-- 8. CTE PPP: Pedido Comercial
PPP AS (
  SELECT
    PED.CD_SUBTIPOPED AS TP_PEDIDO,
    (SELECT TRIM(STT.DS_SUBTIPOPED) FROM COML_SUBTIPOPED STT WHERE STT.CD_SUBTIPOPED = PED.CD_SUBTIPOPED) AS DS_TP_PEDIDO,
    IPC.PEDIDO AS NR_PEDIDO,
    TRIM(PED.PEDIDOCLIENTE) AS NR_PROGRAMACAO,
    TRIM(PED.NUMERO_NOTA_FISCAL) AS NR_NFE_PEDIDO,
    TRIM(IPC.ITEMPEDIDOCLIENTE) AS DS_ITEM_PEDIDO_CLIENTE,
    TRIM(IPC.OBS) AS OBS_ITEM_PEDIDO,
    TRIM(IPC.CD_DESENHO_CLIENTE) AS CD_REF_CLIENTE,
    PED.BLOQUEIOFATURAMENTO AS ST_BLOQUEIO_FAT,
    DECODE(PED.BLOQUEIOFATURAMENTO,0,'NORMAL',1,'BLOQUEADO',2,'LIBERADO') AS DS_ST_BLOQUEIO_FAT,
    IPC.ITEMPEDIDO AS SQ_ITEM_PEDIDO,
    IPC.SITUACAOITEM AS ST_ITEM_PEDIDO,
    (SELECT UPPER(SII.DESCRICAO) FROM COML_SITUACOESITEM SII WHERE SII.SITUACAOITEM = IPC.SITUACAOITEM) AS DS_ST_ITEM_PEDIDO,
    CASE WHEN IPC.SITUACAOITEM IN (6,10,12,13,14,18) THEN 0 ELSE 1 END AS ST_PEDIDO_EM_ABERTO,
    PED.IDFILIALRESPONSAVEL AS ID_PESSOA_COMPRADOR,
    TRIM(PRE.NOME) AS NM_PESSOA_COMPRADOR,
    TRIM(PRE.NOMEFANTASIA) AS NM_PESSOA_COMPRADOR_F,
    PED.IDFILIALCOBRANCA AS ID_PESSOA_FATURA,
    TRIM(PFA.NOME) AS NM_PESSOA_FATURA,
    PED.IDFILIALENTREGA AS ID_PESSOA_ENTREGA,
    TRIM(PEN.NOME) AS NM_PESSOA_ENTREGA,
    IPC.PRECOUNITARIO AS PR_UNITARIO_PED,
    IPC.PRECODIGITADO AS PR_DIGITADO_PED,
    PED.TABELAPRECO AS CD_TAB_PRECO,
    TO_DATE(IPC.EXPEDIREM,'YYYYMMDD') AS DT_ENTREGA,
    CASE WHEN PED.IDFILIALRESPONSAVEL <> PED.IDFILIALCOBRANCA THEN 1 ELSE 0 END AS ST_PESCOM_DIF_PESFAT,
    CASE WHEN PED.IDFILIALRESPONSAVEL <> PED.IDFILIALCOBRANCA THEN 'SIM' ELSE 'NAO' END AS DS_ST_PESCOM_DIF_PESFAT,
    CASE WHEN PED.IDFILIALRESPONSAVEL IN (SELECT FIL.IDPESSOAFJ FROM PESSOASFJ FIL WHERE FIL.EMPRESA='02944599  ' AND FIL.IDPESSOAFJ NOT IN (1,2,3)) THEN 1 ELSE 0 END AS ST_TRANSF_LOJAS,
    CASE WHEN PED.IDFILIALRESPONSAVEL IN (SELECT FIL.IDPESSOAFJ FROM PESSOASFJ FIL WHERE FIL.EMPRESA='02944599  ' AND FIL.IDPESSOAFJ NOT IN (1,2,3)) THEN 'SIM' ELSE 'NAO' END AS DS_ST_TRANSF_LOJAS
  FROM
    ITENSPEDIDOCOMERCIAL IPC
    JOIN PEDIDOCOMERCIAL PED ON PED.PEDIDO = IPC.PEDIDO
    JOIN PESSOASFJ PRE ON PRE.IDPESSOAFJ = PED.IDFILIALRESPONSAVEL
    JOIN PESSOASFJ PFA ON PFA.IDPESSOAFJ = PED.IDFILIALCOBRANCA
    JOIN PESSOASFJ PEN ON PEN.IDPESSOAFJ = PED.IDFILIALENTREGA
),

-- 9. CTE XXX: pedido alternativo via peça reservada
XXX AS (
  SELECT
    G1.NUMERO_OB AS NR_OB,
    G2.NUMERO_PEDIDO_COMERC AS NR_PEDIDO,
    G2.SEQUENCIA_PRODUTO_PE AS SQ_ITEM_PEDIDO
  FROM
    GERAPECADESTINOOB G1
    JOIN OB ON OB.NUMERO_OB = G1.NUMERO_OB
    JOIN GERAPECAPEDCOMERCIAL G2 ON G2.IDPECASPRODUTO = G1.IDPECASPRODUTO
    JOIN GERAPECASPRODUTO G3 ON G3.IDPECASPRODUTO = G2.IDPECASPRODUTO AND G3.CODIGO_REDUZIDO_PROD = OB.CODIGO_REDUZIDO
  GROUP BY G1.NUMERO_OB, G2.NUMERO_PEDIDO_COMERC, G2.SEQUENCIA_PRODUTO_PE
),

-- 10. CTE PEDIDO_OB: Prioridade única do pedido (romaneio > XXX > OOO)
PEDIDO_OB AS (
  SELECT
    COALESCE(ROO.NR_OB, XXX.NR_OB, OOO.NR_OB) AS NR_OB,
    COALESCE(ROO.NR_PEDIDO, XXX.NR_PEDIDO, OOO.NR_PEDIDO) AS NR_PEDIDO,
    COALESCE(ROO.SQ_ITEM_PEDIDO, XXX.SQ_ITEM_PEDIDO, OOO.SQ_ITEM_PEDIDO) AS SQ_ITEM_PEDIDO
  FROM
    (SELECT DISTINCT NR_OB FROM ROO) ROO
    FULL JOIN XXX ON XXX.NR_OB = ROO.NR_OB
    FULL JOIN OOO ON OOO.NR_OB = COALESCE(ROO.NR_OB, XXX.NR_OB)
),

-- 11. CTE QT1: quantidades cruas
QT1 AS (
  SELECT
    O3.NUMERO_OB AS NR_OB,
    O3.KILOS_PROGRAMADOS AS QT_CRU_PROG_OB,
    DECODE(O3.TOTAL_PECAS_CONFIRM,0,
      ROUND(O3.KILOS_PROGRAMADOS / (SELECT MAX(PDD.PESO_PADRAO) FROM VW_ESP_PESO_PADRAO PDD WHERE PDD.REDUZIDO=O3.CODPRO_REDUZIDO), 0),
      O3.TOTAL_PECAS_CONFIRM) AS QT_PC_CRU_PROG_OB,
    SUM(NVL(O4.QTPESOLIQUORIG,0)) AS QT_CRU_ORIG_OB,
    SUM(NVL(O2.QTLIQUIDA,0)) AS QT_CRU_ATUAL_OB,
    COUNT(O2.IDPECASPRODUTO) AS QT_PC_CRU_OB
  FROM
    OB_PRODUTO O3
    LEFT JOIN GERAPECAORIGEMOB O1 ON O1.NUMERO_OB = O3.NUMERO_OB
    LEFT JOIN GERAPECASPRODUTO O2 ON O2.IDPECASPRODUTO = O1.IDPECASPRODUTO
    LEFT JOIN GERAPECACOMPLPECA O4 ON O4.IDPECASPRODUTO = O1.IDPECASPRODUTO
  GROUP BY O3.NUMERO_OB, O3.KILOS_PROGRAMADOS, O3.TOTAL_PECAS, O3.TOTAL_PECAS_CONFIRM, O3.CODPRO_REDUZIDO
),

-- 12. CTE QT2: quantidades acabadas
QT2 AS (
  SELECT
    O1.NUMERO_OB AS NR_OB,
    SUM(O2.QTLIQUIDA) AS QT_ACA_OB,
    COUNT(O2.IDPECASPRODUTO) AS QT_PC_ACA_OB,
    CASE WHEN MAX(O2.CODIGO_DEPOSITO) = 100 THEN 1 ELSE 0 END AS EH_ACAB_REPROC
  FROM
    GERAPECADESTINOOB O1
    JOIN GERAPECASPRODUTO O2 ON O2.IDPECASPRODUTO = O1.IDPECASPRODUTO
  GROUP BY O1.NUMERO_OB
  HAVING CASE WHEN MAX(O2.CODIGO_DEPOSITO) = 100 THEN 1 ELSE 0 END = 0  -- Filtro antecipado de reprocesso
),

-- 13. CTE QT3: quantidades disponíveis e reservadas
QT3 AS (
  SELECT
    NR_OB,
    SUM(QT_ACA_DISP_OB) AS QT_ACA_DISP_OB,
    SUM(QT_PC_ACA_DISP_OB) AS QT_PC_ACA_DISP_OB,
    SUM(QT_ACA_RES_OB) AS QT_ACA_RES_OB,
    SUM(QT_PC_RES_OB) AS QT_PC_ACA_RES_OB
  FROM (
    SELECT
      O1.NUMERO_OB AS NR_OB,
      CASE WHEN O2.STPECAPRODUTO = 0 THEN SUM(O2.QTLIQUIDA) ELSE 0 END AS QT_ACA_DISP_OB,
      CASE WHEN O2.STPECAPRODUTO = 0 THEN COUNT(O2.IDPECASPRODUTO) ELSE 0 END AS QT_PC_ACA_DISP_OB,
      CASE WHEN O2.STPECAPRODUTO = 14 THEN SUM(O2.QTLIQUIDA) ELSE 0 END AS QT_ACA_RES_OB,
      CASE WHEN O2.STPECAPRODUTO = 14 THEN COUNT(O2.IDPECASPRODUTO) ELSE 0 END AS QT_PC_RES_OB
    FROM
      GERAPECADESTINOOB O1
      JOIN GERAPECASPRODUTO O2 ON O2.IDPECASPRODUTO = O1.IDPECASPRODUTO AND O2.STPECAPRODUTO IN (0,14)
    GROUP BY O1.NUMERO_OB, O2.STPECAPRODUTO
  )
  GROUP BY NR_OB
),

-- 14. CTE NFF: nota fiscal por romaneio
NFF AS (
  SELECT
    PRO.NUMERO_ROMANEIO AS NR_ROMANEIO,
    NFC.NRNOTA AS NR_NF,
    NFC.DTEMISSAO AS DT_EMISSAO_NF
  FROM
    GERAREQUESTOITEMNOTA GQI
    JOIN PRODUTO_ROMANEIO PRO ON PRO.IDPRODUTO_ROMANEIO = GQI.IDPRODUTO_ROMANEIO
