  LEFT JOIN PPP ON PPP.NR_PEDIDO = PEDIDO_OB.NR_PEDIDO
               AND PPP.SQ_ITEM_PEDIDO = PEDIDO_OB.SQ_ITEM_PEDIDO

  LEFT JOIN QT1 ON QT1.NR_OB = OBE.NUMERO_OB
  LEFT JOIN QT2 ON QT2.NR_OB = OBE.NUMERO_OB
  LEFT JOIN QT3 ON QT3.NR_OB = OBE.NUMERO_OB
  LEFT JOIN NFF ON NFF.NR_ROMANEIO = ROO.NR_ROMANEIO
  LEFT JOIN XXXXXX ON XXXXXX.NR_OB = OBE.NUMERO_OB  -- Placeholder: XXX foi mesclado em PEDIDO_OB
  LEFT JOIN BBB ON BBB.NR_OB = OBE.NUMERO_OB
  LEFT JOIN OB_FAT_TOTAL ON OB_FAT_TOTAL.NR_OB = OBE.NUMERO_OB
  LEFT JOIN DEFP ON DEFP.NR_OB = OBE.NUMERO_OB
  LEFT JOIN QTPNF ON QTPNF.NR_OB = OBE.NUMERO_OB
  LEFT JOIN GGG ON GGG.NR_PEDIDO = PEDIDO_OB.NR_PEDIDO
               AND GGG.SQ_ITEM_PEDIDO = PEDIDO_OB.SQ_ITEM_PEDIDO
               AND GGG.NR_OB = OBE.NUMERO_OB
