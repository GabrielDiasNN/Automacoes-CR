/*
 * ============================================================
 * COMENTÁRIOS SOBRE AS OTIMIZAÇÕES
 * ============================================================
 *
 * 1. Subconsultas escalares substituídas por CTEs:
 *    - TIN, OBQ, REC, FAT, ROO, RRR, OOO, XXX, QT1, QT2, QT3, NFF, BBB, OB_FAT_TOTAL,
 *      GGG, DEFP, QTPNF foram transformados em CTEs e depois aplicados LEFT JOIN.
 *    - Isso evita execução repetida para cada linha da tabela principal.
 *
 * 2. Uso de ROW_NUMBER no lugar de auto‑join com MAX:
 *    - No CTE TIN, usamos ROW_NUMBER() OVER (PARTITION BY NUMERO_OB ORDER BY SEQUENCIA DESC)
 *      para obter a última fase, em vez de subconsulta correlacionada.
 *
 * 3. Centralização da lógica de pedido:
 *    - A expressão complexa NVL(NVL(ROO.NR_PEDIDO,XXX.NR_PEDIDO),OOO.NR_PEDIDO)
 *      foi extraída para o CTE PEDIDO_OB, que prioriza romaneio > XXX > OOO.
 *      Isso reduz a repetição e simplifica os joins.
 *
 * 4. Filtros antecipados:
 *    - O filtro "EH_ACAB_REPROC = 0" foi aplicado diretamente no CTE QT2 (HAVING),
 *      reduzindo o volume de dados já na agregação.
 *
 * 5. Substituição de UNION por UNION ALL:
 *    - Nos CTEs ROO e RRR, usamos UNION ALL porque as duas branches são disjuntas
 *      (uma pega registros em PECAS_ROMANEIO_SAIDA, a outra em GERAPECAROMSAIDA),
 *      evitando o custo de eliminação de duplicatas.
 *
 * 6. Joins ANSI LEFT JOIN em vez de (+) para clareza e melhor otimização pelo Oracle.
 *
 * 7. Redução de acessos a tabelas:
 *    - Muitas subconsultas escalares podiam ser convertidas em joins, como as que
 *      buscavam descrições (DS_PESSOA_ROMANEIO, DS_ST_ROMANEIO, etc.) – estas
 *      permanecem por necessidade de agregação pontual; avaliar se podem ser
 *      convertidas em joins com CTEs separadas posteriormente.
