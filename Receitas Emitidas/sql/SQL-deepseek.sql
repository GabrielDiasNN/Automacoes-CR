       ELSE 0 END AS ST_OB_VARIOS_FAT,
  CASE WHEN DECODE(NVL(ROO.ST_ROM_EM_ABERTO,1),1,'0',0,'1') = 1 AND ROO.QT_ROMANEIO = QT2.QT_ACA_OB THEN 'NAO'
       WHEN DECODE(NVL(ROO.ST_ROM_EM_ABERTO,1),1,'0',0,'1') = 1 AND ROO.QT_ROMANEIO <> QT2.QT_ACA_OB THEN 'SIM'
       ELSE 'AGUARDANDO' END AS DS_ST_OB_VARIOS_FAT,
  NFF.NR_NF,
  NFF.DT_EMISSAO_NF,
  DECODE(NVL(OB_FAT_TOTAL.NR_OB,0),0,0,1) AS OB_FAT_TOTAL,

  /* DADOS OB BLOQUEIO */
  BBB.CD_FASE_OB_BLOQ,
  BBB.DS_FASE_OB_BLOQ,
  BBB.ST_OB_BLOQUEIO,
  BBB.DS_ST_OB_BLOQUEIO,
