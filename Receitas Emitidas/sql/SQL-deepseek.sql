  BBB.DS_ST_LIB_INI_FASE,
  BBB.OBS_OB_BLOQUEIO,
  BBB.DS_MOTIVO_BLOQUEIO,
  BBB.DT_HR_BLOQUEIO,
  BBB.NM_USU_BLOQUEIO,
  BBB.DT_H_LIBERACAO,
  BBB.NM_USU_LIBERACAO,

  /* DADOS DEFEITO PEÇA CRUA */
  DEFP.DS_GR_DEFEITO AS DS_GR_DEFEITO_CRU,
  DEFP.DS_TP_DEFEITO AS DS_TP_DEFEITO_CRU,

  /* NF DAS PEÇAS CRUAS */
  QTPNF.QT_PC_NF

FROM
  OB OBE
  JOIN ITENS_ESTOQUE IAC ON IAC.CODIGO_REDUZIDO = OBE.CODIGO_REDUZIDO
  JOIN ENGEITEMESTOCOR COR ON COR.CDREDUZIDO = IAC.CODIGO_REDUZIDO
  JOIN COR COO ON COO.CODIGO_COR = COR.CDCOR
  JOIN COML_TIPOSCOR TCO ON TCO.TIPOCOR = COO.TIPOCOR
  JOIN ENGEITEMESTONIVELGE9 NV9 ON NV9.CDREDUZIDO = IAC.CODIGO_REDUZIDO
  JOIN ITENS_ESTOQUE ICR ON ICR.CODIGO_REDUZIDO = OBE.CODIGO_REDUZIDO_CRU
  LEFT JOIN TIN_FINAL ON TIN_FINAL.NUMERO_OB = OBE.NUMERO_OB
  LEFT JOIN OBQ ON OBQ.NR_OB = OBE.NUMERO_OB
  LEFT JOIN REC ON REC.CODIGO_REDUZIDO = OBE.CODIGO_REDUZIDO
  LEFT JOIN FAT ON FAT.NUMERO_OB = OBE.NUMERO_OB
               AND FAT.SEQUENCIA = DECODE(OBE.STATUS,0,0,PKGBENF0001.FNC_RETORNA_SEQUENCIA_OB(OBE.NUMERO_OB,0))
  LEFT JOIN ROO ON ROO.NR_OB = OBE.NUMERO_OB
  LEFT JOIN RRR ON RRR.NR_OB = OBE.NUMERO_OB
  LEFT JOIN OOO ON OOO.NR_OB = OBE.NUMERO_OB

  -- Prioridade do pedido: primeiro pelo romaneio, depois XXX, depois OOO
