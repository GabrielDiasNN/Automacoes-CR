    DE5.QT_PC_ROM_FAT
  FROM
    GERAPECADESTINOOB DE1
    JOIN (
      SELECT DE4.NUMERO_OB AS NR_OB, COUNT(DE2.IDPECASPRODUTO) AS QT_PC_ROM_FAT
      FROM PECAS_ROMANEIO_SAIDA DE2
      JOIN ROMANEIO DE3 ON DE3.NUMERO_ROMANEIO = DE2.NUMERO_ROMANEIO_SAID AND DE3.STATUS IN (4,6)
