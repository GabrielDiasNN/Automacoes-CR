-- =============================================================================
-- RECEITAS BLOQUEADAS - VERSÃO 19c (CTE de tempos sem JOIN redundante em UP_ORDEM_MVTO)
-- =============================================================================
WITH 
CTE_TEMPOS AS (
    SELECT 
        UPO.NUMEROORDEMREAL AS NR_OB,
        MAX(UNP.DTTEMPOINICIAL) AS INICIO_TING,
        MAX(UNP.DTTEMPOFINAL) AS FINAL_TING,
        MAX(SUBSTR(UNP.NUMERO_MAQUINA, 7, 4)) AS MQ_TING
    FROM SGTPRD.UP_ORDEM_MVTO UPO
    INNER JOIN SGTPRD.UNIDADE_PROGRAMACAO UNP 
        ON UPO.NUMEROUP = UNP.NUMEROUP
    WHERE UNP.TIPO_MAQUINA = 19 
      AND UNP.EXCLUIDA = 0 
      AND UNP.TIPOUP = 0
      AND UNP.DTTEMPOFINAL >= TRUNC(SYSDATE)
    GROUP BY UPO.NUMEROORDEMREAL
),
-- Gráfico da receita lido das tabelas (antes: VW_LAC_RECPRD_RECLAB, que usa a função
-- OPTSTRAGGR). LISTAGG ordenado por ROWID de RECEITAS_ALTERAR reproduz a ordem da view.
CTE_GRAFICO AS (
    SELECT CRB.ID_LIGA_CADREC_ITEMR AS IDLCRIR_PRD,
        MAX(CASE
            WHEN CRL.PROCESSOINDUSTRIAL IS NULL THEN 'G ' || LTRIM(CRA.GRAFICO_RECEITA, '0')
            ELSE (
                SELECT SUBSTR(LISTAGG('G ' || LTRIM(RAR.CODIGO_GRAFICO, '0') || ' C ' || LTRIM(RVM.GRUPO_INSUMO, '0')
                           || '/' || LTRIM(RVM.SUBGRUPO_INSUMO, '0') || '/' || LTRIM(RVM.CLASSE_INSUMO, '0'),
                           ',' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY RAR.ROWID), 1, 80)
                FROM SGTPRD.RECEITAS_ALTERAR RAR
                INNER JOIN SGTPRD.RECEITA_VARIAVEL RVA
                    ON RVA.REDUZIDO_RECEITA = RAR.REDUZIDO_RECVARIAVEL
                INNER JOIN SGTPRD.REC_VARIAVEL_MESTRE RVM
                    ON RVM.ID = RVA.IDRECVARIAVELMESTRE
                WHERE RAR.ID_LIGACAOCOLORMASTE = LCO.ID_LIGACAOCOLORMASTE
            )
        END) AS GRAFICO
    FROM SGTPRD.LIGA_CADREC_ITEMREC CRB
    INNER JOIN SGTPRD.CADASTRO_RECEITAS CRA
        ON CRA.CODIGO_REDUZIDO_RECE = CRB.CODIGO_REDUZIDO_RECE
    LEFT JOIN SGTPRD.LIGACAO_COLORMASTER LCO
        ON LCO.PI_PRODUCAO = CRA.PROCESSOINDUSTRIAL
       AND LCO.CODCOR = SUBSTR(CRA.CODCOR, 1, 10)
       AND LCO.ESPECIFICACAO_PRODUT = CRA.ESPECIFICACAO_PRODUT
       AND LCO.PROCESSO_ESPECIFICO = CRA.PROCESSO_ESPECIFICO
       AND LCO.IDPESSOASFJ = CRA.IDPESSOASFJ
       AND LCO.IDLOTE_PADRAO = CRB.IDLOTE_PADRAO
       AND LCO.ID_FAIXARELACAOBANHO = CRB.ID_FAIXARELACAOBANHO
       AND LCO.TIPO_RECEITA = 0
    LEFT JOIN SGTPRD.LIGA_CADREC_ITEMREC LCL
        ON LCL.TIPO_DE_RECEITA = LCO.TIPO_DE_RECEITA
       AND LCL.ID_LIGA_CADREC_ITEMR = LCO.ID_LIGA_CADREC_ITEMR
    LEFT JOIN SGTPRD.CADASTRO_RECEITAS CRL
        ON CRL.CODIGO_REDUZIDO_RECE = LCL.CODIGO_REDUZIDO_RECE
    WHERE CRB.ID_LIGA_CADREC_ITEMR IN (
        SELECT L.ID_LIGA_CADREC_ITEMR
        FROM SGTPRD.LIGA_CADREC_ITEMREC L
        INNER JOIN SGTPRD.LABRECEITA_BLOQUEADA B 
            ON B.ID_LABRECEITA_BLOQ = L.ID_LABRECEITA_BLOQ
        WHERE B.BLOQUEIO_RECEITA = 0
    )
    GROUP BY CRB.ID_LIGA_CADREC_ITEMR
),
CTE_DADOS AS (
    SELECT 
        OBFX.CODIGO_GRUPO AS GRUPO,
        OBFX.NUMERO_OB AS NR_OB,
        TRIM(OBFX.CODIGO_COR_DESENHO) AS COR_OB,
        TRIM(SUBSTR(CREX.CODCOR, 1, 11)) AS COR_REC,
        OBFX.ESPECIFICACAO_PRODUT AS EP_OB,
        CREX.ESPECIFICACAO_PRODUT AS EP_REC,
        OBFX.PROCESSO_ESPECIFICO AS PE_OB,
        CREX.PROCESSO_ESPECIFICO AS PE_REC,
        T.MQ_TING,
        T.INICIO_TING,
        T.FINAL_TING,
        GR.GRAFICO,
        DECODE(LCR.DATA_ULTIMA_PRODUC, 0, TO_DATE('1899-12-31','YYYY-MM-DD'), 
               TO_DATE(LCR.DATA_ULTIMA_PRODUC,'YYYYMMDD')) AS DATA_ULT_PROD,
        CREX.CODIGO_CLASSIFICACAO AS CD_CLASSIF,
        UPPER(TRIM(CLF.DESCRICAO)) AS CLASSIF_COR,
        LCR.CODIGO_REDUZIDO_RECE AS CODIGO_REDUZIDO_RECE,
        UPPER(LRB.USUARIO_BLOQUEIO) AS USUARIO_BLOQUEIO,
        TO_DATE(LRB.DATA_BLOQUEIO, 'YYYY/MM/DD') AS DATA_BLOQUEIO,
        TO_DATE(LCR.DATA_ALTERACAO, 'YYYY/MM/DD') AS DATA_ALTERACAO,
        LCR.USUARIO_ALTEROU,
        UPPER(TRIM(CRI.NOME_USERLITERAL)) AS NOME_USUARIO_ALTEROU,
        CASE 
            WHEN OBFX.PROCESSO_ESPECIFICO IS NULL OR CREX.PROCESSO_ESPECIFICO IS NULL THEN 'Indefinido'
            WHEN OBFX.PROCESSO_ESPECIFICO = CREX.PROCESSO_ESPECIFICO THEN 'OK'
            ELSE 'Divergente'
        END AS STATUS_PE
    FROM CTE_TEMPOS T
    INNER JOIN SGTPRD.OB_FASES OBFX 
        ON OBFX.NUMERO_OB = T.NR_OB
    INNER JOIN SGTPRD.OB OB 
        ON OBFX.NUMERO_OB = OB.NUMERO_OB
    LEFT JOIN SGTPRD.CADASTRO_RECEITAS CREX 
        ON CREX.PROCESSOINDUSTRIAL = (OBFX.CODIGO_FASE || OBFX.TIPO_PROCESSO)
       AND SUBSTR(CREX.CODCOR, 1, 11) = OBFX.CODIGO_COR_DESENHO
       AND CREX.ESPECIFICACAO_PRODUT = OBFX.ESPECIFICACAO_PRODUT
       AND CREX.PROCESSO_ATIVO_PRODU = 1
    INNER JOIN SGTPRD.LIGA_CADREC_ITEMREC LCR 
        ON LCR.CODIGO_REDUZIDO_RECE = CREX.CODIGO_REDUZIDO_RECE
    INNER JOIN SGTPRD.LABRECEITA_BLOQUEADA LRB 
        ON LRB.ID_LABRECEITA_BLOQ = LCR.ID_LABRECEITA_BLOQ
    LEFT JOIN CTE_GRAFICO GR 
        ON GR.IDLCRIR_PRD = LCR.ID_LIGA_CADREC_ITEMR
    LEFT JOIN SGTPRD.CLASSIFICACAO_COR CLF 
        ON CLF.CODIGO_CLASSIFICACAO = CREX.CODIGO_CLASSIFICACAO
    LEFT JOIN SGTPRD.CRISTAL CRI
        ON CRI.CODREDUSUARIO = LCR.USUARIO_ALTEROU
    WHERE OB.STATUS <> 0
      AND OBFX.CODIGO_FASE = 40
      AND OBFX.STATUS = 0
      AND LRB.BLOQUEIO_RECEITA = 0
)
SELECT GRUPO, NR_OB, COR_OB, COR_REC, EP_OB, EP_REC, PE_OB, PE_REC, MQ_TING, 
       INICIO_TING, FINAL_TING, GRAFICO, DATA_ULT_PROD, CD_CLASSIF, CLASSIF_COR, 
       CODIGO_REDUZIDO_RECE, USUARIO_BLOQUEIO, DATA_BLOQUEIO, DATA_ALTERACAO, 
       USUARIO_ALTEROU, NOME_USUARIO_ALTEROU, STATUS_PE 
FROM CTE_DADOS
ORDER BY INICIO_TING ASC, NR_OB ASC, GRUPO ASC
