-- =============================================================================
-- OBS PARADAS NA FASE - VERSÃO 100% NATIVA ORACLE 19c
-- =============================================================================
WITH
    OB_FASES_CALC AS (
        SELECT /*+ MATERIALIZE */
            OBF.NUMERO_OB,
            -- Fase atual (REGRAS_NEGOCIO.md): menor SEQUENCIA com status 1, 2 ou 3; sem
            -- nenhuma nesse conjunto, a última sequência.
            NVL(MIN(CASE WHEN OBF.STATUS IN (1, 2, 3) THEN OBF.SEQUENCIA END), MAX(OBF.SEQUENCIA)) AS SEQ_ATUAL,
            -- Última confirmação, mesma regra de PKGBENF0001.FNC_RETORNA_ULT_CONF_OB conferida
            -- em 17/10/2026 contra VW_BNF_OBMONTADA (760 de 760 OBs iguais): fase confirmada
            -- (4) usa o fim da UP; pesada/em execução (2, 3) usam TEMPO_*_CONFIR (minutos desde
            -- 01/01/1996). OB sem confirmação fica com DIAS_PARADO nulo (obp_config.py usa 0).
            MAX(CASE
                WHEN OBF.STATUS IN (2, 3, 4) AND GREATEST(NVL(OBF.TEMPO_FINAL_CONFIRMA, 0), NVL(OBF.TEMPO_INICIAL_CONFIR, 0)) > 0 THEN
                    CASE WHEN OBF.STATUS = 4
                         THEN NVL((SELECT MAX(UNP.DTTEMPOFINAL)
                           FROM SGTPRD.UP_ORDEM_MVTO UPO
                           JOIN SGTPRD.UNIDADE_PROGRAMACAO UNP ON UNP.NUMEROUP = UPO.NUMEROUP
                          WHERE UPO.NUMEROORDEMREAL = OBF.NUMERO_OB
                            AND UPO.SEQUENCIAORDEMREAL = OBF.SEQUENCIA
                            AND UNP.EXCLUIDA = 0), DATE '1996-01-01' + GREATEST(NVL(OBF.TEMPO_FINAL_CONFIRMA, 0), NVL(OBF.TEMPO_INICIAL_CONFIR, 0)) / 1440)
                         ELSE DATE '1996-01-01' + GREATEST(NVL(OBF.TEMPO_FINAL_CONFIRMA, 0), NVL(OBF.TEMPO_INICIAL_CONFIR, 0)) / 1440
                    END
            END) AS DT_ULT_CONF,
            TRIM(MAX(OBF.CODIGO_PLACA)) AS PLACA_KANBAN,
            MAX(CASE WHEN OBF.CODIGO_FASE = 40 THEN OBF.CODIGO_COR_DESENHO END)
                KEEP (DENSE_RANK LAST ORDER BY
                      CASE WHEN OBF.CODIGO_FASE = 40 THEN OBF.SEQUENCIA ELSE NULL END
                      NULLS FIRST) AS CD_COR_TINGIMENTO
        FROM SGTPRD.OB_FASES OBF
        INNER JOIN SGTPRD.OB OB ON OB.NUMERO_OB = OBF.NUMERO_OB
        WHERE OB.STATUS <> 0
        GROUP BY OBF.NUMERO_OB
    ),

    OB_ATIVA AS (
        SELECT /*+ MATERIALIZE */
            OB.NUMERO_OB,
            OB.CODIGO_REDUZIDO,
            OB.CODIGO_FLUXO,
            OB.TIPO_ORDEM,
            FC.SEQ_ATUAL,
            SYSDATE - FC.DT_ULT_CONF AS DIAS_PARADO,
            FC.PLACA_KANBAN,
            FC.CD_COR_TINGIMENTO
        FROM SGTPRD.OB OB
        INNER JOIN SGTPRD.PEDPRODUCAOOB PPO 
            ON PPO.NUMEROOB = OB.NUMERO_OB
           AND PPO.SETOR = 5
           AND PPO.OBMONTADA = '1'
        INNER JOIN OB_FASES_CALC FC 
            ON FC.NUMERO_OB = OB.NUMERO_OB
        WHERE OB.STATUS <> 0
    ),

    ITEM_OB AS (
        SELECT
            OBA.NUMERO_OB,
            OBA.CODIGO_REDUZIDO AS REDUZ_ACABADO,
            TRIM(MAX(ITE.CODIGO_ALTERNATIVO)) AS ALTERNATIVO,
            TRIM(MAX(ITE.DESCRICAO)) AS DS_ITEM,
            TRIM(MAX(ART.CDARTIGOCRU)) AS CD_ARTIGO,
            MIN(EIC.CDCOR) AS CD_COR_ITEM,
            MAX(ITC.LARGURA) AS LARGURA,
            MAX(ITC.GRAMATURA) AS GRAMATURA
        FROM OB_ATIVA OBA
        INNER JOIN SGTPRD.ITENS_ESTOQUE ITE 
            ON ITE.CODIGO_REDUZIDO = OBA.CODIGO_REDUZIDO
        INNER JOIN SGTPRD.ENGEITEMESTOARTCRU ART 
            ON ART.CDREDUZIDO = ITE.CODIGO_REDUZIDO
        INNER JOIN SGTPRD.ENGEITEMESTOCOR EIC 
            ON EIC.CDREDUZIDO = ITE.CODIGO_REDUZIDO
        INNER JOIN SGTPRD.ITENS_COMPLEMENTO ITC 
            ON ITC.CODIGO_REDUZIDO = ITE.CODIGO_REDUZIDO
        GROUP BY OBA.NUMERO_OB, OBA.CODIGO_REDUZIDO
    ),

    QT_OB AS (
        SELECT
            GPO.NUMERO_OB,
            COUNT(GPP.IDPECASPRODUTO) AS QT_PECAS,
            SUM(GPP.QTLIQUIDA) AS QT_KILOS_REAL
        FROM SGTPRD.GERAPECAORIGEMOB GPO
        INNER JOIN SGTPRD.GERAPECASPRODUTO GPP 
            ON GPP.IDPECASPRODUTO = GPO.IDPECASPRODUTO
        INNER JOIN OB_ATIVA OBA 
            ON OBA.NUMERO_OB = GPO.NUMERO_OB
        GROUP BY GPO.NUMERO_OB
    ),

    ENTREGA_OB AS (
        SELECT
            PPOB.NUMEROOB AS NUMERO_OB,
            MAX(TO_DATE(IPC.EXPEDIREM, 'YYYYMMDD')) AS DT_ENTREGA,
            MAX(TRIM(PES.NOMEFANTASIA)) AS NOME_CLIENTE
        FROM SGTPRD.PEDPRODUCAOOB PPOB
        INNER JOIN OB_ATIVA OBA 
            ON OBA.NUMERO_OB = PPOB.NUMEROOB
        INNER JOIN SGTPRD.PEDPRODUCAO PP 
            ON PP.NUMERO = PPOB.NUMERO
        INNER JOIN SGTPRD.OFORDENS OFO 
            ON OFO.NUMEROPEDPRODUCAO = PP.NUMERO
           AND OFO.REDUZIDO = PPOB.REDUZIDO
        INNER JOIN SGTPRD.OFPEDIDO OFP 
            ON OFP.NUMEROOF = OFO.NUMEROOF
           AND OFP.NIVEL = OFO.NIVEL
           AND OFP.REDUZIDO = OFO.REDUZIDO
           AND OFP.QUANTIDADE_ATUAL <> 0
        INNER JOIN SGTPRD.ITENSPEDIDOQTDES IPQ 
            ON IPQ.IDITENSPEDIDOQTDES = OFP.IDITENSPEDIDOQTDES
        INNER JOIN SGTPRD.ITENSPEDIDOGRADE IPG 
            ON IPG.IDITENSPEDIDOGRADE = IPQ.IDITEMPEDGRADE
        INNER JOIN SGTPRD.ITENSPEDIDOCOMERCIAL IPC 
            ON IPC.PEDIDO = IPG.PEDIDO
           AND IPC.ITEMPEDIDO = IPG.ITEMPEDIDO
        INNER JOIN SGTPRD.PEDIDOCOMERCIAL PED 
            ON PED.PEDIDO = IPC.PEDIDO
        INNER JOIN SGTPRD.PESSOASFJ PES 
            ON PES.IDPESSOAFJ = PED.IDFILIALRESPONSAVEL
        GROUP BY PPOB.NUMEROOB
    )

SELECT
    OBA.NUMERO_OB,
    NVL(OBA.PLACA_KANBAN, 'SEM KANBAN') AS PLACA_KANBAN,
    ITM.ALTERNATIVO,
    ITM.CD_ARTIGO,
    NVL(OBA.CD_COR_TINGIMENTO, ITM.CD_COR_ITEM) AS CD_COR,
    ITM.REDUZ_ACABADO,
    ITM.DS_ITEM,
    ITM.LARGURA,
    ITM.GRAMATURA,
    TRIM(FFL.DESCRICAO_FASE) AS FASE_ATUAL,
    OBF.CODIGO_FASE AS CODIGO_FASE,
    UPPER(ENI.DESCRIPTION) AS STATUS_FASE_ATUAL,
    TRUNC(OBA.DIAS_PARADO, 1) AS DIAS_PARADO,
    OBA.CODIGO_FLUXO,
    QT.QT_PECAS,
    QT.QT_KILOS_REAL,
    ENT.DT_ENTREGA,
    ENT.NOME_CLIENTE
FROM OB_ATIVA OBA
INNER JOIN SGTPRD.OB_FASES OBF 
    ON OBF.NUMERO_OB = OBA.NUMERO_OB
   AND OBF.SEQUENCIA = OBA.SEQ_ATUAL
INNER JOIN SGTPRD.FASES_FLUXO FFL 
    ON FFL.CODIGO_FASE = OBF.CODIGO_FASE
-- Descrição do status pelas tabelas do enumerado do ERP (TOBFASESSTATUS), que cobrem
-- todos os códigos (0 a 6), em vez de CASE fixo.
LEFT JOIN SGTPRD.XX2_ENUMERATES ENU
    ON ENU.NAME = 'TOBFASESSTATUS'
LEFT JOIN SGTPRD.XX2_ENUMITEM ENI
    ON ENI.IDENUMERATE = ENU.ID
   AND ENI.SEQUENCE = OBF.STATUS
INNER JOIN ITEM_OB ITM 
    ON ITM.NUMERO_OB = OBA.NUMERO_OB
INNER JOIN QT_OB QT 
    ON QT.NUMERO_OB = OBA.NUMERO_OB
LEFT JOIN ENTREGA_OB ENT 
    ON ENT.NUMERO_OB = OBA.NUMERO_OB
WHERE (OBA.TIPO_ORDEM = 0 OR OBF.CODIGO_FASE <> 10)
ORDER BY OBA.DIAS_PARADO DESC NULLS LAST
