/*
    ================================================================================
    QUERY OTIMIZADA: MONTAGEM DE TERCEIRIZADOS (VERSÃO ESTÁVEL)
    FOCO: Filtros Programação %T, Montagem, Destino Receita e Status OB
    ================================================================================
*/

WITH 
-- 1. Dados Básicos da OB (Filtro Status)
CTE_OB AS (
    SELECT 
        NUMERO_OB, STATUS, CODIGO_REDUZIDO, CODIGO_OBSERVACAO
    FROM SGTPRD.OB
    WHERE STATUS <> 0
),

-- 2. NF das Peças Cruas
CTE_NF_CRU AS (
    SELECT POC.NR_OB, LISTAGG(POC.QT_PECA||' - '||POC.NR_NF, ',' ON OVERFLOW TRUNCATE '' WITHOUT COUNT) WITHIN GROUP (ORDER BY POC.NR_NF) AS QT_PC_NF
    FROM (
        SELECT AB1.NUMERO_OB NR_OB, BC1.NUMERO_NOTA NR_NF, COUNT(DISTINCT AB1.IDPECASPRODUTO) QT_PECA
        FROM SGTPRD.GERAPECAORIGEMOB AB1
        JOIN SGTPRD.GERAPECANOTAENTRADA BC1 ON BC1.IDPECASPRODUTO = AB1.IDPECASPRODUTO
        GROUP BY AB1.NUMERO_OB, BC1.NUMERO_NOTA
    ) POC
    GROUP BY POC.NR_OB
),

-- 3. Pedido Comercial (Hierarquia Original para obter NR_PROG)
-- Pedido e item saem sempre da MESMA fonte (romaneio > peça comercial > OF) e,
-- dentro dela, da mesma linha (KEEP ... ORDER BY pedido): nunca pedido de uma fonte
-- com item de outra. Romaneio com pedido ou item zerado não conta como fonte.
CTE_PEDIDO_FONTES AS (
    SELECT
        OB.NUMERO_OB,
        (SELECT MAX(PR1.NUMERO_PEDIDO) FROM SGTPRD.PECAS_ROMANEIO_SAIDA PRS JOIN SGTPRD.PRODUTO_ROMANEIO PR1 ON PR1.NUMERO_ROMANEIO = PRS.NUMERO_ROMANEIO_SAID AND PR1.IDPRODUTO_ROMANEIO = PRS.IDPRODUTO_ROMANEIO JOIN SGTPRD.GERAPECADESTINOOB DOB ON DOB.IDPECASPRODUTO = PRS.IDPECASPRODUTO WHERE DOB.NUMERO_OB = OB.NUMERO_OB AND PR1.NUMERO_PEDIDO <> 0 AND PR1.ITEM_PEDIDO <> 0) AS PED_ROM,
        (SELECT MAX(PR1.ITEM_PEDIDO) KEEP (DENSE_RANK LAST ORDER BY PR1.NUMERO_PEDIDO) FROM SGTPRD.PECAS_ROMANEIO_SAIDA PRS JOIN SGTPRD.PRODUTO_ROMANEIO PR1 ON PR1.NUMERO_ROMANEIO = PRS.NUMERO_ROMANEIO_SAID AND PR1.IDPRODUTO_ROMANEIO = PRS.IDPRODUTO_ROMANEIO JOIN SGTPRD.GERAPECADESTINOOB DOB ON DOB.IDPECASPRODUTO = PRS.IDPECASPRODUTO WHERE DOB.NUMERO_OB = OB.NUMERO_OB AND PR1.NUMERO_PEDIDO <> 0 AND PR1.ITEM_PEDIDO <> 0) AS ITEM_ROM,
        (SELECT MAX(G2.NUMERO_PEDIDO_COMERC) FROM SGTPRD.GERAPECAPEDCOMERCIAL G2 JOIN SGTPRD.GERAPECADESTINOOB G1 ON G1.IDPECASPRODUTO = G2.IDPECASPRODUTO JOIN SGTPRD.GERAPECASPRODUTO G3 ON G3.IDPECASPRODUTO = G2.IDPECASPRODUTO JOIN SGTPRD.OB G4 ON G4.NUMERO_OB = G1.NUMERO_OB WHERE G1.NUMERO_OB = OB.NUMERO_OB AND G3.CODIGO_REDUZIDO_PROD = G4.CODIGO_REDUZIDO AND G2.NUMERO_PEDIDO_COMERC IS NOT NULL) AS PED_COM,
        (SELECT MAX(G2.SEQUENCIA_PRODUTO_PE) KEEP (DENSE_RANK LAST ORDER BY G2.NUMERO_PEDIDO_COMERC) FROM SGTPRD.GERAPECAPEDCOMERCIAL G2 JOIN SGTPRD.GERAPECADESTINOOB G1 ON G1.IDPECASPRODUTO = G2.IDPECASPRODUTO JOIN SGTPRD.GERAPECASPRODUTO G3 ON G3.IDPECASPRODUTO = G2.IDPECASPRODUTO JOIN SGTPRD.OB G4 ON G4.NUMERO_OB = G1.NUMERO_OB WHERE G1.NUMERO_OB = OB.NUMERO_OB AND G3.CODIGO_REDUZIDO_PROD = G4.CODIGO_REDUZIDO AND G2.NUMERO_PEDIDO_COMERC IS NOT NULL) AS ITEM_COM,
        (SELECT IPG.PEDIDO FROM SGTPRD.PEDPRODUCAOOB PPOB JOIN SGTPRD.OFORDENS OFO ON OFO.NUMEROPEDPRODUCAO = PPOB.NUMERO AND OFO.REDUZIDO = PPOB.REDUZIDO JOIN SGTPRD.OFPEDIDO OFP ON OFP.NUMEROOF = OFO.NUMEROOF AND OFP.NIVEL = OFO.NIVEL AND OFP.REDUZIDO = OFO.REDUZIDO JOIN SGTPRD.ITENSPEDIDOQTDES IPQ ON IPQ.IDITENSPEDIDOQTDES = OFP.IDITENSPEDIDOQTDES JOIN SGTPRD.ITENSPEDIDOGRADE IPG ON IPG.IDITENSPEDIDOGRADE = IPQ.IDITEMPEDGRADE WHERE PPOB.NUMEROOB = OB.NUMERO_OB AND OFP.QUANTIDADE_ATUAL <> 0 ORDER BY IPG.PEDIDO, IPG.ITEMPEDIDO FETCH FIRST 1 ROW ONLY) AS PED_OF,
        (SELECT IPG.ITEMPEDIDO FROM SGTPRD.PEDPRODUCAOOB PPOB JOIN SGTPRD.OFORDENS OFO ON OFO.NUMEROPEDPRODUCAO = PPOB.NUMERO AND OFO.REDUZIDO = PPOB.REDUZIDO JOIN SGTPRD.OFPEDIDO OFP ON OFP.NUMEROOF = OFO.NUMEROOF AND OFP.NIVEL = OFO.NIVEL AND OFP.REDUZIDO = OFO.REDUZIDO JOIN SGTPRD.ITENSPEDIDOQTDES IPQ ON IPQ.IDITENSPEDIDOQTDES = OFP.IDITENSPEDIDOQTDES JOIN SGTPRD.ITENSPEDIDOGRADE IPG ON IPG.IDITENSPEDIDOGRADE = IPQ.IDITEMPEDGRADE WHERE PPOB.NUMEROOB = OB.NUMERO_OB AND OFP.QUANTIDADE_ATUAL <> 0 ORDER BY IPG.PEDIDO, IPG.ITEMPEDIDO FETCH FIRST 1 ROW ONLY) AS ITEM_OF
    FROM CTE_OB OB
),

CTE_PEDIDO_PRIORIDADE AS (
    SELECT
        NUMERO_OB,
        CASE WHEN PED_ROM IS NOT NULL THEN PED_ROM WHEN PED_COM IS NOT NULL THEN PED_COM ELSE PED_OF END AS NR_PEDIDO,
        CASE WHEN PED_ROM IS NOT NULL THEN ITEM_ROM WHEN PED_COM IS NOT NULL THEN ITEM_COM ELSE ITEM_OF END AS SQ_ITEM
    FROM CTE_PEDIDO_FONTES
),

-- 4. Detalhe do Pedido (NR_PROG)
CTE_PED_DET AS (
    SELECT 
        IPC.PEDIDO, IPC.ITEMPEDIDO, TRIM(IPC.CD_DESENHO_CLIENTE) AS CD_REF_CLT,
        TRIM(PED.PEDIDOCLIENTE) AS NR_PROG, TRIM(IPC.ITEMPEDIDOCLIENTE) AS DS_ITEMPED_CLT
    FROM SGTPRD.ITENSPEDIDOCOMERCIAL IPC
    JOIN SGTPRD.PEDIDOCOMERCIAL PED ON PED.PEDIDO = IPC.PEDIDO
),

-- 5. Peso padrão por artigo cru, das tabelas da antiga VW_ESP_PESO_PADRAO
-- (PESO_PADRAO_PECA e ENG_PRODG_ACABADO), sem passar pela view.
CTE_PESO_PADRAO AS (
    SELECT ART.CDARTIGOCRU AS ARTIGO, PCR.PESO_METROS_PECA AS PESO_PADRAO
    FROM SGTPRD.PESO_PADRAO_PECA PCR
    JOIN SGTPRD.ENGEITEMESTOARTCRU ART ON ART.CDREDUZIDO = PCR.CODIGO_REDUZIDO_PROD
    UNION ALL
    SELECT ART.CDARTIGOCRU, PAC.VLPESO_METROS_PECA
    FROM SGTPRD.ENG_PRODG_ACABADO PAC
    JOIN SGTPRD.ITENS_ESTOQUE AGR ON AGR.REDUZIDO_AGRUPADOR = PAC.REDUZIDO_AGRUPADOR
    JOIN SGTPRD.ENGEITEMESTOARTCRU ART ON ART.CDREDUZIDO = AGR.CODIGO_REDUZIDO
),

-- 6. Última confirmação da OB, só com tabelas (substitui PKGBENF0001.FNC_RETORNA_ULT_CONF_OB).
-- Fase confirmada (status 4) usa o fim da UP (UNIDADE_PROGRAMACAO.DTTEMPOFINAL, UP não
-- excluída); pesada/em execução (2, 3) e confirmada sem UP usam TEMPO_*_CONFIR, em minutos
-- desde 01/01/1996. Conferido em 17/10/2026 contra VW_BNF_OBMONTADA.DATA_ULT_CONF, que chama
-- a função: 760 de 760 OBs abertas iguais.
CTE_ULT_CONF AS (
    SELECT OBF.NUMERO_OB,
        MAX(CASE
            WHEN OBF.STATUS IN (2, 3, 4) AND GREATEST(NVL(OBF.TEMPO_FINAL_CONFIRMA, 0), NVL(OBF.TEMPO_INICIAL_CONFIR, 0)) > 0 THEN
                CASE WHEN OBF.STATUS = 4
                     THEN NVL((SELECT MAX(UNP.DTTEMPOFINAL)
                       FROM SGTPRD.UP_ORDEM_MVTO UPO
                       JOIN SGTPRD.UNIDADE_PROGRAMACAO UNP ON UNP.NUMEROUP = UPO.NUMEROUP
                      WHERE UPO.NUMEROORDEMREAL = OBF.NUMERO_OB
                        AND UPO.SEQUENCIAORDEMREAL = OBF.SEQUENCIA
                        AND UNP.EXCLUIDA = 0), DATE '1996-01-01' + GREATEST(NVL(OBF.TEMPO_FINAL_CONFIRMA, 0), NVL(OBF.TEMPO_INICIAL_CONFIR, 0)) / 1440)
                     ELSE DATE '1996-01-01' + GREATEST(NVL(OBF.TEMPO_FINAL_CONFIRMA, 0), NVL(OBF.TEMPO_INICIAL_CONFIR, 0)) / 1440
                END
        END) AS DT_ULT_CONFIRMACAO
    FROM SGTPRD.OB_FASES OBF
    JOIN CTE_OB OB ON OB.NUMERO_OB = OBF.NUMERO_OB
    GROUP BY OBF.NUMERO_OB
)

SELECT /*+ MONITOR */
    SYSDATE AS Valida_Atualizacao,
    PDET.CD_REF_CLT,
    NF.QT_PC_NF,
    (SELECT LISTAGG(TRIM(UPPER(C.TEXTO)), '' ON OVERFLOW TRUNCATE '' WITHOUT COUNT) WITHIN GROUP (ORDER BY C.ROWID) FROM SGTPRD.OBSERVACAO C WHERE C.CODIGO = OBE.CODIGO_OBSERVACAO) AS OBS_OB,
    OBE.NUMERO_OB AS NR_OB,
    CAST(NULL AS VARCHAR2(100)) AS VALIDACAO_NF,
    DECODE(OBE.STATUS, 0, 0, 1) AS ST_OB_ABERTO,
    PDET.NR_PROG,
    PDET.DS_ITEMPED_CLT,
    (SELECT DECODE(O3.TOTAL_PECAS_CONFIRM,0,(ROUND(O3.KILOS_PROGRAMADOS/NVL((SELECT MAX(PP.PESO_PADRAO) FROM SGTPRD.ENGEITEMESTOARTCRU A2 JOIN CTE_PESO_PADRAO PP ON PP.ARTIGO = A2.CDARTIGOCRU WHERE A2.CDREDUZIDO = O3.CODPRO_REDUZIDO),1),0)),O3.TOTAL_PECAS_CONFIRM) FROM SGTPRD.OB_PRODUTO O3 WHERE O3.NUMERO_OB = OBE.NUMERO_OB) AS QT_PC_PROG,
    (SELECT MAX(OBF.CODIGO_PLACA) FROM SGTPRD.OB_FASES OBF WHERE OBF.NUMERO_OB = OBE.NUMERO_OB) AS NR_KANBAN,
    (SELECT TRIM(I.CODIGO_ALTERNATIVO) FROM SGTPRD.ITENS_ESTOQUE I WHERE I.CODIGO_REDUZIDO = OBE.CODIGO_REDUZIDO) AS CD_ALTERNATIVO,
    (SELECT FF.DESCRICAO_FASE FROM SGTPRD.OB_FASES OBF JOIN SGTPRD.FASES_FLUXO FF ON FF.CODIGO_FASE = OBF.CODIGO_FASE WHERE OBF.NUMERO_OB = OBE.NUMERO_OB AND OBF.SEQUENCIA = (SELECT MAX(SEQUENCIA) FROM SGTPRD.OB_FASES WHERE NUMERO_OB = OBE.NUMERO_OB)) as DS_FASE_ATUAL,
    (SELECT UPPER(ENI.DESCRIPTION) FROM SGTPRD.XX2_ENUMITEM ENI JOIN SGTPRD.XX2_ENUMERATES ENU ON ENU.ID = ENI.IDENUMERATE WHERE ENU.NAME = 'TOBFASESSTATUS' AND ENI.SEQUENCE = (SELECT STATUS FROM SGTPRD.OB_FASES WHERE NUMERO_OB = OBE.NUMERO_OB AND SEQUENCIA = (SELECT MAX(SEQUENCIA) FROM SGTPRD.OB_FASES WHERE NUMERO_OB = OBE.NUMERO_OB))) as DS_ST_FASE_ATUAL,
    ULT.DT_ULT_CONFIRMACAO

FROM CTE_OB OBE
LEFT JOIN CTE_NF_CRU NF ON NF.NR_OB = OBE.NUMERO_OB
LEFT JOIN CTE_PEDIDO_PRIORIDADE PRI ON PRI.NUMERO_OB = OBE.NUMERO_OB
LEFT JOIN CTE_PED_DET PDET ON PDET.PEDIDO = PRI.NR_PEDIDO AND PDET.ITEMPEDIDO = PRI.SQ_ITEM
LEFT JOIN CTE_ULT_CONF ULT ON ULT.NUMERO_OB = OBE.NUMERO_OB

WHERE OBE.STATUS <> 0
  -- 1. Filtro Montagem (Setor 5)
  AND (SELECT MAX(OBMONTADA) FROM SGTPRD.PEDPRODUCAOOB WHERE NUMEROOB = OBE.NUMERO_OB AND SETOR = 5) = 1
  -- 2. Filtro Destino Receita 1 (Fase 40)
  AND (SELECT MAX(DESTINO_RECEITA) FROM SGTPRD.OB_FASES WHERE NUMERO_OB = OBE.NUMERO_OB AND CODIGO_FASE = 40) = 1
  -- 3. Filtro Programação LIKE %T
  AND PDET.NR_PROG LIKE '%T'
ORDER BY PDET.NR_PROG, PDET.DS_ITEMPED_CLT, OBE.NUMERO_OB
