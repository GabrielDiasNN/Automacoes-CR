CORRECAO FUNCIONAL: meta valida sem saida fisica = Atraso; DIAS_DESVIO_PRAZO permanece NULL
TIPO: Painel/KPI
PARAMETROS / BINDS: Janela automatica: 12 meses fechados + mes corrente
GRAO: Mes de emissao da NF + subtipo + comprador + classe de atendimento + tipo + natureza
TABELAS PRINCIPAIS: SGTPRD.NOTAFISCALCAPA, SGTPRD.NOTAFISCALITENS, SGTPRD.BD_FAT_FATURAMENTO, SGTPRD.ITENS_ESTOQUE, SGTPRD.NATUREZA_OPERACAO, SGTPRD.PRODUTO_ROMANEIO, SGTPRD.PEDIDOCOMERCIAL, SGTPRD.ITENSPEDIDOCOMERCIAL, SGTPRD.COML_SUBTIPOPED, SGTPRD.COML_TIPOSPEDIDOS, SGTPRD.PESSOASFJ, SGTPRD.ROMANEIO, SGTPRD.GERAPECAROMSAIDA, SGTPRD.GERAPECASPRODUTO
SEMANTICA: Data efetiva = ROMANEIO.DATA_EXPEDICAO (saida fisica da empresa); prazo comparado = ITENSPEDIDOCOMERCIAL.DATAEXPEDIREM. Mede atendimento ao prazo de expedicao, nao chegada ao cliente.
GRANULARIDADE INTERNA: FATOS_FILTRADOS/BASE_FATURAMENTO preservam IDPNS + IDPRODUTO_ROMANEIO; contagem agregada de pecas por NUMERO_ROMANEIO + PNS.CDREDUZIDO em subconsulta escalar; DATA_EXPEDICAO numerica YYYYMMDD.
ARQUITETURA V2.2 (ESTABILIZADA): fatos fisicos filtrados estreitos com decomposicao temporal disjunta (UNION ALL), enriquecimento comercial uma vez, COUNT de pecas por chave sem expandir a base principal.
ESTABILIDADE: 5/5 execucoes consecutivas validas comprovadas (04/10/2026), 0 erros ORA-00028, Golden Hash f51ad8d51ecfbcb25b139589ee8e639100bcf4e8215445c2e8cbe6d3d0532fa7.
