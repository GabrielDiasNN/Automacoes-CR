           CASE WHEN UNI.ORDEM LIKE '00%' THEN
                     CASE UNI.ORDEM
                          WHEN '00A' THEN '% PROPORÇÃO NORMAL NA PRODUÇÃO DE TINTURARIA'
                          WHEN '00B' THEN '% REPROCESSO TOTAL / PRODUÇÃO NORMAL'
                          WHEN '00C' THEN 'SUBCLASSIFICAÇÃO DO REPROCESSO PENDENTE PCP'
                          WHEN '00D' THEN '% ACABADO MENSAL / TINGIDO MENSAL'
                          WHEN '00E' THEN '% ACABADO MENSAL / MONTADO MENSAL'
                          WHEN '00F' THEN 'KG / PARTIDA (TINTURARIA)'
                     END
                WHEN UNI.ORDEM IN ('04A', '04B', '04C') THEN '% CARGA NOMINAL BARCA'
                WHEN UNI.ORDEM = '04E' THEN '% REPROCESSO TOTAL S/ PRODUÇÃO NORMAL'
                WHEN UNI.ORDEM = '04F' THEN 'SUBCLASSIFICAÇÃO DO REPROCESSO PENDENTE PCP'
                WHEN UNI.ORDEM IN ('04H', '04I', '04J', '04K') THEN '% MIX DE CORES'
                WHEN UNI.ORDEM IN ('04L', '04M', '04N') THEN '% PARTICIPAÇÃO TURNO TINTURARIA'
                WHEN UNI.ORDEM IN ('06A', '06B') THEN '% CARGA SECADOR (ÓLEO / VAPOR)'
                WHEN UNI.ORDEM IN ('11A', '11B') THEN '% CARGA RAMA (RM 01 / RM 02)'
                WHEN UNI.ORDEM IN ('12D', '12E', '12F') THEN '% PARTICIPAÇÃO TURNO ACABAMENTO'
                WHEN UNI.ORDEM IN ('90', '91', '92') THEN '% S/ TOTAL PRODUTO ACABADO'
                WHEN UNI.ORDEM = '93' THEN '% PROPORÇÃO TUBULAR / RAMADO'
                WHEN UNI.ORDEM = '12B' THEN 'QUANTIDADE DE PEÇAS / ROLOS'
                WHEN UNI.ORDEM = '12C' THEN 'KG MÉDIO POR PEÇA ACABADA'
           END AS TIPO_METRICA,
           UNI.TEMPO_PREV_HORAS,
           UNI.TEMPO_REAL_HORAS,
           TO_NUMBER(NULL) AS DESVIO_TEMPO_MIN,
           TO_NUMBER(NULL) AS EFIC_TEMPO_PCT,
           CASE WHEN UNI.TEM_FATO = 1 AND UNI.ORDEM IN ('04G', '12A') THEN
                ROUND((REF.KG_TING_TOT - REF.ACAB_KG_TOT), 2)
           END AS SALDO_WIP_TING_MENOS_EMB_KG,
            CASE WHEN UNI.UNIDADE_METRICA = '%' THEN
                      ROUND(UNI.QT_KG - LAG(UNI.QT_KG) OVER (PARTITION BY UNI.ORDEM ORDER BY UNI.DT_MES), 2)
                 ELSE
                      ROUND((UNI.QT_KG - LAG(UNI.QT_KG) OVER (PARTITION BY UNI.ORDEM ORDER BY UNI.DT_MES))
                            / NULLIF(LAG(UNI.QT_KG) OVER (PARTITION BY UNI.ORDEM ORDER BY UNI.DT_MES), 0) * 100, 1)
            END AS VAR_MOM,
            CASE WHEN UNI.UNIDADE_METRICA = '%' THEN
                      'PONTOS PERCENTUAIS (p.p.)'
                 ELSE
                      'PERCENTUAL (%)'
            END AS TIPO_VAR_MOM,
            ROUND(AVG(UNI.QT_KG) OVER (PARTITION BY UNI.ORDEM ORDER BY UNI.DT_MES ROWS BETWEEN 2 PRECEDING AND CURRENT ROW), 2) AS MEDIA_MOVEL_3M,
            UNI.UNIDADE_METRICA
       FROM UNIFICADO_COMPLETO UNI
      LEFT JOIN REFS_MENSAIS REF ON REF.DT_MES = UNI.DT_MES
      LEFT JOIN DIAS_FASE_LINHA DLF ON DLF.DT_MES = UNI.DT_MES AND DLF.STATUS_MES = UNI.STATUS_MES AND DLF.ORDEM = UNI.ORDEM
      LEFT JOIN DIAS_ACABADO_LINHA DLA ON DLA.DT_MES = UNI.DT_MES AND DLA.STATUS_MES = UNI.STATUS_MES AND DLA.ORDEM = UNI.ORDEM
)
SELECT COMPETENCIA,
       STATUS_MES,
       ORDEM,
       CATEGORIA,
       INDICADOR_FABRIL,
       QT_KG,
       DIAS_PRODUTIVOS,
       MEDIA_KG_DIA,
       QT_PARTIDAS,
       CARGA_MEDIA_KG,
       PERC_ESPECIFICO,
       TIPO_METRICA,
       TEMPO_PREV_HORAS,
       TEMPO_REAL_HORAS,
       DESVIO_TEMPO_MIN,
       EFIC_TEMPO_PCT,
       SALDO_WIP_TING_MENOS_EMB_KG,
       VAR_MOM,
       TIPO_VAR_MOM,
       MEDIA_MOVEL_3M,
       UNIDADE_METRICA
  FROM CALCULADO
 ORDER BY ORDEM ASC, COMPETENCIA DESC;
