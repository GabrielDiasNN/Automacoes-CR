/* =============================================================================
OBJETIVO: Série Temporal Histórica de Produção por Fase e Indicadores Fabris (Últimos 12 Meses + Mês Aberto)
          Modelo Fato / Série Longa (Ideal para Dashboards FastAPI, Power BI e Análises Históricas).
DOMÍNIO: 09_pcp_kpis_gestao
DESTINO: Ingestão de Dados Analíticos, Dashboards Gerenciais e APIs do Hub de Automações.
TIPO: SELECT (Painel Analítico / Histórico Contínuo)
PARÂMETROS / BINDS:
  - Janela temporal automática: Últimos 12 meses fechados + Mês corrente em aberto (TRUNC(ADD_MONTHS(SYSDATE, -12), 'MM') até SYSDATE).
CUIDADOS OPERACIONAIS & DIRETRIZES DE ENGENHARIA ORACLE:
  - Zero Views: Junção direta pelas tabelas físicas com índices operacionais (sem views legadas).
  - Pré-agregação por dimensões operacionais; ganhos de buffer gets/tempo ainda dependem de medição Oracle.
  - Produção de Acabado Oficial por Peça: Dados de produto acabado extraídos da movimentação oficial por peça
    (SGTPRD.BD_PRD_MOVPROD com NUM_TIPO_MOVIMENTO = 37 e CODIGO IN (1, 8)), trazendo volume em kg, quantidade de peças/rolos
    e peso médio por peça, conforme padrão canônico do PCP.
  - Reprocesso total: volume identificado pelo cadastro oficial DESTINO → GRUPO_DESTINO.TIPO_DESTINO = 1.
    Subdivisões por origem permanecem pendentes de regra oficial do PCP.
  - QT_KG é um campo legado de valor da métrica; interprete a unidade efetiva por UNIDADE_METRICA.
  - Dias Produtivos Segmentados: Dias produtivos de Tinturaria (DIAS_TING) e de Acabamento (DIAS_ACABADO) segregados por processo.
  - Métricas Avançadas de Série Temporal: Variação Mês a Mês (MoM % para volumes e MoM p.p. para taxas), Média Móvel 3M
    e balanço mensal dos fluxos tingido e acabado (sem comprovação de estoque WIP).
  - TEMPO_PREV_HORAS, desvio e eficiência permanecem nulos até o PCP confirmar unidade/ponderação de TEMPO_RECEITA.
============================================================================= */

WITH JANELA AS (
    SELECT ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -12) AS DT_INICIO,
           TRUNC(SYSDATE) + 1                    AS DT_FIM,
           TRUNC(SYSDATE, 'MM')                  AS DT_MES_ABERTO
      FROM DUAL
),
MESES AS (
    SELECT ADD_MONTHS(JAN.DT_MES_ABERTO, LEVEL - 13) AS DT_MES,
           CASE WHEN LEVEL = 13 THEN 'EM ABERTO' ELSE 'FECHADO' END AS STATUS_MES
      FROM JANELA JAN
    CONNECT BY LEVEL <= 13
),
FASES_RAW AS (
    -- Junção UPR -> UOM -> OB_FASES feita uma vez só (13 meses, fases do painel);
    -- FASES_DIA_AGR e PARTIDAS_TING_MENSAL leem daqui.
    SELECT /*+ MATERIALIZE */
           UPR.DTPRODFIM,
           UPR.NUMERO_MAQUINA,
           UPR.NRTURNOFIM,
           UPR.DTTEMPOINICONFIRMADO,
           UPR.DTTEMPOFINALCONFIRMA,
           OBF.CODIGO_FASE,
           OBF.DESTINO_RECEITA,
           OBF.GRUPO_DEFEITO,
           OBF.KILOS_PRODUZIDOS,
           OBF.ID_LIGA_CADREC_ITEMR,
           OBF.NUMEROORDEMMOVIMENTO,
           OBF.SEQUENCIAORDEMMOVIME
      FROM SGTPRD.UNIDADE_PROGRAMACAO UPR
      JOIN SGTPRD.UP_ORDEM_MVTO UOM ON UOM.NUMEROUP = UPR.NUMEROUP
      JOIN SGTPRD.OB_FASES OBF ON OBF.NUMERO_OB = UOM.NUMEROORDEMREAL
                              AND OBF.SEQUENCIA = UOM.SEQUENCIAORDEMREAL
     CROSS JOIN JANELA JAN
     WHERE UPR.SETOR = 5 AND UPR.EXCLUIDA = 0 AND UPR.TIPOUP = 0 AND UPR.STATUS = 0
       AND UPR.DTPRODFIM >= JAN.DT_INICIO AND UPR.DTPRODFIM < JAN.DT_FIM
       AND OBF.CODIGO_FASE IN (10, 20, 26, 40, 50, 55, 60, 65, 70, 80, 90, 100, 110)
),
FASES_DIA_AGR AS (
    -- Base única no grão diário (07/10/2026). Antes BASE_FASES_AGR, FASES_DIA_BASE
    -- e DIAS_TING_MENSAL refaziam a mesma junção de 13 meses três vezes e a
    -- consulta passava da janela de rede (~4-6 s). As três derivam desta: somas e
    -- o tempo ponderado (numerador/denominador) agregam do dia para o mês sem perda.
    SELECT /*+ MATERIALIZE */
           TRUNC(R.DTPRODFIM, 'MM') AS DT_MES,
           CASE WHEN R.DTPRODFIM >= JAN.DT_MES_ABERTO THEN 'EM ABERTO' ELSE 'FECHADO' END AS STATUS_MES,
           TRUNC(R.DTPRODFIM) AS DIA,
           R.CODIGO_FASE,
           R.DESTINO_RECEITA AS DESTINO_RECEITA,
           GD.TIPO_DESTINO,
           TRIM(R.GRUPO_DEFEITO) AS GRUPO_DEFEITO,
           MAQ.GRUPO AS GRUPO_MAQUINA,
           R.NUMERO_MAQUINA,
           R.NRTURNOFIM AS TURNO,
           CL.CODIGO_CLASSIFICACAO,
           SUM(R.KILOS_PRODUZIDOS) AS KILOS_PRODUZIDOS,
           SUM(CASE WHEN R.DTTEMPOFINALCONFIRMA > R.DTTEMPOINICONFIRMADO
                    THEN R.KILOS_PRODUZIDOS * (R.DTTEMPOFINALCONFIRMA - R.DTTEMPOINICONFIRMADO) * 24 END) AS TEMPO_NUM,
           SUM(CASE WHEN R.DTTEMPOFINALCONFIRMA > R.DTTEMPOINICONFIRMADO THEN R.KILOS_PRODUZIDOS END) AS TEMPO_DEN
      FROM FASES_RAW R
      LEFT JOIN SGTPRD.MAQUINA           MAQ ON MAQ.NUMERO_MAQUINA = R.NUMERO_MAQUINA AND MAQ.SETOR = 5
      LEFT JOIN SGTPRD.DESTINO           DST ON DST.DESTINO = R.DESTINO_RECEITA
      LEFT JOIN SGTPRD.GRUPO_DESTINO     GD ON GD.CODIGO_GRUPO = DST.CODIGO_GRUPO
      LEFT JOIN SGTPRD.LIGA_CADREC_ITEMREC LCR ON LCR.ID_LIGA_CADREC_ITEMR = R.ID_LIGA_CADREC_ITEMR AND R.CODIGO_FASE = 40
      LEFT JOIN SGTPRD.CADASTRO_RECEITAS CR  ON CR.CODIGO_REDUZIDO_RECE = LCR.CODIGO_REDUZIDO_RECE
      LEFT JOIN SGTPRD.CLASSIFICACAO_COR CL  ON CL.CODIGO_CLASSIFICACAO = CR.CODIGO_CLASSIFICACAO
     CROSS JOIN JANELA                   JAN
     GROUP BY TRUNC(R.DTPRODFIM, 'MM'),
              CASE WHEN R.DTPRODFIM >= JAN.DT_MES_ABERTO THEN 'EM ABERTO' ELSE 'FECHADO' END,
              TRUNC(R.DTPRODFIM),
              R.CODIGO_FASE,
              R.DESTINO_RECEITA,
              GD.TIPO_DESTINO,
              TRIM(R.GRUPO_DEFEITO),
              MAQ.GRUPO,
              R.NUMERO_MAQUINA,
              R.NRTURNOFIM,
              CL.CODIGO_CLASSIFICACAO
),
BASE_FASES_AGR AS (
    SELECT /*+ MATERIALIZE */ DT_MES,
           STATUS_MES,
           CODIGO_FASE,
           DESTINO_RECEITA,
           TIPO_DESTINO,
           GRUPO_DEFEITO,
           GRUPO_MAQUINA,
           NUMERO_MAQUINA,
           TURNO,
           CODIGO_CLASSIFICACAO,
           SUM(KILOS_PRODUZIDOS) AS KILOS_PRODUZIDOS,
           TO_NUMBER(NULL) AS QT_PARTIDAS,
           TO_NUMBER(NULL) AS DIAS_PRODUTIVOS,
           TO_NUMBER(NULL) AS TEMPO_PREV_HORAS,
           ROUND(SUM(TEMPO_NUM) / NULLIF(SUM(TEMPO_DEN), 0), 2) AS TEMPO_REAL_HORAS
      FROM FASES_DIA_AGR
     GROUP BY DT_MES, STATUS_MES, CODIGO_FASE, DESTINO_RECEITA, TIPO_DESTINO,
              GRUPO_DEFEITO, GRUPO_MAQUINA, NUMERO_MAQUINA, TURNO, CODIGO_CLASSIFICACAO
),
FASES_DIA_BASE AS (
    SELECT /*+ MATERIALIZE */ DISTINCT DT_MES, STATUS_MES, DIA, CODIGO_FASE, DESTINO_RECEITA, TIPO_DESTINO,
           GRUPO_DEFEITO, GRUPO_MAQUINA, NUMERO_MAQUINA, TURNO, CODIGO_CLASSIFICACAO
      FROM FASES_DIA_AGR
),
DIAS_FASE_LINHA AS (
    SELECT DT_MES, STATUS_MES, ORDEM, COUNT(DISTINCT DIA) AS DIAS_PRODUTIVOS
      FROM (
            SELECT DT_MES, STATUS_MES, DIA, '01' AS ORDEM FROM FASES_DIA_BASE WHERE CODIGO_FASE = 10
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '02' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 20
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '03' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 26
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04A' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND GRUPO_MAQUINA = 'TG001'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04B' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND GRUPO_MAQUINA = 'TG002'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04C' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND GRUPO_MAQUINA = 'TG003'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04D' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04E' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND TIPO_DESTINO = 1
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04G' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04H' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO IN (1, 6, 7, 10, 18)
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04I' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO = 2
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04J' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO IN (5, 14)
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04K' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO IN (3, 8, 9, 11, 12, 15)
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04L' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND TURNO = 1
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04M' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND TURNO = 2
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '04N' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND TURNO = 3
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '05A' FROM FASES_DIA_BASE WHERE CODIGO_FASE IN (50, 55) AND NUMERO_MAQUINA = '000000HD01'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '05B' FROM FASES_DIA_BASE WHERE CODIGO_FASE IN (50, 55) AND NUMERO_MAQUINA = '000000HD02'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '05C' FROM FASES_DIA_BASE WHERE CODIGO_FASE IN (50, 55) AND NUMERO_MAQUINA = '000000HD03'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '05D' FROM FASES_DIA_BASE WHERE CODIGO_FASE IN (50, 55)
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '06A' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 60 AND NUMERO_MAQUINA = '000000SC01'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '06B' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 60 AND NUMERO_MAQUINA = '000000SC02'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '06C' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 60
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '07' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 65
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '08' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 70
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '09' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 80
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '10' FROM FASES_DIA_BASE WHERE CODIGO_FASE = 90
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '11A' FROM FASES_DIA_BASE WHERE CODIGO_FASE IN (100, 110) AND NUMERO_MAQUINA = '000000RM01'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '11B' FROM FASES_DIA_BASE WHERE CODIGO_FASE IN (100, 110) AND NUMERO_MAQUINA = '000000RM02'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '11C' FROM FASES_DIA_BASE WHERE CODIGO_FASE IN (100, 110)
      ) LINHAS
     GROUP BY DT_MES, STATUS_MES, ORDEM
),
DIAS_TING_MENSAL AS (
    SELECT DT_MES,
           STATUS_MES,
           COUNT(DISTINCT DIA) AS DIAS_TING
      FROM FASES_DIA_AGR
     WHERE CODIGO_FASE = 40
     GROUP BY DT_MES, STATUS_MES
),
PARTIDAS_TING_MENSAL AS (
    SELECT TRUNC(R.DTPRODFIM, 'MM') AS DT_MES,
           CASE WHEN R.DTPRODFIM >= JAN.DT_MES_ABERTO THEN 'EM ABERTO' ELSE 'FECHADO' END AS STATUS_MES,
           COUNT(DISTINCT R.NUMEROORDEMMOVIMENTO || '~' || R.SEQUENCIAORDEMMOVIME) AS PART_TING_TOT,
           COUNT(DISTINCT CASE WHEN R.DESTINO_RECEITA = 1 THEN R.NUMEROORDEMMOVIMENTO || '~' || R.SEQUENCIAORDEMMOVIME END) AS PART_TING_NORMAL,
           COUNT(DISTINCT CASE WHEN R.DESTINO_RECEITA = 1 AND MAQ.GRUPO = 'TG001' THEN R.NUMEROORDEMMOVIMENTO || '~' || R.SEQUENCIAORDEMMOVIME END) AS PART_B1000,
           COUNT(DISTINCT CASE WHEN R.DESTINO_RECEITA = 1 AND MAQ.GRUPO = 'TG002' THEN R.NUMEROORDEMMOVIMENTO || '~' || R.SEQUENCIAORDEMMOVIME END) AS PART_B600,
           COUNT(DISTINCT CASE WHEN R.DESTINO_RECEITA = 1 AND MAQ.GRUPO = 'TG003' THEN R.NUMEROORDEMMOVIMENTO || '~' || R.SEQUENCIAORDEMMOVIME END) AS PART_B2000
      FROM FASES_RAW R
      LEFT JOIN SGTPRD.MAQUINA MAQ ON MAQ.NUMERO_MAQUINA = R.NUMERO_MAQUINA AND MAQ.SETOR = 5
      CROSS JOIN JANELA JAN
     WHERE R.CODIGO_FASE = 40
       AND R.NUMEROORDEMMOVIMENTO IS NOT NULL AND R.SEQUENCIAORDEMMOVIME IS NOT NULL
     GROUP BY TRUNC(R.DTPRODFIM, 'MM'),
              CASE WHEN R.DTPRODFIM >= JAN.DT_MES_ABERTO THEN 'EM ABERTO' ELSE 'FECHADO' END
),
ACABADO_MOV_DIA AS (
    -- Agrega os movimentos antes das junções de cadastro (fluxo e estampado só
    -- dependem do reduzido): a junção com ITENS_ESTOQUE/LIKE roda sobre milhares
    -- de linhas agregadas em vez de cada peça de 12 meses.
    SELECT /*+ MATERIALIZE */
           TRUNC(MVP.PRODUCAO_DATA) AS DIA,
           MVP.PRODUCAO_TURNO AS TURNO,
           MVP.REDUZIDO_ITEM,
           CASE WHEN MVP.ESTAMPADO = 1 THEN 1 ELSE 0 END AS FLAG_ESTAMPADO,
           SUM(MVP.QUANTIDADE_REAL) AS QUANTIDADE_REAL,
           COUNT(MVP.IDPECASPRODUTO) AS QT_PECAS
      FROM SGTPRD.BD_PRD_MOVPROD MVP
     WHERE MVP.NUM_TIPO_MOVIMENTO = 37
       AND MVP.CODIGO IN (1, 8)
       AND MVP.PRODUCAO_DATA >= ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -12)
       AND MVP.PRODUCAO_DATA <  TRUNC(SYSDATE) + 1
     GROUP BY TRUNC(MVP.PRODUCAO_DATA),
              MVP.PRODUCAO_TURNO,
              MVP.REDUZIDO_ITEM,
              CASE WHEN MVP.ESTAMPADO = 1 THEN 1 ELSE 0 END
),
ACABADO_DIA_AGR AS (
    SELECT /*+ MATERIALIZE */
           TRUNC(M.DIA, 'MM') AS DT_MES,
           CASE WHEN M.DIA >= TRUNC(SYSDATE, 'MM') THEN 'EM ABERTO' ELSE 'FECHADO' END AS STATUS_MES,
           M.DIA,
           M.TURNO,
           TRIM(E9.CDNIVELGENERICO) AS FLUXO,
           CASE WHEN M.FLAG_ESTAMPADO = 1 OR UPPER(ITE.DESCRICAO) LIKE '%ESTAMP%' THEN 1 ELSE 0 END AS IS_ESTAMPADO,
           SUM(M.QUANTIDADE_REAL) AS QUANTIDADE_REAL,
           SUM(M.QT_PECAS) AS QT_PECAS
      FROM ACABADO_MOV_DIA M
      LEFT JOIN SGTPRD.ENGEITEMESTONIVELGE9 E9 ON E9.CDREDUZIDO = M.REDUZIDO_ITEM
      LEFT JOIN SGTPRD.ITENS_ESTOQUE        ITE ON ITE.CODIGO_REDUZIDO = M.REDUZIDO_ITEM
     GROUP BY TRUNC(M.DIA, 'MM'),
              CASE WHEN M.DIA >= TRUNC(SYSDATE, 'MM') THEN 'EM ABERTO' ELSE 'FECHADO' END,
              M.DIA,
              M.TURNO,
              TRIM(E9.CDNIVELGENERICO),
              CASE WHEN M.FLAG_ESTAMPADO = 1 OR UPPER(ITE.DESCRICAO) LIKE '%ESTAMP%' THEN 1 ELSE 0 END
),
BASE_ACABADO_AGR AS (
    SELECT DT_MES,
           STATUS_MES,
           TURNO,
           FLUXO,
           IS_ESTAMPADO,
           SUM(QUANTIDADE_REAL) AS QUANTIDADE_REAL,
           SUM(QT_PECAS) AS QT_PECAS,
           TO_NUMBER(NULL) AS DIAS_PRODUTIVOS
      FROM ACABADO_DIA_AGR
     GROUP BY DT_MES, STATUS_MES, TURNO, FLUXO, IS_ESTAMPADO
),
DIAS_ACABADO_MENSAL AS (
    SELECT DT_MES,
           COUNT(DISTINCT DIA) AS DIAS_ACABADO
      FROM ACABADO_DIA_AGR
     GROUP BY DT_MES
),
DIAS_ACABADO_BASE AS (
    SELECT DT_MES, STATUS_MES, DIA, TURNO, FLUXO, IS_ESTAMPADO
      FROM ACABADO_DIA_AGR
),
DIAS_ACABADO_LINHA AS (
    SELECT DT_MES, STATUS_MES, ORDEM, COUNT(DISTINCT DIA) AS DIAS_PRODUTIVOS
      FROM (
            SELECT DT_MES, STATUS_MES, DIA, '12A' AS ORDEM FROM DIAS_ACABADO_BASE
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '12D' FROM DIAS_ACABADO_BASE WHERE TURNO = 1
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '12E' FROM DIAS_ACABADO_BASE WHERE TURNO = 2
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '12F' FROM DIAS_ACABADO_BASE WHERE TURNO = 3
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '90' FROM DIAS_ACABADO_BASE WHERE FLUXO = 'T'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '91' FROM DIAS_ACABADO_BASE WHERE FLUXO = 'R'
            UNION ALL SELECT DT_MES, STATUS_MES, DIA, '92' FROM DIAS_ACABADO_BASE WHERE IS_ESTAMPADO = 1
      ) LINHAS
     GROUP BY DT_MES, STATUS_MES, ORDEM
),
FASES_MENSAIS AS (
    SELECT F.DT_MES,
           F.STATUS_MES,
           SUM(CASE WHEN F.CODIGO_FASE = 10 THEN F.KILOS_PRODUZIDOS END) AS KG_MONT,
           SUM(CASE WHEN F.CODIGO_FASE = 40 AND F.DESTINO_RECEITA = 1 THEN F.KILOS_PRODUZIDOS END) AS KG_TING_NORM,
           SUM(CASE WHEN F.CODIGO_FASE = 40 AND F.TIPO_DESTINO = 1 THEN F.KILOS_PRODUZIDOS END) AS KG_TING_REP_TOTAL,
           SUM(CASE WHEN F.CODIGO_FASE = 40 THEN F.KILOS_PRODUZIDOS END) AS KG_TING_TOT,
           SUM(CASE WHEN F.CODIGO_FASE = 60 THEN F.KILOS_PRODUZIDOS END) AS KG_SECADOR_TOT,
           SUM(CASE WHEN F.CODIGO_FASE IN (100, 110) THEN F.KILOS_PRODUZIDOS END) AS KG_RAMA_TOT
      FROM BASE_FASES_AGR F
     GROUP BY F.DT_MES, F.STATUS_MES
),
ACABADO_MENSAL AS (
    SELECT B.DT_MES,
           B.ACAB_KG_TOT,
           B.ACAB_PECAS_TOT,
           D.DIAS_ACABADO,
           B.ACAB_KG_TUBULAR,
           B.ACAB_KG_RAMADO
      FROM (
            SELECT DT_MES,
                   SUM(QUANTIDADE_REAL) AS ACAB_KG_TOT,
                   SUM(QT_PECAS) AS ACAB_PECAS_TOT,
                   SUM(CASE WHEN FLUXO = 'T' THEN QUANTIDADE_REAL END) AS ACAB_KG_TUBULAR,
                   SUM(CASE WHEN FLUXO = 'R' THEN QUANTIDADE_REAL END) AS ACAB_KG_RAMADO
              FROM BASE_ACABADO_AGR
             GROUP BY DT_MES
      ) B
      LEFT JOIN DIAS_ACABADO_MENSAL D ON D.DT_MES = B.DT_MES
),
REFS_MENSAIS AS (
    SELECT M.DT_MES,
           M.STATUS_MES,
           F.KG_MONT,
           F.KG_TING_NORM,
           F.KG_TING_REP_TOTAL,
           F.KG_TING_TOT,
           PM.PART_TING_TOT,
           PM.PART_TING_NORMAL,
           PM.PART_B1000,
           PM.PART_B600,
           PM.PART_B2000,
           DT.DIAS_TING,
           F.KG_SECADOR_TOT,
           F.KG_RAMA_TOT,
           A.ACAB_KG_TOT,
           A.ACAB_PECAS_TOT,
           A.DIAS_ACABADO,
           A.ACAB_KG_TUBULAR,
           A.ACAB_KG_RAMADO
      FROM MESES M
      LEFT JOIN FASES_MENSAIS F ON F.DT_MES = M.DT_MES AND F.STATUS_MES = M.STATUS_MES
      LEFT JOIN ACABADO_MENSAL A ON A.DT_MES = M.DT_MES
      LEFT JOIN DIAS_TING_MENSAL DT ON DT.DT_MES = M.DT_MES AND DT.STATUS_MES = M.STATUS_MES
      LEFT JOIN PARTIDAS_TING_MENSAL PM ON PM.DT_MES = M.DT_MES AND PM.STATUS_MES = M.STATUS_MES
),
EXPANDIDO AS (
    SELECT DT_MES, STATUS_MES, '01'  AS ORDEM, 'FASE PRODUTIVA' AS CATEGORIA, '01 - MONTAGEM DE LOTE (CRU)' AS LINHA, DIAS_PRODUTIVOS, QT_PARTIDAS, KILOS_PRODUZIDOS, TO_NUMBER(NULL) AS TEMPO_RECEITA, TO_NUMBER(NULL) AS TEMPO_REAL_HORAS, TO_NUMBER(NULL) AS CAPACIDADE_NOMINAL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 10
    UNION ALL
    SELECT DT_MES, STATUS_MES, '02' , 'FASE PRODUTIVA', '02 - REVISÃO MALHA CRUA', DIAS_PRODUTIVOS, QT_PARTIDAS, KILOS_PRODUZIDOS, NULL, NULL, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 20
    UNION ALL
