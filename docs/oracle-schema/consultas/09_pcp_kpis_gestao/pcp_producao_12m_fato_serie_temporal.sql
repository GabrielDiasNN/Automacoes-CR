CALCULADO AS (
    SELECT TO_CHAR(UNI.DT_MES, 'YYYY-MM')     AS COMPETENCIA,
           UNI.DT_MES,
           UNI.STATUS_MES,
           UNI.ORDEM,
           UNI.CATEGORIA,
           UNI.LINHA                           AS INDICADOR_FABRIL,
           CASE WHEN UNI.TEM_FATO = 0 OR UNI.ORDEM IN ('00C', '04F') THEN NULL
                ELSE ROUND(NVL(UNI.QT_KG, 0), 2)
           END AS QT_KG,
           CASE WHEN UNI.TEM_FATO = 0 THEN NULL
                ELSE COALESCE(UNI.DIAS_PRODUTIVOS, DLF.DIAS_PRODUTIVOS, DLA.DIAS_PRODUTIVOS)
           END AS DIAS_PRODUTIVOS,
            CASE WHEN UNI.TEM_FATO = 1 AND UNI.UNIDADE_METRICA = 'kg' THEN
                 ROUND(NVL(UNI.QT_KG, 0) / NULLIF(COALESCE(UNI.DIAS_PRODUTIVOS, DLF.DIAS_PRODUTIVOS, DLA.DIAS_PRODUTIVOS), 0), 2)
            END AS MEDIA_KG_DIA,
           CASE WHEN UNI.TEM_FATO = 0 THEN NULL
                WHEN UNI.ORDEM IN ('00A', '00F', '04G') THEN REF.PART_TING_TOT
                WHEN UNI.ORDEM = '04A' THEN REF.PART_B1000
                WHEN UNI.ORDEM = '04B' THEN REF.PART_B600
                WHEN UNI.ORDEM = '04C' THEN REF.PART_B2000
                WHEN UNI.ORDEM = '04D' THEN REF.PART_TING_NORMAL
                ELSE TO_NUMBER(NULL)
           END AS QT_PARTIDAS,
           CASE WHEN UNI.TEM_FATO = 0 THEN NULL
                WHEN UNI.ORDEM = '00F' THEN
                     UNI.QT_KG
                WHEN UNI.ORDEM = '04A' THEN ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.PART_B1000, 0), 0)
                WHEN UNI.ORDEM = '04B' THEN ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.PART_B600, 0), 0)
                WHEN UNI.ORDEM = '04C' THEN ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.PART_B2000, 0), 0)
                WHEN UNI.ORDEM = '04D' AND REF.PART_TING_NORMAL > 0 THEN
                     ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.PART_TING_NORMAL, 0), 0)
                WHEN UNI.ORDEM = '04G' AND REF.PART_TING_TOT > 0 THEN
                     ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.PART_TING_TOT, 0), 0)
           END AS CARGA_MEDIA_KG,
           CASE WHEN UNI.TEM_FATO = 0 THEN NULL
                WHEN UNI.ORDEM IN ('00A', '00B', '00C', '00D', '00E', '93') THEN
                     UNI.QT_KG
