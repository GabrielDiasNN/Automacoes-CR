    SELECT '04M', '[TURNO TINTURARIA] 2º TURNO', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND TURNO = 2
    UNION ALL
    SELECT '04N', '[TURNO TINTURARIA] 3º TURNO', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND TURNO = 3
    UNION ALL
    SELECT '05A', '05A - HIDROEXTRATORA 01', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, NULL, NULL, NULL, NULL, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE IN (50, 55) AND NUMERO_MAQUINA = '000000HD01'
    UNION ALL
    SELECT '05B', '05B - HIDROEXTRATORA 02', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, NULL, NULL, NULL, NULL, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE IN (50, 55) AND NUMERO_MAQUINA = '000000HD02'
    UNION ALL
    SELECT '05C', '05C - HIDROEXTRATORA 03', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, NULL, NULL, NULL, NULL, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE IN (50, 55) AND NUMERO_MAQUINA = '000000HD03'
    UNION ALL
