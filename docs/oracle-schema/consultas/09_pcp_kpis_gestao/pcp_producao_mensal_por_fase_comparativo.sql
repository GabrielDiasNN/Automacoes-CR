/* =============================================================================
OBJETIVO: Consulta Mensal de Produção por Fase (Comparativo Mês Atual vs Mesmo Mês Ano Anterior - YoY)
          com Indicadores de Gestão Fabril (Acerto de 1ª / RFT, Carga Média de Barca,
          Escoamento Acabamento/Tinturaria, Rendimento Global, Ritmo Diário, Mix de Cores, Tempos e Turnos).
DOMÍNIO: 09_pcp_kpis_gestao
DESTINO: Divulgação em Grupo de WhatsApp de Líderes e Gestão Fabril (Costa Rica Malhas).
TIPO: SELECT (Painel Analítico / Operacional)
PARÂMETROS / BINDS:
  - Formato padrão de data: DD-MM-AAAA
  - Configurado via CTE JANELA para comparar mês fechado com mesmo mês do ano anterior (YoY).
CUIDADOS OPERACIONAIS & DIRETRIZES DE ENGENHARIA ORACLE:
  - Zero Views: Junção direta pelas tabelas físicas com índices operacionais (sem views legadas).
  - Pré-Agregação de Alta Performance: Redução de ~50k apontamentos brutos para blocos pré-agregados,
    reduzindo a cardinalidade submetida aos joins dimensionais.
  - Produção de Acabado Oficial por Peça: Dados de produto acabado extraídos da movimentação oficial por peça
    (SGTPRD.BD_PRD_MOVPROD com NUM_TIPO_MOVIMENTO = 37 e CODIGO IN (1, 8)), trazendo volume em kg, quantidade de peças/rolos
    e peso médio por peça, conforme padrão canônico do PCP.
  - Joins Condicionais por Fase: Junções de receitas restritas à Fase 40.
  - Regra de Reprocesso: DESTINO_RECEITA IN (2, 4).
      * Grupo de Defeito 1 (Beneficiamento), 3 (Benef. Acabamento) e 4: Reprocesso Beneficiamento (Interno).
      * Demais Grupos: Reprocesso Outros Setores (Malharia, Fiação, Facção - Externo).
  - Controle de Mix de Cores & Gráficos de Tingimento (Fase 40):
      * 1. Claras / Branco / Marfim: Gráficos curtos (~1,5h a 3,0h)
      * 2. Cores Médias: Gráficos intermediários (~3,5h a 4,5h)
      * 3. Cores Escuras & Preto: Gráficos longos (~4,5h a 5,5h)
      * 4. Especiais & 2 Fibras: Gráficos extra-longos (~5,5h a 8,0h)
  - Nomenclatura Operacional Normalizada (Chão de Fábrica):
      * 00A a 00F: Indicadores de Gestão (Acerto de 1ª RFT, Reprocesso Interno/Externo, Escoamento, Balanço de Fluxo Embalado/Cru, Carga Média)
       * Nota Metodológica KPI 00E: Indicador mensal de balanço de fluxo/throughput (kg embalado no mês / kg montagem de cru no mês);
         não rastreia nem expressa rendimento físico por coorte de lote/OB.
      * Fases: Montagem de Lote, Revisão Malha Crua, Virar Moletom, Barcas de Tinturaria, Hidros, Secadores, Rama, Produto Acabado
      * Resumo de Fluxo: Tubular (90), Ramado Aberto (91), Estampado Acabado (92), Proporção Tubular/Ramado (93) e Auditoria Não Classificado (94, condicional a ocorrências).
============================================================================= */

WITH JANELA AS (
    SELECT ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -1)  AS DT_INICIO,
           TRUNC(SYSDATE, 'MM')                  AS DT_FIM,
           ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -13) AS DT_INICIO_ANT,
           ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -12) AS DT_FIM_ANT
      FROM DUAL
),
BASE_FASES_AGR AS (
    SELECT CASE WHEN UPR.DTPRODFIM >= JAN.DT_INICIO     AND UPR.DTPRODFIM < JAN.DT_FIM     THEN 'ATUAL'
                WHEN UPR.DTPRODFIM >= JAN.DT_INICIO_ANT AND UPR.DTPRODFIM < JAN.DT_FIM_ANT THEN 'ANTERIOR'
           END AS PERIODO,
           OBF.CODIGO_FASE,
           NVL(OBF.DESTINO_RECEITA, 1) AS DESTINO_RECEITA,
           TRIM(OBF.GRUPO_DEFEITO) AS GRUPO_DEFEITO,
           MAQ.GRUPO AS GRUPO_MAQUINA,
           UPR.NUMERO_MAQUINA,
           UPR.NRTURNOFIM AS TURNO,
           CL.CODIGO_CLASSIFICACAO,
           TRUNC(UPR.DTPRODFIM) AS DIA,
           SUM(OBF.KILOS_PRODUZIDOS) AS KILOS_PRODUZIDOS,
           COUNT(DISTINCT OBF.NUMERO_OB || '-' || TO_CHAR(OBF.SEQUENCIA)) AS QT_PARTIDAS,
           SUM(CASE WHEN CR.TEMPO_RECEITA > 0 THEN OBF.KILOS_PRODUZIDOS * CR.TEMPO_RECEITA END) AS POND_TEMPO_PREV,
           SUM(CASE WHEN CR.TEMPO_RECEITA > 0 THEN OBF.KILOS_PRODUZIDOS END) AS KG_TEMPO_PREV_VALIDO,
           SUM(CASE WHEN UPR.DTTEMPOFINALCONFIRMA > UPR.DTTEMPOINICONFIRMADO
                    THEN OBF.KILOS_PRODUZIDOS * (UPR.DTTEMPOFINALCONFIRMA - UPR.DTTEMPOINICONFIRMADO) * 24 END) AS POND_TEMPO_REAL,
           SUM(CASE WHEN UPR.DTTEMPOFINALCONFIRMA > UPR.DTTEMPOINICONFIRMADO THEN OBF.KILOS_PRODUZIDOS END) AS KG_TEMPO_REAL_VALIDO
      FROM SGTPRD.UNIDADE_PROGRAMACAO   UPR
      JOIN SGTPRD.UP_ORDEM_MVTO          UOM ON UOM.NUMEROUP = UPR.NUMEROUP
      JOIN SGTPRD.OB_FASES               OBF ON OBF.NUMERO_OB = UOM.NUMEROORDEMREAL
                                            AND OBF.SEQUENCIA = UOM.SEQUENCIAORDEMREAL
      LEFT JOIN SGTPRD.MAQUINA           MAQ ON MAQ.NUMERO_MAQUINA = UPR.NUMERO_MAQUINA AND MAQ.SETOR = 5
      LEFT JOIN SGTPRD.LIGA_CADREC_ITEMREC LCR ON LCR.ID_LIGA_CADREC_ITEMR = OBF.ID_LIGA_CADREC_ITEMR AND OBF.CODIGO_FASE = 40
      LEFT JOIN SGTPRD.CADASTRO_RECEITAS CR  ON CR.CODIGO_REDUZIDO_RECE = LCR.CODIGO_REDUZIDO_RECE
      LEFT JOIN SGTPRD.CLASSIFICACAO_COR CL  ON CL.CODIGO_CLASSIFICACAO = CR.CODIGO_CLASSIFICACAO
     CROSS JOIN JANELA                   JAN
     WHERE UPR.SETOR = 5
       AND UPR.EXCLUIDA = 0
       AND UPR.TIPOUP = 0
       AND UPR.STATUS = 0
       AND (
             (UPR.DTPRODFIM >= JAN.DT_INICIO     AND UPR.DTPRODFIM < JAN.DT_FIM)
          OR (UPR.DTPRODFIM >= JAN.DT_INICIO_ANT AND UPR.DTPRODFIM < JAN.DT_FIM_ANT)
           )
       AND OBF.CODIGO_FASE IN (10, 20, 26, 40, 50, 55, 60, 65, 70, 80, 90, 100, 110)
     GROUP BY CASE WHEN UPR.DTPRODFIM >= JAN.DT_INICIO     AND UPR.DTPRODFIM < JAN.DT_FIM     THEN 'ATUAL'
                   WHEN UPR.DTPRODFIM >= JAN.DT_INICIO_ANT AND UPR.DTPRODFIM < JAN.DT_FIM_ANT THEN 'ANTERIOR'
              END,
              OBF.CODIGO_FASE,
              NVL(OBF.DESTINO_RECEITA, 1),
              TRIM(OBF.GRUPO_DEFEITO),
              MAQ.GRUPO,
              UPR.NUMERO_MAQUINA,
              UPR.NRTURNOFIM,
              CL.CODIGO_CLASSIFICACAO,
              TRUNC(UPR.DTPRODFIM)
),
BASE_ACABADO_AGR AS (
    -- Pré-agrega por item/dia/turno ANTES de juntar com os cadastros de item (centenas de itens vs ~137 mil peças).
    SELECT MV.PERIODO,
           MV.TURNO,
           NVL(TRIM(E9.CDNIVELGENERICO), 'N/C') AS FLUXO,
           CASE WHEN MV.ESTAMPADO = 1 OR UPPER(ITE.DESCRICAO) LIKE '%ESTAMP%' THEN 1 ELSE 0 END AS IS_ESTAMPADO,
           MV.DIA,
           SUM(MV.QUANTIDADE_REAL) AS QUANTIDADE_REAL,
           SUM(MV.QT_PECAS) AS QT_PECAS
      FROM (
            SELECT CASE WHEN MVP.PRODUCAO_DATA >= JAN.DT_INICIO     AND MVP.PRODUCAO_DATA < JAN.DT_FIM     THEN 'ATUAL'
                        WHEN MVP.PRODUCAO_DATA >= JAN.DT_INICIO_ANT AND MVP.PRODUCAO_DATA < JAN.DT_FIM_ANT THEN 'ANTERIOR'
                   END AS PERIODO,
                   MVP.PRODUCAO_TURNO AS TURNO,
                   MVP.REDUZIDO_ITEM,
                   MVP.ESTAMPADO,
                   TRUNC(MVP.PRODUCAO_DATA) AS DIA,
                   SUM(MVP.QUANTIDADE_REAL) AS QUANTIDADE_REAL,
                   COUNT(MVP.IDPECASPRODUTO) AS QT_PECAS
              FROM SGTPRD.BD_PRD_MOVPROD MVP
             CROSS JOIN JANELA JAN
             WHERE MVP.NUM_TIPO_MOVIMENTO = 37
               AND MVP.CODIGO IN (1, 8)
               AND (
                     (MVP.PRODUCAO_DATA >= JAN.DT_INICIO     AND MVP.PRODUCAO_DATA < JAN.DT_FIM)
                  OR (MVP.PRODUCAO_DATA >= JAN.DT_INICIO_ANT AND MVP.PRODUCAO_DATA < JAN.DT_FIM_ANT)
                   )
             GROUP BY CASE WHEN MVP.PRODUCAO_DATA >= JAN.DT_INICIO     AND MVP.PRODUCAO_DATA < JAN.DT_FIM     THEN 'ATUAL'
                           WHEN MVP.PRODUCAO_DATA >= JAN.DT_INICIO_ANT AND MVP.PRODUCAO_DATA < JAN.DT_FIM_ANT THEN 'ANTERIOR'
                      END,
                      MVP.PRODUCAO_TURNO,
                      MVP.REDUZIDO_ITEM,
                      MVP.ESTAMPADO,
                      TRUNC(MVP.PRODUCAO_DATA)
           ) MV
      LEFT JOIN SGTPRD.ENGEITEMESTONIVELGE9 E9 ON E9.CDREDUZIDO = MV.REDUZIDO_ITEM
      LEFT JOIN SGTPRD.ITENS_ESTOQUE        ITE ON ITE.CODIGO_REDUZIDO = MV.REDUZIDO_ITEM
     GROUP BY MV.PERIODO,
              MV.TURNO,
              NVL(TRIM(E9.CDNIVELGENERICO), 'N/C'),
              CASE WHEN MV.ESTAMPADO = 1 OR UPPER(ITE.DESCRICAO) LIKE '%ESTAMP%' THEN 1 ELSE 0 END,
              MV.DIA
),
REFS AS (
    SELECT SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE = 10 THEN F.KILOS_PRODUZIDOS END) AS KG_MONT_ATU,
           SUM(CASE WHEN F.PERIODO = 'ANTERIOR' AND F.CODIGO_FASE = 10 THEN F.KILOS_PRODUZIDOS END) AS KG_MONT_ANT,
           SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE = 40 AND F.DESTINO_RECEITA = 1 THEN F.KILOS_PRODUZIDOS END) AS KG_TING_NORM_ATU,
           SUM(CASE WHEN F.PERIODO = 'ANTERIOR' AND F.CODIGO_FASE = 40 AND F.DESTINO_RECEITA = 1 THEN F.KILOS_PRODUZIDOS END) AS KG_TING_NORM_ANT,
           SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE = 40 AND F.DESTINO_RECEITA IN (2, 4) AND F.GRUPO_DEFEITO IN ('1', '3', '4') THEN F.KILOS_PRODUZIDOS END) AS KG_TING_REP_INT_ATU,
           SUM(CASE WHEN F.PERIODO = 'ANTERIOR' AND F.CODIGO_FASE = 40 AND F.DESTINO_RECEITA IN (2, 4) AND F.GRUPO_DEFEITO IN ('1', '3', '4') THEN F.KILOS_PRODUZIDOS END) AS KG_TING_REP_INT_ANT,
           SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE = 40 AND F.DESTINO_RECEITA IN (2, 4) AND NVL(F.GRUPO_DEFEITO, ' ') NOT IN ('1', '3', '4') THEN F.KILOS_PRODUZIDOS END) AS KG_TING_REP_EXT_ATU,
           SUM(CASE WHEN F.PERIODO = 'ANTERIOR' AND F.CODIGO_FASE = 40 AND F.DESTINO_RECEITA IN (2, 4) AND NVL(F.GRUPO_DEFEITO, ' ') NOT IN ('1', '3', '4') THEN F.KILOS_PRODUZIDOS END) AS KG_TING_REP_EXT_ANT,
           SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE = 40 THEN F.KILOS_PRODUZIDOS END) AS KG_TING_TOT_ATU,
           SUM(CASE WHEN F.PERIODO = 'ANTERIOR' AND F.CODIGO_FASE = 40 THEN F.KILOS_PRODUZIDOS END) AS KG_TING_TOT_ANT,
           SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE = 40 THEN F.QT_PARTIDAS END) AS PART_TING_TOT_ATU,
           SUM(CASE WHEN F.PERIODO = 'ANTERIOR' AND F.CODIGO_FASE = 40 THEN F.QT_PARTIDAS END) AS PART_TING_TOT_ANT,
           COUNT(DISTINCT CASE WHEN F.PERIODO = 'ATUAL' AND F.CODIGO_FASE = 40 THEN F.DIA END) AS DIAS_TING_ATU,
           COUNT(DISTINCT CASE WHEN F.PERIODO = 'ANTERIOR' AND F.CODIGO_FASE = 40 THEN F.DIA END) AS DIAS_TING_ANT,
           SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE = 60 THEN F.KILOS_PRODUZIDOS END) AS KG_SECADOR_TOT_ATU,
           SUM(CASE WHEN F.PERIODO = 'ATUAL'    AND F.CODIGO_FASE IN (100, 110) THEN F.KILOS_PRODUZIDOS END) AS KG_RAMA_TOT_ATU,
           MAX(A.KG_EMB_TOT_ATU)     AS KG_EMB_TOT_ATU,
           MAX(A.KG_EMB_TOT_ANT)     AS KG_EMB_TOT_ANT,
           MAX(A.PECAS_EMB_TOT_ATU)  AS PECAS_EMB_TOT_ATU,
           MAX(A.PECAS_EMB_TOT_ANT)  AS PECAS_EMB_TOT_ANT,
           MAX(A.DIAS_EMB_ATU)       AS DIAS_EMB_ATU,
           MAX(A.DIAS_EMB_ANT)       AS DIAS_EMB_ANT,
           MAX(A.KG_EMB_TUBULAR_ATU) AS KG_EMB_TUBULAR_ATU,
           MAX(A.KG_EMB_TUBULAR_ANT) AS KG_EMB_TUBULAR_ANT,
           MAX(A.KG_EMB_RAMADO_ATU)  AS KG_EMB_RAMADO_ATU,
           MAX(A.KG_EMB_RAMADO_ANT)  AS KG_EMB_RAMADO_ANT,
           MAX(A.KG_EMB_NC_ATU)      AS KG_EMB_NC_ATU,
           MAX(A.KG_EMB_NC_ANT)      AS KG_EMB_NC_ANT
      FROM BASE_FASES_AGR F
      LEFT JOIN (
           SELECT SUM(CASE WHEN PERIODO = 'ATUAL'    THEN QUANTIDADE_REAL END) AS KG_EMB_TOT_ATU,
                  SUM(CASE WHEN PERIODO = 'ANTERIOR' THEN QUANTIDADE_REAL END) AS KG_EMB_TOT_ANT,
                  SUM(CASE WHEN PERIODO = 'ATUAL'    THEN QT_PECAS END) AS PECAS_EMB_TOT_ATU,
                  SUM(CASE WHEN PERIODO = 'ANTERIOR' THEN QT_PECAS END) AS PECAS_EMB_TOT_ANT,
                  COUNT(DISTINCT CASE WHEN PERIODO = 'ATUAL' THEN DIA END) AS DIAS_EMB_ATU,
                  COUNT(DISTINCT CASE WHEN PERIODO = 'ANTERIOR' THEN DIA END) AS DIAS_EMB_ANT,
                  SUM(CASE WHEN PERIODO = 'ATUAL'    AND FLUXO = 'T' THEN QUANTIDADE_REAL END) AS KG_EMB_TUBULAR_ATU,
                  SUM(CASE WHEN PERIODO = 'ANTERIOR' AND FLUXO = 'T' THEN QUANTIDADE_REAL END) AS KG_EMB_TUBULAR_ANT,
                  SUM(CASE WHEN PERIODO = 'ATUAL'    AND FLUXO = 'R' THEN QUANTIDADE_REAL END) AS KG_EMB_RAMADO_ATU,
                  SUM(CASE WHEN PERIODO = 'ANTERIOR' AND FLUXO = 'R' THEN QUANTIDADE_REAL END) AS KG_EMB_RAMADO_ANT,
                   SUM(CASE WHEN PERIODO = 'ATUAL'    AND FLUXO NOT IN ('T', 'R') THEN QUANTIDADE_REAL END) AS KG_EMB_NC_ATU,
                   SUM(CASE WHEN PERIODO = 'ANTERIOR' AND FLUXO NOT IN ('T', 'R') THEN QUANTIDADE_REAL END) AS KG_EMB_NC_ANT
             FROM BASE_ACABADO_AGR
      ) A ON 1 = 1
),
EXPANDIDO AS (
    SELECT '01'  AS ORDEM, '01 - MONTAGEM DE LOTE (CRU)' AS LINHA, PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, TO_NUMBER(NULL) AS POND_TEMPO_PREV, TO_NUMBER(NULL) AS KG_TEMPO_PREV_VALIDO, TO_NUMBER(NULL) AS POND_TEMPO_REAL, TO_NUMBER(NULL) AS KG_TEMPO_REAL_VALIDO, TO_NUMBER(NULL) AS CAPACIDADE_NOMINAL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 10
    UNION ALL
    SELECT '02' , '02 - REVISÃO MALHA CRUA', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, NULL, NULL, NULL, NULL, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 20
    UNION ALL
    SELECT '03' , '03 - VIRAR MOLETOM (FELPA)', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, NULL, NULL, NULL, NULL, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 26
    UNION ALL
    SELECT '04A', '04A - TINTURARIA: BARCA 1000 KG (TG001)', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, 1000 FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND GRUPO_MAQUINA = 'TG001'
    UNION ALL
    SELECT '04B', '04B - TINTURARIA: BARCA 600 KG (TG002)', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, 600 FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND GRUPO_MAQUINA = 'TG002'
    UNION ALL
    SELECT '04C', '04C - TINTURARIA: BARCA 2000 KG (TG003)', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, 2000 FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND GRUPO_MAQUINA = 'TG003'
    UNION ALL
    SELECT '04D', '04 - TINTURARIA: PRODUÇÃO NORMAL', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1
    UNION ALL
    SELECT '04E', '04 - TINTURARIA: REPROCESSO BENEFICIAMENTO', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA IN (2, 4) AND GRUPO_DEFEITO IN ('1', '3', '4')
    UNION ALL
    SELECT '04F', '04 - TINTURARIA: REPROCESSO MALHARIA/FIAÇÃO', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA IN (2, 4) AND NVL(GRUPO_DEFEITO, ' ') NOT IN ('1', '3', '4')
    UNION ALL
    SELECT '04G', '04 - TINTURARIA: TOTAL GERAL (NORMAL + REPROCESSO)', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40
    UNION ALL
    SELECT '04H', '[MIX CORES] 1. CLARAS / BRANCO / MARFIM', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO IN (1, 6, 7, 10, 18)
    UNION ALL
    SELECT '04I', '[MIX CORES] 2. CORES MÉDIAS', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO IN (2)
    UNION ALL
    SELECT '04J', '[MIX CORES] 3. CORES ESCURAS E PRETO', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO IN (5, 14)
    UNION ALL
    SELECT '04K', '[MIX CORES] 4. ESPECIAIS E 2 FIBRAS', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND CODIGO_CLASSIFICACAO IN (3, 8, 9, 11, 12, 15)
    UNION ALL
    SELECT '04L', '[TURNO TINTURARIA] 1º TURNO', PERIODO, DIA, QT_PARTIDAS, KILOS_PRODUZIDOS, POND_TEMPO_PREV, KG_TEMPO_PREV_VALIDO, POND_TEMPO_REAL, KG_TEMPO_REAL_VALIDO, NULL FROM BASE_FASES_AGR WHERE CODIGO_FASE = 40 AND DESTINO_RECEITA = 1 AND TURNO = 1
