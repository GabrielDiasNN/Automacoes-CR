SELECT TO_CHAR(JAN.DT_INICIO, 'DD-MM-YYYY') || ' a ' || TO_CHAR(JAN.DT_FIM - 1, 'DD-MM-YYYY') || ' (vs ' || TO_CHAR(JAN.DT_INICIO_ANT, 'MM-YYYY') || ')' AS PERIODO_REFERENCIA,
       TO_CHAR(JAN.DT_INICIO, 'MM-YYYY')   AS COMPETENCIA,
       UNI.ORDEM,
       UNI.LINHA                           AS LINHA_RELATORIO,
       ROUND(NVL(UNI.QT_KG, 0), 2)         AS QT_KG,
       ROUND(NVL(UNI.QT_KG_ANT, 0), 2)     AS QT_KG_ANO_ANT,
       CASE WHEN UNI.ORDEM IN ('00A', '00B', '00C', '00D', '00E', '93') THEN
                 ROUND(NVL(UNI.QT_KG, 0) - NVL(UNI.QT_KG_ANT, 0), 2)
            WHEN UNI.ORDEM IN ('00F', '12C') THEN
                 ROUND(NVL(UNI.QT_KG, 0) - NVL(UNI.QT_KG_ANT, 0), 2)
            ELSE
                 ROUND((NVL(UNI.QT_KG, 0) - UNI.QT_KG_ANT) / NULLIF(UNI.QT_KG_ANT, 0) * 100, 1)
       END AS VAR_YOY_PCT,
       CASE WHEN UNI.ORDEM IN ('00A', '00B', '00C', '00D', '00E', '93') THEN
                 'DIF_PP'
            WHEN UNI.ORDEM IN ('00F', '12C') THEN
                 'DIF_ABS'
            ELSE
                 'VAR_PCT'
       END AS TIPO_VARIACAO_YOY,
       CASE WHEN UNI.ORDEM NOT LIKE '00%' AND UNI.ORDEM NOT IN ('12B', '12C', '93') THEN
            ROUND(NVL(UNI.QT_KG, 0) / NULLIF(UNI.DIAS_PRODUTIVOS, 0), 2)
       END AS MEDIA_KG_DIA,
       CASE WHEN UNI.ORDEM NOT LIKE '00%' AND UNI.ORDEM NOT IN ('12B', '12C', '93') THEN
            ROUND(NVL(UNI.QT_KG_ANT, 0) / NULLIF(UNI.DIAS_PRODUTIVOS_ANT, 0), 2)
       END AS MEDIA_KG_DIA_ANT,
       CASE WHEN UNI.ORDEM NOT LIKE '00%' AND UNI.ORDEM NOT IN ('12B', '12C', '93') AND UNI.DIAS_PRODUTIVOS > 0 AND UNI.DIAS_PRODUTIVOS_ANT > 0 THEN
            ROUND(( (NVL(UNI.QT_KG, 0) / UNI.DIAS_PRODUTIVOS) - (NVL(UNI.QT_KG_ANT, 0) / UNI.DIAS_PRODUTIVOS_ANT) )
                  / NULLIF(NVL(UNI.QT_KG_ANT, 0) / UNI.DIAS_PRODUTIVOS_ANT, 0) * 100, 1)
       END AS VAR_RITMO_PCT,
       UNI.QT_PARTIDAS,
       CASE WHEN UNI.ORDEM = '00F' THEN
                 UNI.QT_KG
            WHEN UNI.ORDEM = '12C' THEN
                 UNI.QT_KG
            WHEN UNI.QT_PARTIDAS > 0 AND UNI.ORDEM NOT LIKE '00%' AND UNI.ORDEM NOT LIKE '12%' THEN
                 ROUND(NVL(UNI.QT_KG, 0) / UNI.QT_PARTIDAS, 0)
       END AS CARGA_MEDIA_KG,
       CASE WHEN UNI.ORDEM IN ('00A', '00B', '00C', '00D', '00E', '93') THEN
                 UNI.QT_KG
            WHEN UNI.ORDEM IN ('04A', '04B', '04C') AND UNI.CAPACIDADE_NOMINAL > 0 THEN
                 ROUND((NVL(UNI.QT_KG, 0) / NULLIF(UNI.QT_PARTIDAS, 0)) / UNI.CAPACIDADE_NOMINAL * 100, 1)
            WHEN UNI.ORDEM IN ('04E', '04F', '04H', '04I', '04J', '04K', '04L', '04M', '04N') THEN
                 ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.KG_TING_NORM_ATU, 0) * 100, 2)
            WHEN UNI.ORDEM IN ('06A', '06B') THEN
                 ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.KG_SECADOR_TOT_ATU, 0) * 100, 2)
            WHEN UNI.ORDEM IN ('11A', '11B') THEN
                 ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.KG_RAMA_TOT_ATU, 0) * 100, 2)
            WHEN UNI.ORDEM IN ('12D', '12E', '12F', '90', '91', '92', '94') THEN
                 ROUND(NVL(UNI.QT_KG, 0) / NULLIF(REF.KG_EMB_TOT_ATU, 0) * 100, 2)
       END AS PERC_ESPECIFICO,
       CASE WHEN UNI.ORDEM LIKE '00%' THEN
                 CASE UNI.ORDEM
                      WHEN '00A' THEN '% ACERTO DE 1ª (RFT)'
                      WHEN '00B' THEN '% REPROCESSO BENEFICIAMENTO'
                      WHEN '00C' THEN '% REPROCESSO EXTERNO'
                      WHEN '00D' THEN '% ESCOAMENTO (EMBALADO / TINGIDO)'
                      WHEN '00E' THEN '% BALANÇO DE FLUXO (EMB / CRU)'
                      WHEN '00F' THEN 'KG / PARTIDA (TINTURARIA)'
                 END
            WHEN UNI.ORDEM IN ('04A', '04B', '04C') THEN '% CARGA NOMINAL BARCA'
            WHEN UNI.ORDEM IN ('04E', '04F') THEN '% S/ TINGIMENTO NORMAL'
            WHEN UNI.ORDEM IN ('04H', '04I', '04J', '04K') THEN '% MIX DE CORES'
            WHEN UNI.ORDEM IN ('04L', '04M', '04N') THEN '% PARTICIPAÇÃO TURNO TINTURARIA'
            WHEN UNI.ORDEM IN ('06A', '06B') THEN '% CARGA SECADOR (ÓLEO / VAPOR)'
            WHEN UNI.ORDEM IN ('11A', '11B') THEN '% CARGA RAMA (RM 01 / RM 02)'
            WHEN UNI.ORDEM = '12B' THEN 'QUANTIDADE DE PEÇAS / ROLOS'
            WHEN UNI.ORDEM = '12C' THEN 'KG MÉDIO POR PEÇA ACABADA'
            WHEN UNI.ORDEM IN ('12D', '12E', '12F') THEN '% PARTICIPAÇÃO TURNO ACABAMENTO'
            WHEN UNI.ORDEM IN ('90', '91', '92', '94') THEN '% S/ TOTAL PRODUTO ACABADO'
            WHEN UNI.ORDEM = '93' THEN '% PROPORÇÃO TUBULAR / RAMADO'
       END AS TIPO_METRICA,
       UNI.TEMPO_PREV_HORAS,
       UNI.TEMPO_REAL_HORAS,
       CASE WHEN UNI.TEMPO_REAL_HORAS IS NOT NULL AND UNI.TEMPO_PREV_HORAS IS NOT NULL THEN
            ROUND((UNI.TEMPO_REAL_HORAS - UNI.TEMPO_PREV_HORAS) * 60, 0)
       END AS DESVIO_TEMPO_MIN,
       CASE WHEN UNI.TEMPO_REAL_HORAS > 0 AND UNI.TEMPO_PREV_HORAS > 0 THEN
            ROUND((UNI.TEMPO_PREV_HORAS / UNI.TEMPO_REAL_HORAS) * 100, 1)
       END AS EFIC_TEMPO_PCT
  FROM UNIFICADO UNI
 CROSS JOIN JANELA JAN
 CROSS JOIN REFS REF
 ORDER BY UNI.ORDEM;
