AGREGADO AS (
    SELECT ORDEM,
           LINHA,
           SUM(CASE WHEN PERIODO = 'ATUAL'    THEN KILOS_PRODUZIDOS END) AS QT_KG,
           COUNT(DISTINCT CASE WHEN PERIODO = 'ATUAL' THEN DIA END) AS DIAS_PRODUTIVOS,
           SUM(CASE WHEN PERIODO = 'ATUAL'    THEN QT_PARTIDAS END) AS QT_PARTIDAS,
           SUM(CASE WHEN PERIODO = 'ANTERIOR' THEN KILOS_PRODUZIDOS END) AS QT_KG_ANT,
           COUNT(DISTINCT CASE WHEN PERIODO = 'ANTERIOR' THEN DIA END) AS DIAS_PRODUTIVOS_ANT,
           SUM(CASE WHEN PERIODO = 'ANTERIOR' THEN QT_PARTIDAS END) AS QT_PARTIDAS_ANT,
           MAX(CAPACIDADE_NOMINAL) AS CAPACIDADE_NOMINAL,
           ROUND(SUM(CASE WHEN PERIODO = 'ATUAL' THEN POND_TEMPO_PREV END)
                 / NULLIF(SUM(CASE WHEN PERIODO = 'ATUAL' THEN KG_TEMPO_PREV_VALIDO END), 0), 2) AS TEMPO_PREV_HORAS,
           ROUND(SUM(CASE WHEN PERIODO = 'ATUAL' THEN POND_TEMPO_REAL END)
                 / NULLIF(SUM(CASE WHEN PERIODO = 'ATUAL' THEN KG_TEMPO_REAL_VALIDO END), 0), 2) AS TEMPO_REAL_HORAS
      FROM EXPANDIDO
     GROUP BY ORDEM, LINHA
),
KPIS_EXECUTIVOS AS (
    SELECT '00A' AS ORDEM,
           '[INDICADOR GESTÃO] ACERTO DE 1ª - TINTURARIA (RFT %)' AS LINHA,
           ROUND(REF.KG_TING_NORM_ATU / NULLIF(REF.KG_TING_TOT_ATU, 0) * 100, 2) AS QT_KG,
           REF.DIAS_TING_ATU AS DIAS_PRODUTIVOS,
           REF.PART_TING_TOT_ATU AS QT_PARTIDAS,
           ROUND(REF.KG_TING_NORM_ANT / NULLIF(REF.KG_TING_TOT_ANT, 0) * 100, 2) AS QT_KG_ANT,
           REF.DIAS_TING_ANT AS DIAS_PRODUTIVOS_ANT,
           REF.PART_TING_TOT_ANT AS QT_PARTIDAS_ANT,
           TO_NUMBER(NULL) AS CAPACIDADE_NOMINAL,
           TO_NUMBER(NULL) AS TEMPO_PREV_HORAS,
           TO_NUMBER(NULL) AS TEMPO_REAL_HORAS
      FROM REFS REF
     UNION ALL
    SELECT '00B',
