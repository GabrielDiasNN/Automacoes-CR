ARQUIVO ORIGINAL: Novo artefato homologado no acervo (consolidando Estoque, Facção e PCP)
TIPO: PCP / Gestão de Fluxo e Pipeline Produtivo
PARÂMETROS / BINDS: Nenhum (janela móvel de 21 dias para NFs pendentes de pesagem)
TABELAS PRINCIPAIS:
  - SGTPRD.GERAPECASPRODUTO (Estoque Físico de Rolos Cru)
  - SGTPRD.ENGEITEMESTONIVELGE / ENGEITEMESTONIVELGE9 (Nível Genérico Tubular/Ramado)
  - SGTPRD.OB, SGTPRD.OB_FASES, SGTPRD.OB_PRODUTO, SGTPRD.FASES_FLUXO, SGTPRD.GRUPO_FASES (Montagem/Revisão e Processo)
  - SGTPRD.MESTRE_NOTA_ENTRADA, SGTPRD.ITENS_NOTA_ENTRADA, SGTPRD.LOTE_ITENS_NOTA_ENTR (NFs de Facção)
  - SGTPRD.PESSOASFJ, SGTPRD.DEPOSITO, SGTPRD.ITENS_ESTOQUE (Cadastros de Apoio)
CUIDADOS OPERACIONAIS & DIRETRIZES DE ENGENHARIA ORACLE:
  - Consulta analítica somente leitura de alto nível gerencial.
  - OTIMIZAÇÃO (Zero Views): Eliminação de SGTPRD.VW_PI_CBPAP01_PROCBENEF e SGTPRD.VW_BNF_FASEATUALOB,
    substituídas pela CTE determinística FASE_ATUAL_OB com janela ROW_NUMBER() sobre OB_FASES e OB.
  - Regra de Negócio dos Estágios:
      * QTD_CRU: Estoque em galpão (MCP/MCR/MCT) + OBs em Montagem (GF 1) e Revisão (GF 2).
      * QTD_FACAO_PENDENTE: NFs de facção dos últimos 21 dias confirmadas (status 5) sem lote finalizado (stfinalizacao <> 2).
      * EM_PROCESSO: OBs ativas nas fases de Abridor/Rama (Ramado) e Calandras Brilho/Compacta (Tubular).
