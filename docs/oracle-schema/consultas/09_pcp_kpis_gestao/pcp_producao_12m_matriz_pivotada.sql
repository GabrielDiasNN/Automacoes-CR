    SELECT DT_MES, '06C', 'SECADORES', '06 - TOTAL SECADORES', 'kg', KILOS_PRODUZIDOS FROM BASE_FASES_AGR WHERE CODIGO_FASE = 60
    UNION ALL
    SELECT DT_MES, '07' , 'ACABAMENTO INTERMEDIÁRIO', '07 - FELPADEIRA', 'kg', KILOS_PRODUZIDOS FROM BASE_FASES_AGR WHERE CODIGO_FASE = 65
