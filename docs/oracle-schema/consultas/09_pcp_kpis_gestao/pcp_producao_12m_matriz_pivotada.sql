AGREGADO AS (
    SELECT DT_MES,
           ORDEM,
           CATEGORIA,
           LINHA,
           UNIDADE,
           ROUND(SUM(VALOR), 2) AS VALOR
      FROM EXPANDIDO
     GROUP BY DT_MES, ORDEM, CATEGORIA, LINHA, UNIDADE
),
KPIS_EXECUTIVOS AS (
