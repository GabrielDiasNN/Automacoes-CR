UNIFICADO AS (
    SELECT DT_MES, ORDEM, CATEGORIA, LINHA, UNIDADE, VALOR FROM KPIS_EXECUTIVOS
    UNION ALL
    SELECT DT_MES, ORDEM, CATEGORIA, LINHA, UNIDADE, VALOR FROM AGREGADO
),
PIVOTADO AS (
    SELECT ORDEM,
           CATEGORIA,
           LINHA AS INDICADOR_FABRIL,
           UNIDADE AS UNIDADE_METRICA,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -12) THEN VALOR END), 2) AS M12_FECHADO,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -11) THEN VALOR END), 2) AS M11,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -10) THEN VALOR END), 2) AS M10,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -9)  THEN VALOR END), 2) AS M09,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -8)  THEN VALOR END), 2) AS M08,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -7)  THEN VALOR END), 2) AS M07,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -6)  THEN VALOR END), 2) AS M06,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -5)  THEN VALOR END), 2) AS M05,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -4)  THEN VALOR END), 2) AS M04,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -3)  THEN VALOR END), 2) AS M03,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -2)  THEN VALOR END), 2) AS M02,
           ROUND(MAX(CASE WHEN DT_MES = ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -1)  THEN VALOR END), 2) AS M01_FECHADO,
           ROUND(MAX(CASE WHEN DT_MES = TRUNC(SYSDATE, 'MM')                 THEN VALOR END), 2) AS M_ATUAL_ABERTO,
           ROUND(AVG(CASE WHEN DT_MES < TRUNC(SYSDATE, 'MM') THEN VALOR END), 2)                  AS MEDIA_12M_FECHADO,
           CASE WHEN UNIDADE IN ('kg', 'peças') AND ORDEM NOT IN ('00G') THEN
                ROUND(SUM(CASE WHEN DT_MES < TRUNC(SYSDATE, 'MM') THEN VALOR END), 2)
           END AS TOTAL_12M_FECHADO
      FROM UNIFICADO
     GROUP BY ORDEM, CATEGORIA, LINHA, UNIDADE
)
SELECT P.ORDEM,
       P.CATEGORIA,
       P.INDICADOR_FABRIL,
       P.UNIDADE_METRICA,
       P.M12_FECHADO,
       P.M11,
       P.M10,
       P.M09,
       P.M08,
       P.M07,
       P.M06,
       P.M05,
       P.M04,
       P.M03,
       P.M02,
       P.M01_FECHADO,
       P.M_ATUAL_ABERTO,
       P.MEDIA_12M_FECHADO,
       P.TOTAL_12M_FECHADO,
       CASE
            WHEN P.M01_FECHADO IS NULL OR P.MEDIA_12M_FECHADO IS NULL OR P.MEDIA_12M_FECHADO = 0 THEN '-'
            WHEN P.M01_FECHADO >= P.MEDIA_12M_FECHADO * 1.02 THEN 'ALTA'
            WHEN P.M01_FECHADO <= P.MEDIA_12M_FECHADO * 0.98 THEN 'QUEDA'
            ELSE 'ESTAVEL'
       END AS TENDENCIA_VS_MED12M
  FROM PIVOTADO P
 ORDER BY P.ORDEM ASC;
