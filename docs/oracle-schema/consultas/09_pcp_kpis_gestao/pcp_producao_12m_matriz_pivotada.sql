    SELECT DT_MES, '09' , 'ACABAMENTO INTERMEDIÁRIO', '09 - CALANDRA COMPACTA (CL 02)', 'kg', KILOS_PRODUZIDOS FROM BASE_FASES_AGR WHERE CODIGO_FASE = 80
