OBJETIVO: Cruzamento operacional entre pedidos comerciais e romaneios de saída
DOMÍNIO: 07_expedicao_pedidos_comercial
ARQUIVO ORIGINAL: Comandos SQL - CR\Consulta Pedidos e Romaneios.sql
TIPO: SELECT (Consulta Somente Leitura)
PARÂMETROS / BINDS: Nenhum (janela de entrega: últimos 60 dias e próximos 30 dias)
TABELAS PRINCIPAIS: SGTPRD.GERAPECADESTINOOB, SGTPRD.GERAPECAROMSAIDA, SGTPRD.GERAPECASPRODUTO, SGTPRD.ITENSPEDIDOCOMERCIAL, SGTPRD.ITENSPEDIDOGRADE, SGTPRD.ITENSPEDIDOQTDES, SGTPRD.ITENS_ESTOQUE, SGTPRD.OB, SGTPRD.OFORDENS, SGTPRD.OFPEDIDO, SGTPRD.PECAS_ROMANEIO_SAIDA, SGTPRD.PEDIDOCOMERCIAL, SGTPRD.PEDPRODUCAO, SGTPRD.PEDPRODUCAOOB, SGTPRD.ROMANEIO, SGTPRD.XX2_ENUMERATES, SGTPRD.XX2_ENUMITEM
CUIDADOS OPERACIONAIS: Query operacional do acervo SGT. Execução somente leitura.
OTIMIZAÇÃO (22/09/2026): Eliminação de subqueries correlacionadas para agregação de romaneios. Uso de CTEs pré-agregadas com LISTAGG e escopo em janela temporal em DATA_ENTREGA_PEDIDO. Redução de timeout para ~3.1s.
AUDITORIA (29/09/2026): removido o teto FETCH FIRST 100 ROWS ONLY. Em 29/09 a consulta devolve 204 linhas;
  com o teto a auditoria mostrava só 100 (49%) e escondia o resto sem aviso.
