SELECT ITP.PEDIDO,
       PED.PEDIDOCLIENTE PROG,
       ROM.STATUS,
       PRO.CODIGO_PRODUTO_REDUZ REDUZ,
       ITE.DESCRICAO,
       SUM(PRO.QUILOS_ORIGINAIS) PESO,
       SUM(PRO.PECAS_ORIGINAIS) PEAS

  FROM SGTPRD.ROMANEIO             ROM
 INNER JOIN SGTPRD.PRODUTO_ROMANEIO     PRO
    ON PRO.NUMERO_ROMANEIO = ROM.NUMERO_ROMANEIO
 INNER JOIN SGTPRD.ITENSPEDIDOCOMERCIAL ITP
    ON ITP.PEDIDO = PRO.NUMERO_PEDIDO
   AND ITP.ITEMPEDIDO = PRO.ITEM_PEDIDO
 INNER JOIN SGTPRD.PEDIDOCOMERCIAL      PED
    ON PED.PEDIDO = ITP.PEDIDO
 INNER JOIN SGTPRD.ITENS_ESTOQUE        ITE
    ON ITE.CODIGO_REDUZIDO = PRO.CODIGO_PRODUTO_REDUZ
 WHERE ROM.STATUS IN (0, 1, 3, 8)
   AND ROM.IDTIPOROMA IN (1000)

 GROUP BY ITP.PEDIDO,
          PED.PEDIDOCLIENTE,
          ROM.STATUS,
          PRO.CODIGO_PRODUTO_REDUZ,
          ITE.DESCRICAO

 ORDER BY PED.PEDIDOCLIENTE, ROM.STATUS