TABELAS PRINCIPAIS: SGTPRD.ITENSPEDIDOCOMERCIAL, SGTPRD.ITENS_ESTOQUE, SGTPRD.PEDIDOCOMERCIAL, SGTPRD.PRODUTO_ROMANEIO, SGTPRD.ROMANEIO
