TABELAS PRINCIPAIS: SGTPRD.BD_PRD_MOVPROD, SGTPRD.DEPOSITO,
                     SGTPRD.DEPOTIPOITEM, SGTPRD.EMBALAGENS,
                     SGTPRD.GERAATRIBUTOESTOQUE, SGTPRD.GERAPECAFARDO,
                     SGTPRD.GERAPECAFIO, SGTPRD.GERAPECACODIGOALFA,
                     SGTPRD.GERAPECASPRODUTO, SGTPRD.GRUPO_ACONDICIONAM,
                     SGTPRD.ITENS_COMPLEMENTO_FI, SGTPRD.ITENS_ESTOQUE,
                     SGTPRD.MASCARA_TIPO_INSUMO, SGTPRD.MASCARAS,
                     SGTPRD.TIPO_ACONDICIONAMENT, SGTPRD.UNIDADE_FABRIL,
                     SGTPRD.UNIDADE_MEDIDA, SGTPRD.XX2_ENUMERATES,
                     SGTPRD.XX2_ENUMITEM
CUIDADOS OPERACIONAIS: Consulta somente leitura; datas numéricas YYYYMMDD
                        são convertidas com máscara explícita.
REVISÃO (21/09/2026 - frente cirúrgica): camadas derivadas substituídas por
  tabelas/CTEs; conversão de data e montagem do código industrial usam apenas
