PARÂMETROS / BINDS: Nenhum
TABELAS PRINCIPAIS: SGTPRD.ITENS_ESTOQUE, SGTPRD.LABOGRUPOPADROESQUAL, SGTPRD.LABOPADROESPRODUTO, SGTPRD.LABOPADROESQUALIDADE
CUIDADOS OPERACIONAIS: Consulta atômica desmembrada para execução individual.
