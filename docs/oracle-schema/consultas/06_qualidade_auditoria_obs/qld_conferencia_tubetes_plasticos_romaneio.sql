                     SGTPRD.NOTAFISCALCAPA, SGTPRD.NOTAFISCALITENS,
                     SGTPRD.PRODUTO_ROMANEIO, SGTPRD.TIPO_ACONDICIONAMENT,
                     SGTPRD.TTIPOACONITEMESTO, SGTPRD.UNIDADE_MEDIDA
CUIDADOS OPERACIONAIS: Consulta atômica desmembrada para execução individual.
