PARÂMETROS / BINDS: Nenhum
TABELAS PRINCIPAIS: SGTPRD.CLASSIFICACAO_COR, SGTPRD.COML_GRUPOSPRECOSITE,
                     SGTPRD.COML_ITEMPORGRUPODEP, SGTPRD.COML_PRECOSARTIGOS,
                     SGTPRD.COML_TABELAPRECOS, SGTPRD.COML_TIPOSCOR,
                     SGTPRD.COR, SGTPRD.ENGEITEMARTIGOCRU,
                     SGTPRD.ENGEITEMESTOARTCRU, SGTPRD.ENGEITEMESTOCOR,
                     SGTPRD.ITENS_ESTOQUE, SGTPRD.TCLI_ITENS_TOTVS
CUIDADOS OPERACIONAIS: Consulta atômica somente leitura; o recorte da tabela
                        de preços é aplicado dentro da CTE de base.
