TABELAS PRINCIPAIS: SGTPRD.CLASSIFICACAO_COR, SGTPRD.COLECOES,
                     SGTPRD.COML_TIPOSCOR, SGTPRD.COR,
                     SGTPRD.ENGEITEMARTIGOCRU, SGTPRD.ENGEITEMESTOARTCRU,
                     SGTPRD.ENGEITEMESTOCOR, SGTPRD.ITENS_ESTOQUE,
                     SGTPRD.LINHA_PRODUTO, SGTPRD.TCLI_ITENS_TOTVS
CUIDADOS OPERACIONAIS: Consulta somente leitura; as descrições e códigos
                        comerciais são compostos diretamente das tabelas-base.
