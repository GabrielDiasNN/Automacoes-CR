WITH
ENUM_STATUS_OB AS (
  SELECT ENI.SEQUENCE AS STATUS, ENI.DESCRIPTION AS DESCRICAO
    FROM SGTPRD.XX2_ENUMERATES ENU
    JOIN SGTPRD.XX2_ENUMITEM ENI ON ENI.IDENUMERATE = ENU.ID
   WHERE ENU.NAME LIKE 'TOBSTATUS%'
),
ENUM_TIPO_ORDEM AS (
  SELECT ENI.SEQUENCE AS TIPO_ORDEM, ENI.DESCRIPTION AS DESCRICAO
    FROM SGTPRD.XX2_ENUMERATES ENU
    JOIN SGTPRD.XX2_ENUMITEM ENI ON ENI.IDENUMERATE = ENU.ID
   WHERE ENU.NAME LIKE 'TOBTIPOORDEM%'
),
ENUM_STATUS_UP AS (
  SELECT ENI.SEQUENCE AS STATUS, ENI.DESCRIPTION AS DESCRICAO
    FROM SGTPRD.XX2_ENUMERATES ENU
    JOIN SGTPRD.XX2_ENUMITEM ENI ON ENI.IDENUMERATE = ENU.ID
   WHERE ENU.NAME LIKE 'TSTATUSUP%'
),
ENUM_STATUS_ROM_SAIDA AS (
  SELECT ENI.SEQUENCE AS STATUS, ENI.DESCRIPTION AS DESCRICAO
    FROM SGTPRD.XX2_ENUMERATES ENU
    JOIN SGTPRD.XX2_ENUMITEM ENI ON ENI.IDENUMERATE = ENU.ID
   WHERE ENU.NAME LIKE 'TSTATUSROMANEIOSAIDA%'
),
ENUM_STATUS_OB_FASES AS (
  SELECT ENI.SEQUENCE AS STATUS, ENI.DESCRIPTION AS DESCRICAO
    FROM SGTPRD.XX2_ENUMERATES ENU
    JOIN SGTPRD.XX2_ENUMITEM ENI ON ENI.IDENUMERATE = ENU.ID
   WHERE ENU.NAME LIKE 'TOBFASESSTATUS%'
),
SIS_USUARIO AS (
  SELECT CRI.CODREDUSUARIO, TRIM(CRI.NOME_USERLITERAL) AS NOME
    FROM SGTPRD.CRISTAL CRI
),
PESO_PADRAO AS (
  SELECT BASE.ARTIGO,
         ART.CDREDUZIDO AS REDUZIDO,
         BASE.PESO_PADRAO
    FROM (
          SELECT ART0.CDARTIGOCRU AS ARTIGO,
                 PCR.PESO_METROS_PECA AS PESO_PADRAO
            FROM SGTPRD.PESO_PADRAO_PECA PCR
            JOIN SGTPRD.ENGEITEMESTOARTCRU ART0 ON ART0.CDREDUZIDO = PCR.CODIGO_REDUZIDO_PROD
          UNION ALL
          SELECT ART0.CDARTIGOCRU AS ARTIGO,
                 PAC.VLPESO_METROS_PECA AS PESO_PADRAO
            FROM SGTPRD.ENG_PRODG_ACABADO PAC
            JOIN SGTPRD.ITENS_ESTOQUE AGR ON AGR.REDUZIDO_AGRUPADOR = PAC.REDUZIDO_AGRUPADOR
            JOIN SGTPRD.ENGEITEMESTOARTCRU ART0 ON ART0.CDREDUZIDO = AGR.CODIGO_REDUZIDO
         ) BASE
    LEFT JOIN SGTPRD.ENGEITEMESTOARTCRU ART ON ART.CDARTIGOCRU = BASE.ARTIGO
   GROUP BY BASE.ARTIGO, ART.CDREDUZIDO, BASE.PESO_PADRAO
)
SELECT /*+ FIRST_ROWS(10) */
    /* DADOS DA OB */
    OBE.NUMERO_OB AS NR_OB
  , OOO.NR_OF
  , DECODE(OBE.STATUS, 0, 0, 1) AS ST_OB_EM_ABERTO
  , NVL((SELECT O.OBMONTADA FROM SGTPRD.PEDPRODUCAOOB O WHERE O.SETOR = 5 AND O.NUMEROOB = OBE.NUMERO_OB), 0) AS ST_OB_MONTADA
  , (SELECT TRIM(MAX(OBF.CODIGO_PLACA)) FROM SGTPRD.OB_FASES OBF WHERE OBF.NUMERO_OB = OBE.NUMERO_OB) AS NR_KANBAN
  , OBE.TIPO_GERACAO AS TP_GERACAO
  , DECODE(OBE.TIPO_GERACAO, 0, 'PLANO', 1, 'DIVISAO') AS DS_TP_GERACAO
  , OBE.PROGRAMACAO_AUTOMATI AS ST_PROG_AUTOMATICA
  , OBE.BAIXOU_PECAS AS ST_BAIXO_PECA
  , OBE.PRIM_LOTE_PROCESSO AS ST_PRIM_LOTE
  , OBE.STATUS AS ST_OB
  , UPPER(EN_SOB.DESCRICAO) AS DS_ST_OB
  , OBE.TIPO_ORDEM AS TP_ORDEM
  , OBE.CODIGO_FLUXO AS CD_FLUXO
  , OBE.NUMERO_GRUPO_PROGRAM AS NR_GR_PROGRAMACAO
  , (SELECT SEI.SETOR_SEQUENCIA || ' - ' || TRIM(SEI.DESCRICAO)
       FROM SGTPRD.GRUPO_FASES GFA
       JOIN SGTPRD.FASES_FLUXO FFL ON FFL.CODIGO_GRUPO = GFA.CODIGO
       JOIN SGTPRD.SETOR_INDUSTRIAL SEI ON SEI.SETOR_SEQUENCIA = GFA.SETOR_SEQUENCIA
      WHERE FFL.CODIGO_FASE = FAT.CD_FASE_ATUAL) AS DS_SETOR_INDUSTRIAL
  , NVL(TERC.ST_TERCEIROS, 5) AS ST_TERCEIROS
  , NVL(TERC.DS_ST_TERCEIROS, 'SEM TERCEIROS') AS DS_ST_TERCEIROS
  , (SELECT MAX(UFA.CODIGO_UNIDADE_FABRI) || ' - ' || TRIM(UFA.NOME_UNIDADE_FABRIL)
       FROM SGTPRD.OB_FASES VPF
       JOIN SGTPRD.MAQUINA MAQ ON MAQ.NUMERO_MAQUINA = VPF.NUMERO_MAQUINA
       JOIN SGTPRD.GRUPO_MAQUINAS GPR ON GPR.GRUPO = MAQ.GRUPO AND GPR.SETOR = MAQ.SETOR
       JOIN SGTPRD.UNIDADE_FABRIL UFA ON UFA.CODIGO_UNIDADE_FABRI = GPR.UNIDADE_FABRIL
      WHERE VPF.NUMERO_OB = OBE.NUMERO_OB
        AND UFA.EH_FACCAO = 'S'
      GROUP BY UFA.NOME_UNIDADE_FABRIL) AS DS_FACCAO
  , UPPER(EN_TO.DESCRICAO) AS DS_TP_ORDEM
  , OBE.DTINIPRODUCAO AS DT_EMISSAO
  , OBE.DTENCERORDEM AS DT_ENCERRAMENTO
  , OBE.DT_PROGRAMACAO AS DT_PROGRAMACAO
  , OBS_OB.OBS_OB
  , OBE.CODIGO_REDUZIDO AS CD_REDUZIDO
  , TRIM(IAC.CODIGO_ALTERNATIVO) AS CD_ALTERNATIVO
  , SUBSTR(IAC.CODIGO, 4, 5) AS CD_ARTIGO
  , SUBSTR(IAC.CODIGO, 13, 5) AS CD_COR
  , TRIM(COO.DESCRICAO) AS DS_COR
  , COO.TIPOCOR AS TP_COR
  , TRIM(TCO.DESCRICAO) AS DS_TP_COR
  , SUBSTR(IAC.CODIGO,1,3)||'.'||SUBSTR(IAC.CODIGO,4,5)||'.'||SUBSTR(IAC.CODIGO,9,1)||'.'||SUBSTR(IAC.CODIGO,10,3)||'.'||SUBSTR(IAC.CODIGO,13,5)||'.'||SUBSTR(IAC.CODIGO,18,6)||'.'||SUBSTR(IAC.CODIGO,24,2)||'.'||SUBSTR(IAC.CODIGO,26,2) AS CD_INDUSTRIAL
  , TRIM(IAC.DESCRICAO) AS DS_PRODUTO
  , DECODE(TRIM(NV9.CDNIVELGENERICO), 'T', 1, 'R', 2) AS CD_PROCESSO
  , DECODE(TRIM(NV9.CDNIVELGENERICO), 'T', 'TUBULAR', 'R', 'RAMADO') AS DS_PROCESSO
  , OBE.CODIGO_REDUZIDO_CRU AS CD_REDUZIDO_CRU
  , TRIM(ICR.CODIGO_ALTERNATIVO) AS CD_ALTERNATIVO_CRU
  , TRIM(ICR.DESCRICAO) AS DS_PRODUTO_CRU
  , CAST(NVL((SELECT MAX(FFL.PROCESSOTERCEIROS)
                FROM SGTPRD.OB_FASES OBF
                JOIN SGTPRD.FASES_FLUXO FFL ON FFL.CODIGO_FASE = OBF.CODIGO_FASE
               WHERE OBF.NUMERO_OB = OBE.NUMERO_OB), 0) AS NUMBER(10)) AS PROD_EXTERNA
  , (SELECT MAX(MPA.DATA_DOCUMENTO)
       FROM SGTPRD.BD_PRD_MOVPROD MPA
      WHERE MPA.CODIGO = 1
        AND MPA.OPERACAO = 1
        AND MPA.REDUZIDO_ITEM = IAC.CODIGO_REDUZIDO) AS DT_ULT_PROD_ITEM_ACA
  , (SELECT MAX(NFC.DTEMISSAO)
       FROM SGTPRD.NOTAFISCALITENS NFI
       JOIN SGTPRD.NOTAFISCALCAPA NFC ON NFC.ID = NFI.IDNOTAFISCALCAPA
      WHERE NFI.CDREDUZIDO = IAC.CODIGO_REDUZIDO
        AND NFC.STNOTAFATURAMENTO <> 2) AS DT_ULT_FAT_ITEM_ACA
  , CASE WHEN OBE.STATUS = 0 THEN NVL(OBE.DTENCERORDEM - OBE.DTINIPRODUCAO, 0)
         WHEN OBE.STATUS = 1 THEN NVL(SYSDATE - OBE.DTINIPRODUCAO, 0)
         ELSE 0 END AS LEAD_TIME
  , (SELECT TRIM(LPC.DECRICAO)
       FROM SGTPRD.LINHAPRODUTOCOMERCIA LPC
      WHERE LPC.LINHAPRODUTOCOMERCIA = IAC.LINHAPRODUTOCOMERCIA) AS DS_LINHA_COMERCIAL
  , (SELECT TRIM(TO_CHAR(ENG.LARGURA, '999G999G990D00') || ' m')
       FROM SGTPRD.ENG_PRODG_ACABADO ENG
      WHERE ENG.REDUZIDO_AGRUPADOR = IAC.REDUZIDO_AGRUPADOR) AS LARGURA_ACA
  , (SELECT ENG.GRAMATURA || ' g/m²'
       FROM SGTPRD.ENG_PRODG_ACABADO ENG
      WHERE ENG.REDUZIDO_AGRUPADOR = IAC.REDUZIDO_AGRUPADOR) AS GRAMATURA_ACA

    /* DADOS DAS FASES DA OB */
  , OBM.DATA_PRI_CONF AS DT_PRI_CONFIRMACAO
  , OBM.DATA_ULT_CONF AS DT_ULT_CONFIRMACAO
  , CASE WHEN OBM.DATA_ULT_CONF IS NULL THEN NULL ELSE SYSDATE - OBM.DATA_ULT_CONF END AS DIAS_PARADO
  , OBS.OBS_FASE_OB
  , TIN.NR_MAQUINA_TIN
  , TIN.CD_GR_TINGIMENTO
  , TIN.DT_HR_INICIO_TINGIMENTO
  , TIN.DT_HR_FINAL_TINGIMENTO
  , TIN.ST_FASE_TIN
  , TIN.ST_UP_FASE_TIN
  , (SELECT UPPER(SUP.DESCRICAO) FROM ENUM_STATUS_UP SUP WHERE SUP.STATUS = TIN.ST_UP_FASE_TIN) AS DS_ST_UP_FASE_TIN
  , TIN.DURACAO_MIN
  , TIN.RECEITA_PESADA AS ST_REC_PESADA
  , DECODE(TIN.RECEITA_PESADA, 0, 'NAO', 1, 'SIM') AS DS_REC_PESADA
  , TIN.EP
  , TIN.PE
  , TIN.CD_DESTINO_REC
  , TIN.DS_DESTINO_REC
  , NVL(REC.ST_BLOQ_REC, 2) AS ST_BLOQ_REC
  , NVL(REC.DS_BLOQ_REC, 'SEM RECEITA') AS DS_BLOQ_REC
  , FAT.NR_MAQ_FASE_ATUAL
  , FAT.ST_FASE_ATUAL
  , FAT.CD_FASE_ATUAL
  , FAT.DS_ST_FAS_ATUAL
  , FAT.DS_FASE_ATUAL
  , (SELECT F1.DESCRICAO_FASE_2 FROM SGTPRD.FASES_FLUXO F1 WHERE F1.CODIGO_FASE = FAT.CD_FASE_ATUAL) AS DS_FASE_BI

