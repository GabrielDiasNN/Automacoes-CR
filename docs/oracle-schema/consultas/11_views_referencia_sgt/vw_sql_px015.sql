       AND OBF.SEQUENCIA = SGTPRD.PKGBENF0001.FNC_RETORNA_SEQUENCIA_OB(OBE.NUMERO_OB, 0)
       AND OBF.SEQUENCIA <> 0
) FAT ON 1=1

LEFT JOIN LATERAL (
