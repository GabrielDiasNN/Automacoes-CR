              JOIN SGTPRD.ROMANEIO             ROM ON ROM.NUMERO_ROMANEIO = PRS.NUMERO_ROMANEIO_SAID
              JOIN SGTPRD.PRODUTO_ROMANEIO     PR1 ON PR1.NUMERO_ROMANEIO = ROM.NUMERO_ROMANEIO AND PR1.IDPRODUTO_ROMANEIO = PRS.IDPRODUTO_ROMANEIO
             WHERE DOB.NUMERO_OB = OBE.NUMERO_OB
               AND ROM.STATUS IN (0, 1, 3, 8)

            UNION ALL

            SELECT SUM(GGP.QTLIQUIDA) AS QT_ROMANEIO
                 , COUNT(GRR.IDPECASPRODUTO) AS QT_PC_ROMANEIO
              FROM SGTPRD.GERAPECADESTINOOB DBB
              JOIN SGTPRD.GERAPECAROMSAIDA  GRR ON GRR.IDPECASPRODUTO = DBB.IDPECASPRODUTO
              JOIN SGTPRD.ROMANEIO          RMM ON RMM.NUMERO_ROMANEIO = GRR.NUMERO_ROMANEIO_SAID
              JOIN SGTPRD.GERAPECASPRODUTO  GGP ON GGP.IDPECASPRODUTO = GRR.IDPECASPRODUTO
               WHERE DBB.NUMERO_OB = OBE.NUMERO_OB
               AND NOT EXISTS (SELECT 1 FROM SGTPRD.PECAS_ROMANEIO_SAIDA PRS WHERE PRS.IDPECASPRODUTO = GRR.IDPECASPRODUTO)
               AND RMM.STATUS IN (0, 1, 3, 8)
           ) RRRR
