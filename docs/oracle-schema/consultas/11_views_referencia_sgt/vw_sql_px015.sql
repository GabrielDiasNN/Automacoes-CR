              LEFT JOIN SGTPRD.GERAPECACOMPLPECA O4 ON O4.IDPECASPRODUTO = O1.IDPECASPRODUTO
             WHERE O1.NUMERO_OB = OBE.NUMERO_OB) AS QT_CRU_ORIG_OB
         , (SELECT SUM(NVL(O2.QTLIQUIDA, 0))
