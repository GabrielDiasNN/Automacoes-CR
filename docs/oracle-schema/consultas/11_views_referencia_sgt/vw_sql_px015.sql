              LEFT JOIN SGTPRD.GERAPECASPRODUTO O2 ON O2.IDPECASPRODUTO = O1.IDPECASPRODUTO
             WHERE O1.NUMERO_OB = OBE.NUMERO_OB) AS QT_CRU_ATUAL_OB
         , (SELECT COUNT(O2.IDPECASPRODUTO)
