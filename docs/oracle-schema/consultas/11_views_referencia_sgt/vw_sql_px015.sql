             SELECT DISTINCT TO_CHAR(OBQ1E.DESTINO) AS v FROM SGTPRD.OB_QUALIDADE OBQ1E
              WHERE OBQ1E.SEQUENCIA_OB_QUALIDA = (SELECT MAX(OBQ2E.SEQUENCIA_OB_QUALIDA) FROM SGTPRD.OB_QUALIDADE OBQ2E WHERE OBQ2E.NUMERO_OB = OBQ1E.NUMERO_OB AND OBQ2E.SEQUENCIA_FASE <> 0)
                AND OBQ1E.NUMERO_OB = OBE.NUMERO_OB)) AS CD_DESTINO_DEF
         , (SELECT LISTAGG(v, ',' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY v) FROM (
             SELECT DISTINCT TRIM(OBQ1F.USO_ALTERNATIVO) AS v FROM SGTPRD.OB_QUALIDADE OBQ1F
              WHERE OBQ1F.SEQUENCIA_OB_QUALIDA = (SELECT MAX(OBQ2F.SEQUENCIA_OB_QUALIDA) FROM SGTPRD.OB_QUALIDADE OBQ2F WHERE OBQ2F.NUMERO_OB = OBQ1F.NUMERO_OB AND OBQ2F.SEQUENCIA_FASE <> 0)
                AND OBQ1F.NUMERO_OB = OBE.NUMERO_OB)) AS DS_USO_ALTERNATIVO
         , (SELECT LISTAGG(v, ',' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY v) FROM (
             SELECT DISTINCT TO_CHAR(OBQ1G.GRUPO_DEFEITO) AS v FROM SGTPRD.OB_QUALIDADE OBQ1G
              WHERE OBQ1G.SEQUENCIA_OB_QUALIDA = (SELECT MAX(OBQ2G.SEQUENCIA_OB_QUALIDA) FROM SGTPRD.OB_QUALIDADE OBQ2G WHERE OBQ2G.NUMERO_OB = OBQ1G.NUMERO_OB AND OBQ2G.SEQUENCIA_FASE <> 0)
                AND OBQ1G.NUMERO_OB = OBE.NUMERO_OB)) AS GR_DEFEITO
         , (SELECT LISTAGG(v, ',' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY v) FROM (
             SELECT DISTINCT TO_CHAR(OBQ1H.TIPO_DEFEITO) AS v FROM SGTPRD.OB_QUALIDADE OBQ1H
              WHERE OBQ1H.SEQUENCIA_OB_QUALIDA = (SELECT MAX(OBQ2H.SEQUENCIA_OB_QUALIDA) FROM SGTPRD.OB_QUALIDADE OBQ2H WHERE OBQ2H.NUMERO_OB = OBQ1H.NUMERO_OB AND OBQ2H.SEQUENCIA_FASE <> 0)
                AND OBQ1H.NUMERO_OB = OBE.NUMERO_OB)) AS TP_DEFEITO
         , (SELECT LISTAGG(val, ',' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY val) FROM (
             SELECT DISTINCT GDQ.CODIGO_GRUPO || ' - ' || TRIM(GDQ.DESCRICAO_GRUPO) AS val
               FROM SGTPRD.GRUPO_DEFEITO_QUALID GDQ
              WHERE GDQ.CODIGO_GRUPO IN (SELECT DISTINCT OBQ1B.GRUPO_DEFEITO FROM SGTPRD.OB_QUALIDADE OBQ1B
                                           WHERE OBQ1B.SEQUENCIA_OB_QUALIDA = (SELECT MAX(OBQ2B.SEQUENCIA_OB_QUALIDA) FROM SGTPRD.OB_QUALIDADE OBQ2B WHERE OBQ2B.NUMERO_OB = OBQ1B.NUMERO_OB AND OBQ2B.SEQUENCIA_FASE <> 0)
                                             AND OBQ1B.NUMERO_OB = OBE.NUMERO_OB)
            )) AS DS_GR_DEFEITO
         , (SELECT LISTAGG(val, ',' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY val) FROM (
