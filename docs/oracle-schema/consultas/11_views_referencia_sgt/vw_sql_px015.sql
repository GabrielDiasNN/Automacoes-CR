  , NVL(QT1.QT_CRU_PROG_OB, 0) AS QT_CRU_PROG_OB
  , NVL(QT1.QT_PC_CRU_PROG_OB, 0) AS QT_PC_CRU_PROG_OB
  , NVL(QT1.QT_CRU_ORIG_OB, 0) AS QT_CRU_ORIG_OB
  , NVL(QT1.QT_CRU_ATUAL_OB, 0) AS QT_CRU_ATUAL_OB
