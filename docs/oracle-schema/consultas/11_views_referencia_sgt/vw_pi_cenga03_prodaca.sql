          1
         WHEN EPA.UNIMED_DIMENSIONAL = 2 THEN
          100
         WHEN EPA.UNIMED_DIMENSIONAL = 3 THEN
          2.528
         WHEN EPA.UNIMED_DIMENSIONAL = 4 THEN
          1000
         ELSE
          0
