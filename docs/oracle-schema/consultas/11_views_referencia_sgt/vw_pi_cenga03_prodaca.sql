          FROM GRUPO_PRODUTO GPR
         WHERE GPR.NUMERO_GRUPO_PROGRAM = ITE.NUMERO_GRUPO_PROGRAM) CORTE_OURELA, --LEONARDO S. KREUSCH T-89685
