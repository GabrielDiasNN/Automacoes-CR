          (1 - EPA.VARIACAOGRAMATURAMAX / 100)
         WHEN EPA.TIPO_DA_GRAMATURA <> 1 AND ICO.TIPOPRODUTO IN (4,9) AND
              EPA.GRAMATURA <> 0 THEN
          1000 / (EPA.GRAMATURA * 2) * (1 - EPA.VARIACAOGRAMATURAMAX / 100)
         ELSE
          0
       END RENDIMENTO_MIN,
       CASE
         WHEN EPA.TIPO_DA_GRAMATURA = 1 AND ICO.TIPOPRODUTO NOT IN (4,9) AND
              (EPA.GRAMATURA * EPA.LARGURA) <> 0 THEN
          1000 / (EPA.GRAMATURA * EPA.LARGURA) *
          (1 + EPA.VARIACAOGRAMATURAMIN / 100)
