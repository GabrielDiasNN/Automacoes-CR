TABELAS PRINCIPAIS: SGTPRD.FASES_FLUXO, SGTPRD.GERAPECAORIGEMOB, SGTPRD.GERAREQUESTOITEMNOTA, SGTPRD.ITENS_ESTOQUE, SGTPRD.NOTAFISCALCAPA, SGTPRD.NOTAFISCALITENS, SGTPRD.OB_FASES, SGTPRD.OB_PRODUTO, SGTPRD.PECAS_ROMANEIO_SAIDA, SGTPRD.PRODUTO_ROMANEIO, SGTPRD.TERCITEMORDESERVOBFA, SGTPRD.TERCITENSORDEMSERV, SGTPRD.TERCORDEMSERVICO
CUIDADOS OPERACIONAIS: Query operacional do acervo SGT. Execução somente leitura salvo se DML restrito.
