SELECT ROM.NUMERO_ROMANEIO_SAID ROMANEIO,
       NFS.NRNOTA               NOTA_FISCAL,
       SUBSTR(ITE.CODIGO,18,4)||'-'||SUBSTR(ITE.CODIGO,22,4) DESENHO_VARIANTE,
       FFL.DESCRICAO_FASE       DS_FASE_TERCEIRO,
       OBF.CODIGO_FASE          CD_FASE_TERCEIRO,
       OBF.NUMERO_OB            NR_OB,
       OBP.CODPRO_REDUZIDO      CD_RED_ACA,
       ITE.DESCRICAO            DS_PRODUTO,
       ROM.QTDE                 QT_NF,
       --SUBSTR(ITE.CODIGO,18,6)  DESENHO, '000000'
       --SUBSTR(ITE.CODIGO,24,2)  VARIANTE, '00'
       --SUBSTR(ITE.CODIGO,18,6)||'-'||SUBSTR(ITE.CODIGO,24,2) CD_DESENHO_VAR, '000000-00'
       TOS.ID                   NR_OS

FROM   SGTPRD.OB_FASES             OBF
INNER JOIN SGTPRD.FASES_FLUXO          FFL
       ON  FFL.CODIGO_FASE     = OBF.CODIGO_FASE
INNER JOIN SGTPRD.OB_PRODUTO           OBP
       ON  OBP.NUMERO_OB       = OBF.NUMERO_OB
INNER JOIN SGTPRD.ITENS_ESTOQUE        ITE
       ON  ITE.CODIGO_REDUZIDO = OBP.CODPRO_REDUZIDO
INNER JOIN SGTPRD.TERCITEMORDESERVOBFA SOV
       ON  SOV.NUMERO_OB       = OBF.NUMERO_OB
       AND SOV.SEQUENCIA       = OBF.SEQUENCIA
INNER JOIN SGTPRD.TERCITENSORDEMSERV   OSV
       ON  OSV.ID              = SOV.IDTERCITENSORDEMSERV
INNER JOIN SGTPRD.TERCORDEMSERVICO     TOS
       ON  TOS.ID              = OSV.IDTERCORDEMSERVICO
INNER JOIN (
       SELECT ORI.NUMERO_OB, PRS.NUMERO_ROMANEIO_SAID, SUM(PRS.PESO_PECA) QTDE
       FROM  SGTPRD.GERAPECAORIGEMOB ORI
       INNER JOIN SGTPRD.PECAS_ROMANEIO_SAIDA PRS
             ON PRS.IDPECASPRODUTO = ORI.IDPECASPRODUTO
       GROUP BY ORI.NUMERO_OB, PRS.NUMERO_ROMANEIO_SAID
      ) ROM
       ON  ROM.NUMERO_OB       = OBF.NUMERO_OB
INNER JOIN (
       SELECT PRO.NUMERO_ROMANEIO, NFC.NRNOTA
       FROM   SGTPRD.GERAREQUESTOITEMNOTA   GQI
       INNER JOIN SGTPRD.PRODUTO_ROMANEIO       PRO
              ON  PRO.IDPRODUTO_ROMANEIO = GQI.IDPRODUTO_ROMANEIO
       INNER JOIN SGTPRD.NOTAFISCALITENS        NFI
              ON  NFI.ID                 = GQI.IDNOTAFISCALITENS
       INNER JOIN SGTPRD.NOTAFISCALCAPA         NFC
              ON  NFC.ID                 = NFI.IDNOTAFISCALCAPA
       GROUP BY PRO.NUMERO_ROMANEIO, NFC.NRNOTA
      ) NFS
       ON  NFS.NUMERO_ROMANEIO = ROM.NUMERO_ROMANEIO_SAID
WHERE  OBF.STATUS = 3 --EM EXECUÇÃO
AND    FFL.PROCESSOTERCEIROS = '1'
AND    OBF.CODIGO_FASE <> 140

ORDER BY NOTA_FISCAL
