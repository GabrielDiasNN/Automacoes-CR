/* =============================================================================
DIAGNOSTICO - mapeamento de quimicos. Consultas auxiliares, SOMENTE LEITURA.
Nao alimentam os controles. Cada bloco responde uma pergunta de mapeamento.
Resultados observados em 17/10/2026 estao em mapeamento_regras_consumo_quimicos.md.
============================================================================= */

/* D1 - Universo de quimicos do setor de tinturaria (AR_ESTOQUE_QUIMICO) */
SELECT SETOR_FABRIL, CD_GRUPO, CD_SUBGRUPO, DS_SUBGRUPO, CD_CLASSE, DS_CLASSE,
       COUNT(*)         AS QT_ITENS,
       SUM(QT_ESTOQUE)  AS QT_TOTAL
  FROM SGTPRD.AR_ESTOQUE_QUIMICO
 GROUP BY SETOR_FABRIL, CD_GRUPO, CD_SUBGRUPO, DS_SUBGRUPO, CD_CLASSE, DS_CLASSE
 ORDER BY QT_ITENS DESC;

/* D2 - Consumo real e receitas por mes (pesagem confirmada = MOVCONFIRMADO 1 e STATUSPESAGEMRECEITA 3) */
SELECT TRUNC(R.DT_CONFIRMACAO, 'MM')                              AS MES,
       COUNT(*)                                                    AS LINHAS,
       COUNT(DISTINCT R.NUMEROORDEM || '-' || R.SEQUENCIAFASEOB)   AS PARTIDAS,
       COUNT(DISTINCT R.CODINSREDUZIDO)                            AS INSUMOS,
       ROUND(SUM(R.QUANTIDADEPESADA), 2)                           AS KG_REAL
  FROM SGTPRD.MOVTO_RECEITA R
 WHERE R.DT_CONFIRMACAO >= ADD_MONTHS(TRUNC(SYSDATE), -6)
   AND R.MOVCONFIRMADO = 1
   AND R.STATUSPESAGEMRECEITA = 3
 GROUP BY TRUNC(R.DT_CONFIRMACAO, 'MM')
 ORDER BY MES;

/* D3 - Combinacao de flags de MOVTO_RECEITA: define o criterio de consumo real.
   Achado: PESADA = 0 com STATUS 3 ja tem kg, entao PESADA nao e confiavel sozinho. */
SELECT PESADA, MOVCONFIRMADO, STATUSPESAGEMRECEITA, REGISTROBAIXAESTOQUE,
       COUNT(*)                  AS QT,
       ROUND(SUM(QUANTIDADEPESADA), 2) AS KG_PESADO,
       ROUND(SUM(QUANTIDADE), 2)       AS KG_QUANTIDADE
  FROM SGTPRD.MOVTO_RECEITA
 WHERE DT_EMISSAO >= ADD_MONTHS(TRUNC(SYSDATE), -12)
 GROUP BY PESADA, MOVCONFIRMADO, STATUSPESAGEMRECEITA, REGISTROBAIXAESTOQUE
 ORDER BY QT DESC;

/* D4 - Teste da formula percentual: QUANTIDADE = CONSUMO_UNITARIO * KILOS_PRODUZIDOS / 100.
   Mede a fracao de lancamentos que bate, por FATORCALCULO. Resultado parcial (~50%). */
WITH B AS (
    SELECT R.QUANTIDADE, R.CONSUMO_UNITARIO AS U, R.FATORCALCULO AS F, OBF.KILOS_PRODUZIDOS AS KG
      FROM SGTPRD.MOVTO_RECEITA R
      JOIN SGTPRD.OB_FASES OBF
        ON OBF.NUMEROORDEMMOVIMENTO = R.NUMEROORDEM
       AND OBF.SEQUENCIAORDEMMOVIME = R.SEQUENCIAFASEOB
     WHERE R.DT_CONFIRMACAO >= ADD_MONTHS(TRUNC(SYSDATE), -3)
       AND R.MOVCONFIRMADO = 1
       AND R.STATUSPESAGEMRECEITA = 3
       AND OBF.KILOS_PRODUZIDOS > 0
       AND R.CONSUMO_UNITARIO > 0
)
SELECT F,
       COUNT(*)                                                                       AS QT,
       SUM(CASE WHEN ABS(QUANTIDADE - U * KG / 100) <= 0.001 + 0.0005 * ABS(QUANTIDADE)
                THEN 1 ELSE 0 END)                                                    AS QT_BATE_PCT_KG
  FROM B
 GROUP BY F
 ORDER BY F;

/* D5 - Estoque por deposito dos quimicos (VW_ESTO_SALDO). Verifica se reserva ja esta descontada. */
SELECT S.CODIGO_DEPOSITO,
       COUNT(DISTINCT S.CD_REDUZIDO)  AS QT_PRODUTOS,
       SUM(S.QT_SALDO)                AS SALDO,
       SUM(S.QT_ESTOQUE_DISP)         AS DISPONIVEL,
       SUM(S.QT_PED_ABERTO)           AS PED_ABERTO,
       SUM(CASE WHEN S.QT_SALDO <> S.QT_ESTOQUE_DISP THEN 1 ELSE 0 END) AS LINHAS_SALDO_DIFERENTE_DISP
  FROM SGTPRD.VW_ESTO_SALDO S
 WHERE S.CD_REDUZIDO IN (SELECT CD_REDUZIDO FROM SGTPRD.AR_ESTOQUE_QUIMICO)
 GROUP BY S.CODIGO_DEPOSITO
 ORDER BY S.CODIGO_DEPOSITO;

/* D6 - Unidade de estoque dos quimicos (ITENS_ESTOQUE -> UNIDADE_MEDIDA) */
SELECT U.DSSIGLA AS UNIDADE, COUNT(*) AS QT_ITENS
  FROM SGTPRD.ITENS_ESTOQUE ITE
  LEFT JOIN SGTPRD.UNIDADE_MEDIDA U ON U.IDUNIDADEMEDIDA = ITE.IDUNIDADEMEDIDA
 WHERE ITE.CODIGO_REDUZIDO IN (SELECT CD_REDUZIDO FROM SGTPRD.AR_ESTOQUE_QUIMICO)
 GROUP BY U.DSSIGLA
 ORDER BY QT_ITENS DESC;

/* D7 - Compras pendentes por insumo quimico. Achado: PRAZOENTREGA e 0 em todas as linhas. */
SELECT COUNT(*)                                                   AS QT_LINHAS,
       SUM(CASE WHEN I.PRAZOENTREGA > 0 THEN 1 ELSE 0 END)        AS COM_PRAZO,
       SUM(CASE WHEN E.DATAENTREGA < TO_NUMBER(TO_CHAR(SYSDATE, 'YYYYMMDD')) THEN 1 ELSE 0 END) AS ENTREGA_VENCIDA_LINHAS
  FROM SGTPRD.ENTREGAS_PEDIDO_COMP E
  JOIN SGTPRD.ITENS_PEDIDO_COMPRA I ON I.ID = E.IDITENSPEDIDOCOMPRA
 WHERE E.QTDPEDIDA > NVL(E.QTDRECEBIDA, 0)
   AND I.CODINSREDUZIDO IN (SELECT CD_REDUZIDO FROM SGTPRD.AR_ESTOQUE_QUIMICO);

/* D8 - Status dos pedidos de compra com entrega pendente. O significado de STATUS ainda NAO esta confirmado. */
SELECT P.STATUS, P.TIPO, COUNT(DISTINCT P.ID) AS QT_PEDIDOS
  FROM SGTPRD.PEDIDO_COMPRA P
  JOIN SGTPRD.ITENS_PEDIDO_COMPRA I ON I.IDPEDIDOCOMPRA = P.ID
  JOIN SGTPRD.ENTREGAS_PEDIDO_COMP E ON E.IDITENSPEDIDOCOMPRA = I.ID
 WHERE E.QTDPEDIDA > NVL(E.QTDRECEBIDA, 0)
 GROUP BY P.STATUS, P.TIPO
 ORDER BY QT_PEDIDOS DESC;

/* D9 - Caminho de movimentacao de estoque de consumo (CUSTMOVICONSUMOQUIM liga a GERAMOVIMENTOESTOQUE).
   Serve para comparar baixa de estoque com consumo na maquina. Nao usar como consumo real. */
SELECT COUNT(*) AS QT_LINHAS, MIN(DATA_ORIGINAL) AS DATA_MIN, MAX(DATA_NOVA) AS DATA_NOVA_MAX
  FROM SGTPRD.CUSTMOVICONSUMOQUIM;
